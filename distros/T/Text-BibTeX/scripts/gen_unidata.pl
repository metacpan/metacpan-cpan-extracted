#!/usr/bin/env perl
# Generate src/unidata.h: the Unicode character classes and case
# mappings used by src/unicode.c.
#
# The tables come from the Unicode database of the perl that runs this
# script (via Unicode::UCD), so the C library always agrees with the perl
# it is built for.  Build.PL runs this automatically.

use 5.026;
use strict;
use warnings;
use feature 'fc';
use Unicode::UCD qw(prop_invlist);

my $out = shift // 'src/unidata.h';

sub invlist {
   my ($name, @props) = @_;
   # Union of the inversion lists of @props
   my %in;
   for my $prop (@props) {
      my @list = prop_invlist($prop);
      die "unknown property $prop" unless @list;
      for (my $i = 0; $i < @list; $i += 2) {
         my $end = $i + 1 < @list ? $list[$i + 1] : 0x110000;
         $in{$_} = 1 for $list[$i] .. $end - 1;
      }
   }
   # Back to an inversion list: start of each range, then one past its end
   my @cps = sort { $a <=> $b } keys %in;
   my @inv;
   for my $i (0 .. $#cps) {
      push @inv, $cps[$i] if $i == 0 || $cps[$i] != $cps[$i - 1] + 1;
      push @inv, $cps[$i] + 1 if $i == $#cps || $cps[$i + 1] != $cps[$i] + 1;
   }
   my @rows;
   my @rest = @inv;
   while (my @c = splice @rest, 0, 16) {
      push @rows, '   ' . join(', ', map { sprintf '0x%05X', $_ } @c);
   }
   return "static const unsigned long ${name}[] =\n{\n" . join(",\n", @rows)
      . "\n};\n#define ${name}_LEN " . scalar(@inv) . "\n\n";
}

sub casemap {
   my ($name, $prop, $func) = @_;
   my @list = prop_invlist($prop);
   my @rows;
   for (my $i = 0; $i < @list; $i += 2) {
      my $end = $i + 1 < @list ? $list[$i + 1] : 0x110000;
      for my $cp ($list[$i] .. $end - 1) {
         next if $cp < 0x80;            # ASCII is handled inline
         my @m = map { ord } split //, $func->(chr $cp);
         next if @m == 1 && $m[0] == $cp;
         die sprintf("mapping of U+%04X too long", $cp) if @m > 3;
         push @m, 0 while @m < 3;
         push @rows, sprintf '   { 0x%05X, { 0x%05X, 0x%05X, 0x%05X } }', $cp, @m;
      }
   }
   return "static const bt_casemap_entry ${name}[] =\n{\n" . join(",\n", @rows)
      . "\n};\n#define ${name}_LEN " . scalar(@rows) . "\n\n";
}

my $h = <<"END";
/* Generated by scripts/gen_unidata.pl from the Unicode ${\ Unicode::UCD::UnicodeVersion()}
 * database of perl $^V.  Do not edit. */

#ifndef BT_UNIDATA_H
#define BT_UNIDATA_H

#define BT_UNICODE_VERSION "${\ Unicode::UCD::UnicodeVersion()}"

typedef struct
{
   unsigned long cp;
   unsigned long map[3];
} bt_casemap_entry;

END

$h .= invlist('bt_uni_lower_inv', 'General_Category=Ll');
$h .= invlist('bt_uni_alpha_inv', 'Alphabetic');
$h .= invlist('bt_uni_alnum_inv', 'Alphabetic', 'General_Category=Nd');
$h .= invlist('bt_uni_extend_inv', 'Grapheme_Cluster_Break=Extend',
              'Grapheme_Cluster_Break=SpacingMark', 'Grapheme_Cluster_Break=ZWJ');
$h .= casemap('bt_uni_lc_map', 'Changes_When_Lowercased', sub { lc $_[0] });
$h .= casemap('bt_uni_uc_map', 'Changes_When_Uppercased', sub { uc $_[0] });
$h .= casemap('bt_uni_tc_map', 'Changes_When_Titlecased', sub { ucfirst $_[0] });
$h .= casemap('bt_uni_fc_map', 'Changes_When_Casefolded', sub { fc $_[0] });
$h .= "#endif /* BT_UNIDATA_H */\n";

open my $fh, '>', "$out.tmp" or die "$out.tmp: $!";
print $fh $h;
close $fh or die "$out.tmp: $!";
rename "$out.tmp", $out or die "rename $out: $!";
