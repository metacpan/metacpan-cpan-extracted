=head2 Google::Cloud::Dialogflow::V2beta1::Session::EventInput

Events allow for matching intents by event name instead of the natural
language input. For instance, input `<event: { name: "welcome_event",
parameters: { name: "Sam" } }>` can trigger a personalized welcome response.
The parameter `name` may be used by the agent in the response:
`"Hello #welcome_event.name! What can I do for you today?"`.

Inherits from L<Protobuf::Message>.

=head3 Accessors

=over 4

=item * C<< $msg->name() >> / C<< $msg->name($value) >>

Type: C<String>

Required. The unique identifier of the event.

=item * C<< $msg->parameters() >> / C<< $msg->parameters($value) >>

Type: C<Message> (L<Google::Protobuf::Struct::Struct>)

The collection of parameters associated with the event.

Depending on your protocol or client library language, this is a
map, associative array, symbol table, dictionary, or JSON object
composed of a collection of (MapKey, MapValue) pairs:

* MapKey type: string
* MapKey value: parameter name
* MapValue type: If parameter's entity type is a composite entity then use
map, otherwise, depending on the parameter value type, it could be one of
string, number, boolean, null, list or map.
* MapValue value: If parameter's entity type is a composite entity then use
map from composite entity property names to property values, otherwise,
use parameter value.

=item * C<< $msg->language_code() >> / C<< $msg->language_code($value) >>

Type: C<String>

Required. The language of this query. See [Language
Support](https://cloud.google.com/dialogflow/docs/reference/language)
for a list of the currently supported language codes. Note that queries in
the same session do not necessarily need to specify the same language.

This field is ignored when used in the context of a
[WebhookResponse.followup_event_input][google.cloud.dialogflow.v2beta1.WebhookResponse.followup_event_input]
