use strict;
use warnings;
use Alien::TDLib;

my $header = Alien::TDLib->dist_dir . '/include/td/telegram/td_api.h';
open my $h, '<', $header or die "$header: $!";
my $src = do { local $/; <$h> };
close $h;

my %fn;
while ($src =~ /^class (\w+) final : public Function \{(.*?)^\};/msg) {
    my ($name, $body) = ($1, $2);
    my @args;
    push @args, $1 while $body =~
        /^\s{2}(?!static|explicit|void|std::int32_t ID)[\w:<>,\s\*]+?\s+(\w+)_;\s*$/mg;
    $fn{$name} = "@args";
}

# Every class, its base, and the DECLARED TYPE of each member. This is what lets
# xt/schema_slots.t reject an @type that exists but is wrong for the slot it sits
# in -- the shape of both bugs found in the 0.03 review.
my (%base, %slot);
while ($src =~ /^class (\w+) (?:final )?: public (\w+) \{(.*?)^\};/msg) {
    my ($name, $parent, $body) = ($1, $2, $3);
    $base{$name} = $parent;
    while ($body =~ /^\s{2}(?!static|explicit|void|std::int32_t ID)
                     ([\w:<>,\s\*]+?)\s+(\w+)_;\s*$/mgx) {
        my ($type, $field) = ($1, $2);
        $type =~ s/std:://g; $type =~ s/\s+//g; $type =~ s/&&$//;
        # a class body opens with 'public:' on its own line, and the type
        # pattern spans newlines, so the FIRST member of every class picks
        # it up and would otherwise be dropped from the table
        $type =~ s/\Apublic://;
        # object_ptr<X> and array<object_ptr<X>> are the only shapes that carry
        # a nested @type; everything else is a scalar we do not police
        if    ($type =~ /\Aarray<object_ptr<(\w+)>>\z/) { $slot{$name}{$field} = "array:$1" }
        elsif ($type =~ /\Aobject_ptr<(\w+)>\z/)        { $slot{$name}{$field} = $1 }
    }
}
die "only ${\ scalar keys %fn} functions parsed from $header\n" unless keys %fn > 500;

my $version = Alien::TDLib->version // 'unknown';

# taken from the main module, not written by hand: a literal here would
# silently revert Schema.pm to an older version on the next regeneration,
# and nothing checks that the shipped modules agree
my $dist_version = do {
    open my $m, '<', 'lib/EV/Telegram/TDLib.pm' or die "main module: $!";
    my ($v) = grep { /our \$VERSION = / } <$m>;
    $v =~ /'([^']+)'/ or die "cannot read the dist version\n";
    $1;
};

my $out = 'lib/EV/Telegram/TDLib/Schema.pm';
open my $o, '>', $out or die "$out: $!";
print $o <<"HEAD";
package EV::Telegram::TDLib::Schema;

use strict;
use warnings;

our \$VERSION = '$dist_version';

# Generated by author/gen-schema.pl from the td_api.h that Alien::TDLib
# ships. Do not edit; regenerate instead.

our \$TDLIB_VERSION = '$version';

=head1 NAME

EV::Telegram::TDLib::Schema - the pinned TDLib schema tables

=head1 DESCRIPTION

Generated from the C<td_api.h> that L<Alien::TDLib> ships, and loaded by
L<EV::Telegram::TDLib> to check a request before it is sent. It holds
C<%FUNCTIONS> (function name to its field names), C<%CLASS_BASE> (class
to base class) and C<%CLASS_SLOTS>, plus C<\$TDLIB_VERSION>, the TDLib
release they came from.

Nothing here is API: the tables track whatever TDLib the module was
built against, and are regenerated rather than edited.

=cut

our %FUNCTIONS = (
HEAD
printf $o "    %-44s => '%s',\n", $_, $fn{$_} for sort keys %fn;
print $o ");\n\nour %CLASS_BASE = (\n";
printf $o "    %-46s => '%s',\n", $_, $base{$_} for sort keys %base;
print $o ");\n\nour %CLASS_SLOTS = (\n";
for my $c (sort keys %slot) {
    next unless keys %{ $slot{$c} };
    printf $o "    %-46s => { %s },\n", $c,
        join ', ', map { "$_ => '$slot{$c}{$_}'" } sort keys %{ $slot{$c} };
}
print $o ");\n\n1;\n";

close $o;

printf "wrote %s: %d functions, TDLib %s\n", $out, scalar keys %fn, $version;
