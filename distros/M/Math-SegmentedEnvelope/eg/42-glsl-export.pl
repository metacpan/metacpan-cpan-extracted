#!/usr/bin/env perl
# GLSL export: generate GPU shader functions from envelopes
# Useful for game devs who design curves in Perl then embed in shaders
use strict;
use warnings;
use Math::SegmentedEnvelope qw(adsr perc env spline);

# ADSR for amplitude
my $amp = adsr(0.01, 0.1, 0.7, 0.3, morpher_formula => 'smoothstep');

# Filter sweep
my $filter = adsr(0.005, 0.3, 0.4, 0.5,
    peak => 1.0, attack_curve => 3,
    morpher_formula => 'cubic_out');

# Bounce easing
my $bounce = env([[0, 1], [1], [1]], morpher_formula => 'bounce_out');

# Spline path
my $path = spline([0, 0.3, 0.7, 1.0], [0, 1, 0.2, 0.8]);

print "// Generated by Math::SegmentedEnvelope\n";
print "// Paste into your fragment/vertex shader\n\n";

# Export each with different sample counts
print $amp->to_glsl(name => 'ampEnvelope', samples => 32);
print "\n";
print $filter->to_glsl(name => 'filterSweep', samples => 32);
print "\n";
print $bounce->to_glsl(name => 'bounceEase', samples => 48);
print "\n";
print $path->to_glsl(name => 'splinePath', samples => 24);

# Example shader using the envelopes
print <<'GLSL';

// Example usage in a fragment shader:
//
// uniform float u_time;
// uniform float u_note_on_time;
//
// void main() {
//     float t = u_time - u_note_on_time;
//     float amp = ampEnvelope(t);
//     float brightness = filterSweep(t);
//     float ease = bounceEase(clamp(t / 0.5, 0.0, 1.0));
//
//     vec3 color = vec3(brightness, brightness * 0.7, brightness * 0.3);
//     gl_FragColor = vec4(color * amp, 1.0);
// }

GLSL

# Show the generated function size
for my $pair (['amp', $amp, 32], ['filter', $filter, 32],
              ['bounce', $bounce, 48], ['path', $path, 24]) {
    my ($name, $e, $n) = @$pair;
    my $glsl = $e->to_glsl(samples => $n);
    printf "// %s: %d samples, %d bytes of GLSL\n", $name, $n, length($glsl);
}
