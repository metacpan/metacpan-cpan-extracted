#!/usr/bin/env perl
# Lathe mesh: revolve an envelope profile around Y axis to create a 3D mesh
# Exports to OBJ and STL, then renders via OpenGL::Modern with geometry shader
#
# The envelope defines the radius at each height — like a potter's wheel profile.
# Different envelopes create vases, bottles, bells, horns, etc.
#
# Requires: OpenGL::Modern, OpenGL::GLUT, OpenGL::Array
use strict;
use warnings;

BEGIN {
    eval { require OpenGL::Modern; OpenGL::Modern->import(':all'); 1 }
        or die "This example requires OpenGL::Modern\n";
    eval { require OpenGL::GLUT; OpenGL::GLUT->import(':all'); 1 }
        or die "This example requires OpenGL::GLUT\n";
    eval { require OpenGL::Array; 1 }
        or die "This example requires OpenGL::Array\n";
}

use Math::SegmentedEnvelope qw(adsr perc spline env);
use Time::HiRes qw(time);
use POSIX qw(floor tan);

my $W = 800;
my $H = 600;
my $PI = 3.14159265358979323846;

# Envelope profiles: radius as function of height [0,1]
my @profiles = (
    { name => 'Vase',
      env => spline([0, 0.05, 0.15, 0.4, 0.6, 0.85, 0.95, 1.0],
                    [0.3, 0.35, 0.5, 0.2, 0.15, 0.4, 0.45, 0.42]) },
    { name => 'Bell',
      env => env([[0.5, 0.5, 0.3, 0.05, 0.02],
                  [0.1, 0.3, 0.4, 0.2], [1, -3, -2, 1]]) },
    { name => 'Wine Glass',
      env => spline([0, 0.05, 0.1, 0.12, 0.5, 0.52, 0.7, 0.9, 1.0],
                    [0.3, 0.32, 0.25, 0.03, 0.03, 0.05, 0.25, 0.35, 0.35]) },
    { name => 'Horn',
      env => env([[0.4, 0.3, 0.15, 0.05, 0.02],
                  [0.3, 0.3, 0.2, 0.2], [-2, -2, -2, -1]],
                 morpher_formula => 'cubic_out') },
    { name => 'Bottle',
      env => spline([0, 0.1, 0.5, 0.6, 0.65, 0.8, 0.85, 1.0],
                    [0.25, 0.3, 0.3, 0.25, 0.08, 0.08, 0.1, 0.1]) },
);

my $current = 0;
my $slices = 48;    # around Y axis
my $stacks = 64;    # along height

sub generate_mesh {
    my ($profile) = @_;
    my $env = $profile->{env};
    my $s = $env->static;
    my $dur = $env->duration;

    my (@verts, @normals, @indices);

    # Generate vertices on surface of revolution
    for my $j (0 .. $stacks) {
        my $t = $j / $stacks;
        my $y = $t;
        my $r = $s->($t * $dur);

        for my $i (0 .. $slices - 1) {
            my $theta = $i / $slices * 2 * $PI;
            my $x = cos($theta) * $r;
            my $z = sin($theta) * $r;
            push @verts, $x, $y, $z;

            # Approximate normal via finite difference
            my $r_prev = $s->(($t > 0.01 ? $t - 0.01 : 0) * $dur);
            my $r_next = $s->(($t < 0.99 ? $t + 0.01 : 1) * $dur);
            my $dr = ($r_next - $r_prev) / 0.02;
            # Tangent along profile: (dr, 1, 0), normal is perpendicular
            my $nx = cos($theta);
            my $nz = sin($theta);
            my $ny = -$dr;
            my $nl = sqrt($nx*$nx + $ny*$ny + $nz*$nz) || 1;
            push @normals, $nx/$nl, $ny/$nl, $nz/$nl;
        }
    }

    # Generate triangle indices
    for my $j (0 .. $stacks - 1) {
        for my $i (0 .. $slices - 1) {
            my $i2 = ($i + 1) % $slices;
            my $a = $j * $slices + $i;
            my $b = $j * $slices + $i2;
            my $c = ($j + 1) * $slices + $i;
            my $d = ($j + 1) * $slices + $i2;
            push @indices, $a, $c, $b, $b, $c, $d;
        }
    }

    return (\@verts, \@normals, \@indices);
}

# Export to OBJ
sub export_obj {
    my ($verts, $normals, $indices, $file) = @_;
    open my $fh, '>', $file or die "Cannot write $file: $!";
    print $fh "# Generated by Math::SegmentedEnvelope lathe\n";
    for (my $i = 0; $i < @$verts; $i += 3) {
        printf $fh "v %.6f %.6f %.6f\n", $verts->[$i], $verts->[$i+1], $verts->[$i+2];
    }
    for (my $i = 0; $i < @$normals; $i += 3) {
        printf $fh "vn %.6f %.6f %.6f\n", $normals->[$i], $normals->[$i+1], $normals->[$i+2];
    }
    for (my $i = 0; $i < @$indices; $i += 3) {
        my ($a, $b, $c) = ($indices->[$i]+1, $indices->[$i+1]+1, $indices->[$i+2]+1);
        printf $fh "f %d//%d %d//%d %d//%d\n", $a,$a, $b,$b, $c,$c;
    }
    close $fh;
    printf "Exported %s: %d verts, %d tris\n", $file,
        scalar(@$verts)/3, scalar(@$indices)/3;
}

# Export to binary STL
sub export_stl {
    my ($verts, $normals, $indices, $file) = @_;
    open my $fh, '>', $file or die "Cannot write $file: $!";
    binmode $fh;
    print $fh "\0" x 80;  # header
    my $num_tris = scalar(@$indices) / 3;
    print $fh pack('V', $num_tris);
    for (my $i = 0; $i < @$indices; $i += 3) {
        my @tri;
        for my $vi ($indices->[$i], $indices->[$i+1], $indices->[$i+2]) {
            push @tri, @{$verts}[$vi*3 .. $vi*3+2];
        }
        # Face normal from cross product
        my @e1 = ($tri[3]-$tri[0], $tri[4]-$tri[1], $tri[5]-$tri[2]);
        my @e2 = ($tri[6]-$tri[0], $tri[7]-$tri[1], $tri[8]-$tri[2]);
        my @n = ($e1[1]*$e2[2]-$e1[2]*$e2[1],
                 $e1[2]*$e2[0]-$e1[0]*$e2[2],
                 $e1[0]*$e2[1]-$e1[1]*$e2[0]);
        my $nl = sqrt($n[0]**2 + $n[1]**2 + $n[2]**2) || 1;
        print $fh pack('f3', map { $_ / $nl } @n);       # normal
        print $fh pack('f3', @tri[0..2]);                  # vertex 1
        print $fh pack('f3', @tri[3..5]);                  # vertex 2
        print $fh pack('f3', @tri[6..8]);                  # vertex 3
        print $fh pack('v', 0);                            # attribute
    }
    close $fh;
    printf "Exported %s: %d tris, %d bytes\n", $file, $num_tris, -s $file;
}

# OpenGL rendering
my $vert_src = <<'GLSL';
#version 150
in vec3 aPos;
in vec3 aNormal;
out VS_OUT { vec3 normal; vec3 worldPos; } vs_out;
uniform mat4 uMVP;
void main() {
    vs_out.normal = aNormal;
    vs_out.worldPos = aPos;
    gl_Position = uMVP * vec4(aPos, 1.0);
}
GLSL

my $geom_src = <<'GLSL';
#version 150
layout(triangles) in;
layout(triangle_strip, max_vertices = 3) out;
in VS_OUT { vec3 normal; vec3 worldPos; } gs_in[];
out vec4 frag_color;
uniform float uTime;
uniform vec3 uColor;

void main() {
    // Flat shading
    vec3 e1 = gs_in[1].worldPos - gs_in[0].worldPos;
    vec3 e2 = gs_in[2].worldPos - gs_in[0].worldPos;
    vec3 fn = normalize(cross(e1, e2));

    vec3 light = normalize(vec3(sin(uTime*0.3), 0.8, cos(uTime*0.3)));
    float diff = max(dot(fn, light), 0.0);

    for (int i = 0; i < 3; i++) {
        gl_Position = gl_in[i].gl_Position;
        vec3 col = uColor * (0.25 + diff * 0.75);
        // Rim highlight
        float rim = 1.0 - max(dot(fn, normalize(vec3(0,0,1))), 0.0);
        col += vec3(0.3, 0.3, 0.4) * pow(rim, 3.0) * 0.5;
        frag_color = vec4(col, 1.0);
        EmitVertex();
    }
    EndPrimitive();
}
GLSL

my $frag_src = <<'GLSL';
#version 150
in vec4 frag_color;
out vec4 outColor;
void main() { outColor = frag_color; }
GLSL

my ($prog, $u_mvp, $u_time, $u_color, $vao, $vbo_v, $vbo_n, $ibo, $num_idx);
my $start;

sub compile_shader {
    my ($type, $src) = @_;
    my $s = glCreateShader($type);
    glShaderSource_p($s, $src);
    glCompileShader($s);
    my ($ok) = glGetShaderiv_p($s, GL_COMPILE_STATUS);
    die "Shader: " . glGetShaderInfoLog_p($s) unless $ok;
    return $s;
}

sub mat4_perspective {
    my ($fov, $aspect, $near, $far) = @_;
    my $f = 1 / tan($fov * $PI / 360);
    my @m = (0) x 16;
    $m[0]=$f/$aspect; $m[5]=$f; $m[10]=($far+$near)/($near-$far);
    $m[11]=-1; $m[14]=2*$far*$near/($near-$far);
    return @m;
}

sub mat4_lookat {
    my ($ex,$ey,$ez,$cx,$cy,$cz,$ux,$uy,$uz) = @_;
    my @f=($cx-$ex,$cy-$ey,$cz-$ez);
    my $fl=sqrt($f[0]**2+$f[1]**2+$f[2]**2); @f=map{$_/$fl}@f;
    my @s=($f[1]*$uz-$f[2]*$uy,$f[2]*$ux-$f[0]*$uz,$f[0]*$uy-$f[1]*$ux);
    my $sl=sqrt($s[0]**2+$s[1]**2+$s[2]**2); @s=map{$_/$sl}@s;
    my @u=($s[1]*$f[2]-$s[2]*$f[1],$s[2]*$f[0]-$s[0]*$f[2],$s[0]*$f[1]-$s[1]*$f[0]);
    return($s[0],$u[0],-$f[0],0,$s[1],$u[1],-$f[1],0,$s[2],$u[2],-$f[2],0,
        -($s[0]*$ex+$s[1]*$ey+$s[2]*$ez),-($u[0]*$ex+$u[1]*$ey+$u[2]*$ez),
        $f[0]*$ex+$f[1]*$ey+$f[2]*$ez,1);
}

sub mat4_mult {
    my($a,$b)=@_; my @r=(0)x16;
    for my $i(0..3){for my $j(0..3){for my $k(0..3){$r[$j*4+$i]+=$a->[$k*4+$i]*$b->[$j*4+$k]}}}
    return @r;
}

sub upload_mesh {
    my ($verts, $normals, $indices) = @_;

    ($vao) = glGenVertexArrays_p(1);
    glBindVertexArray($vao);

    ($vbo_v) = glGenBuffers_p(1);
    glBindBuffer(GL_ARRAY_BUFFER, $vbo_v);
    my $v = OpenGL::Array->new_list(GL_FLOAT, @$verts);
    glBufferData_c(GL_ARRAY_BUFFER, $v->length, $v->ptr, GL_STATIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer_c(0, 3, GL_FLOAT, GL_FALSE, 0, 0);

    ($vbo_n) = glGenBuffers_p(1);
    glBindBuffer(GL_ARRAY_BUFFER, $vbo_n);
    my $n = OpenGL::Array->new_list(GL_FLOAT, @$normals);
    glBufferData_c(GL_ARRAY_BUFFER, $n->length, $n->ptr, GL_STATIC_DRAW);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer_c(1, 3, GL_FLOAT, GL_FALSE, 0, 0);

    ($ibo) = glGenBuffers_p(1);
    glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, $ibo);
    my $ix = OpenGL::Array->new_list(GL_UNSIGNED_INT, @$indices);
    glBufferData_c(GL_ELEMENT_ARRAY_BUFFER, $ix->length, $ix->ptr, GL_STATIC_DRAW);
    $num_idx = scalar @$indices;

    glBindVertexArray(0);
}

sub init_gl {
    my $vs = compile_shader(GL_VERTEX_SHADER, $vert_src);
    my $gs = compile_shader(GL_GEOMETRY_SHADER, $geom_src);
    my $fs = compile_shader(GL_FRAGMENT_SHADER, $frag_src);
    $prog = glCreateProgram();
    glAttachShader($prog, $_) for ($vs, $gs, $fs);
    glBindAttribLocation($prog, 0, 'aPos');
    glBindAttribLocation($prog, 1, 'aNormal');
    glLinkProgram($prog);
    my ($ok) = glGetProgramiv_p($prog, GL_LINK_STATUS);
    die "Link: ".glGetProgramInfoLog_p($prog) unless $ok;
    glDeleteShader($_) for ($vs, $gs, $fs);
    $u_mvp = glGetUniformLocation($prog, 'uMVP');
    $u_time = glGetUniformLocation($prog, 'uTime');
    $u_color = glGetUniformLocation($prog, 'uColor');

    glEnable(GL_DEPTH_TEST);

    my ($v, $n, $i) = generate_mesh($profiles[$current]);
    upload_mesh($v, $n, $i);

    # Export files
    export_obj($v, $n, $i, "/tmp/envelope_$profiles[$current]{name}.obj");
    export_stl($v, $n, $i, "/tmp/envelope_$profiles[$current]{name}.stl");

    $start = time();
}

my @colors = ([0.8,0.5,0.3], [0.7,0.7,0.8], [0.4,0.7,0.5], [0.9,0.6,0.2], [0.5,0.6,0.9]);

sub display {
    my $t = time() - $start;

    # Cycle shapes every 5s
    my $new = int($t / 5) % scalar @profiles;
    if ($new != $current) {
        $current = $new;
        my ($v, $n, $i) = generate_mesh($profiles[$current]);
        glDeleteVertexArrays_p($vao) if $vao;
        glDeleteBuffers_p($vbo_v) if $vbo_v;
        glDeleteBuffers_p($vbo_n) if $vbo_n;
        glDeleteBuffers_p($ibo) if $ibo;
        upload_mesh($v, $n, $i);
    }

    glClearColor(0.08, 0.08, 0.12, 1);
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
    glUseProgram($prog);

    my $a = $t * 0.4;
    my @proj = mat4_perspective(40, $W/$H, 0.01, 10);
    my @view = mat4_lookat(cos($a)*1.5, 0.7, sin($a)*1.5, 0,0.45,0, 0,1,0);
    my @mvp = mat4_mult(\@proj, \@view);
    my $m = OpenGL::Array->new_list(GL_FLOAT, @mvp);
    glUniformMatrix4fv_c($u_mvp, 1, GL_FALSE, $m->ptr);
    glUniform1f($u_time, $t);
    my $c = $colors[$current % @colors];
    glUniform3f($u_color, $c->[0], $c->[1], $c->[2]);

    glBindVertexArray($vao);
    glDrawElements_c(GL_TRIANGLES, $num_idx, GL_UNSIGNED_INT, 0);
    glBindVertexArray(0);

    glutSwapBuffers();
}

sub idle { glutPostRedisplay() }
sub keyboard { exit(0) if ord($_[0]) == 27 }

glutInit();
glutInitDisplayMode(GLUT_DOUBLE | GLUT_RGBA | GLUT_DEPTH | GLUT_MULTISAMPLE);
glutInitContextVersion(3, 2);
glutInitContextProfile(0x0001);
glutInitWindowSize($W, $H);
glutCreateWindow('Envelope Lathe Mesh');
init_gl();
glutDisplayFunc(\&display);
glutIdleFunc(\&idle);
glutKeyboardFunc(\&keyboard);

printf "Lathe mesh: %d slices x %d stacks — cycles through %d shapes — ESC to quit\n",
    $slices, $stacks, scalar @profiles;
printf "Exported OBJ+STL to /tmp/\n";
glutMainLoop();
