=head1 DESCRIPTION

It currently provides functionality to find the shortest  route between  the  two
given nodes. It covers the following tube lines:

=over 2

=item * L<Bakerloo Line|Map::Tube::London::Line::Bakerloo>

=item * L<Central Line|Map::Tube::London::Line::Central>

=item * L<Circle Line|Map::Tube::London::Line::Circle>

=item * L<District Line|Map::Tube::London::Line::District>

=item * L<Dockland Light Railway Line|Map::Tube::London::Line::DLR>

=item * L<Hammersmith & City Line|Map::Tube::London::Line::HammersmithCity>

=item * L<Jubilee Line|Map::Tube::London::Line::Jubilee>

=item * L<Metropolitan Line|Map::Tube::London::Line::Metropolitan>

=item * L<Northern Line|Map::Tube::London::Line::Northern>

=item * L<London Overground Line|Map::Tube::London::Line::Overground>

=item * L<Piccadilly Line|Map::Tube::London::Line::Piccadilly>

=item * L<Victoria Line|Map::Tube::London::Line::Victoria>

=item * L<Waterloo & City Line|Map::Tube::London::Line::WaterlooCity>

=back

=head1 CONSTRUCTOR

The constructor DO NOT expects parameters.This setup the default node definitions.

    use strict; use warnings;
    use Map::Tube::London;

    my $tube = Map::Tube::London->new;

=head1 METHODS

=head2 get_shortest_route($from, $to)

It expects C<$from> and C<$to> station name, required param. It returns an object
of type L<Map::Tube::Route>. On error it throws exception of type L<Map::Tube::Exception>.

    use strict; use warnings;
    use Map::Tube::London;

    my $tube  = Map::Tube::London->new;
    my $route = $tube->get_shortest_route('Baker Street', 'Farringdon');

    print "Route: $route\n";;

=head2 as_image($line_name)

It expects the plugin  L<Map::Tube::Plugin::Graph> to be  installed. Returns line
image  as  base64  encoded string if C<$line_name> passed in otherwise it returns
base64 encoded string of the entire map.

    use strict; use warnings;
    use MIME::Base64;
    use Map::Tube::London;

    my $tube = Map::Tube::London->new;
    my $map  = $tube->name;
    open(my $IMAGE, ">", "$map.png");
       or die "ERROR: Can't open [$map.png]: $!";
    binmode($IMAGE);
    print $IMAGE decode_base64($tube->as_image);
    close($IMAGE);

The L<London Tube Map|https://raw.githubusercontent.com/manwar/Map-Tube-London/master/maps/London-Tube.png>
as generated by plugin L<Map::Tube::Plugin::Graph>.

