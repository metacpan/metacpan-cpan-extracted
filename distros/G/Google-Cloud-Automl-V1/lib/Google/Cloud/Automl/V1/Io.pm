=head2 Google::Cloud::Automl::V1::Io::ModelExportOutputConfig

Output configuration for ModelExport Action.

Inherits from L<Protobuf::Message>.

=head3 Accessors

=over 4

=item * C<< $msg->gcs_destination() >> / C<< $msg->gcs_destination($value) >>

Type: C<Message> (L<Google::Cloud::Automl::V1::Io::GcsDestination>)

Required. The Google Cloud Storage location where the model is to be
written to. This location may only be set for the following model
formats:
  "tflite", "edgetpu_tflite", "tf_saved_model", "tf_js", "core_ml".

 Under the directory given as the destination a new one with name
 "model-export-<model-display-name>-<timestamp-of-export-call>",
 where timestamp is in YYYY-MM-DDThh:mm:ss.sssZ ISO-8601 format,
 will be created. Inside the model and any of its supporting files
 will be written.

=item * C<< $msg->model_format() >> / C<< $msg->model_format($value) >>

Type: C<String>

The format in which the model must be exported. The available, and default,
formats depend on the problem and model type (if given problem and type
combination doesn't have a format listed, it means its models are not
exportable):

*  For Image Classification mobile-low-latency-1, mobile-versatile-1,
       mobile-high-accuracy-1:
     "tflite" (default), "edgetpu_tflite", "tf_saved_model", "tf_js",
     "docker".

*  For Image Classification mobile-core-ml-low-latency-1,
       mobile-core-ml-versatile-1, mobile-core-ml-high-accuracy-1:
     "core_ml" (default).

*  For Image Object Detection mobile-low-latency-1, mobile-versatile-1,
       mobile-high-accuracy-1:
     "tflite", "tf_saved_model", "tf_js".
Formats description:

* tflite - Used for Android mobile devices.
* edgetpu_tflite - Used for [Edge TPU](https://cloud.google.com/edge-tpu/)
                   devices.
* tf_saved_model - A tensorflow model in SavedModel format.
* tf_js - A [TensorFlow.js](https://www.tensorflow.org/js) model that can
          be used in the browser and in Node.js using JavaScript.
* docker - Used for Docker containers. Use the params field to customize
           the container. The container is verified to work correctly on
           ubuntu 16.04 operating system. See more at
           [containers
           quickstart](https://cloud.google.com/vision/automl/docs/containers-gcs-quickstart)
* core_ml - Used for iOS mobile devices.

=item * C<< $msg->params() >> / C<< $msg->params($value) >>

Type: C<Message> (L<Google::Cloud::Automl::V1::Io::ModelExportOutputConfig::ParamsEntry>)

Additional model-type and format specific parameters describing the
requirements for the to be exported model files, any string must be up to
25000 characters long.

 * For `docker` format:
    `cpu_architecture` - (string) "x86_64" (default).
    `gpu_architecture` - (string) "none" (default), "nvidia".

=back

