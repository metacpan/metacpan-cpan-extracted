# Regenerates the frozen reference table in t/roc.R.t.  The test never runs
# this; it is kept so the numbers can be checked and re-derived:
#
#   Rscript t/roc.R.R > /tmp/roc.ref.pl
#
# and paste the output over the block between "# BEGIN GENERATED" and
# "# END GENERATED" in t/roc.R.t.
#
# Needs R >= 4.6.1 with pROC 1.19.0.1.  The data is pROC's own aSAH, the set its
# tests/testthat/ suite pins its values on (test-auc.R, test-var.R,
# test-ci.auc.R, test-roc.R).
suppressMessages(library(pROC))
data(aSAH)
options(digits = 17)

num <- function(x) {
	sapply(x, function(v) {
		if (is.na(v)) "undef"
		else if (is.infinite(v)) if (v > 0) "9**9**9" else "-9**9**9"
		else sprintf("%.17g", v)
	})
}
vec <- function(x) paste0("[", paste(num(x), collapse = ","), "]")

cat("# BEGIN GENERATED by t/roc.R.R (pROC ", as.character(packageVersion("pROC")),
    ", ", R.version.string, ")\n", sep = "")
cat("my @outcome = (", paste0("'", as.character(aSAH$outcome), "'", collapse = ","), ");\n", sep = "")
for (col in c("wfns", "ndka", "s100b")) {
	cat("my @", col, " = @{", vec(as.numeric(aSAH[[col]])), "};\n", sep = "")
}
cat("my %ref = (\n")
for (col in c("wfns", "ndka", "s100b")) {
	x <- as.numeric(aSAH[[col]])
	# direction "<" in pROC is controls < cases: a higher score is a case,
	# which is Stats::LikeR's direction '>'.
	r  <- roc(aSAH$outcome, x, levels = c("Good", "Poor"), direction = "<", quiet = TRUE)
	ci <- as.numeric(ci.auc(r, method = "delong"))
	co <- coords(r, "all", ret = c("threshold", "sensitivity", "specificity"),
	             transpose = FALSE)
	# pROC's thresholds run low to high and sit between the observed values;
	# Stats::LikeR's curve runs high to low and uses the values themselves,
	# so the (sensitivity, specificity) pairs are pROC's in reverse order.
	o <- order(co$threshold, decreasing = TRUE)
	cat("\t", col, " => {\n", sep = "")
	cat("\t\tauc  => ", num(as.numeric(auc(r))), ",\n", sep = "")
	cat("\t\tse   => ", num(sqrt(var(r, method = "delong"))), ",\n", sep = "")
	cat("\t\tci   => ", vec(ci[c(1, 3)]), ",\n", sep = "")
	cat("\t\tsens => ", vec(co$sensitivity[o]), ",\n", sep = "")
	cat("\t\tspec => ", vec(co$specificity[o]), ",\n", sep = "")
	cat("\t},\n")
}
# test-roc.R "roc.default handles NAs": the first 20 ndka values are NA, and
# na.rm = TRUE must give the same AUC as rows 21:113.
m <- aSAH; m$ndka[1:20] <- NA
r <- roc(m$outcome, m$ndka, levels = c("Good", "Poor"), direction = "<",
         na.rm = TRUE, quiet = TRUE)
cat("\tndka_missing => { auc => ", num(as.numeric(auc(r))),
    ", se => ", num(sqrt(var(r))), " },\n", sep = "")
# One case among three controls: var() is NA (var() of one placement value),
# so pROC's ci.auc() is NA too.
r <- roc(c(0, 1, 0, 0), c(0.1, 0.25, 0.3, 0.2), levels = c(0, 1),
         direction = "<", quiet = TRUE)
cat("\tone_case => { auc => ", num(as.numeric(auc(r))),
    ", se => ", num(suppressWarnings(sqrt(var(r)))), " },\n", sep = "")
cat(");\n# END GENERATED\n")
