- B<`parent.type`>: Parent's type: `folder` or `organization`.
- B<`parent.id`>: Parent's id number (for example: `123`).
- B<`id`, `projectId`>: Filters by projectId.
- B<`state`, `lifecycleState`>: Filters by state.
- B<`labels`>: Filters by label name or value.
- B<`labels.<key>` (where `<key>` is the name of a label)>: Filters by label
name.

Search expressions are case insensitive.

Some examples queries:


- B<`name:how*`>: The project's name starts with "how".
- B<`name:Howl`>: The project's name is `Howl` or `howl`.
- B<`name:HOWL`>: Equivalent to above.
- B<`NAME:howl`>: Equivalent to above.
- B<`labels.color:*`>: The project has the label `color`.
- B<`labels.color:red`>:  The project's label `color` has the value `red`.
- B<`labels.color:red labels.size:big`>: The project's label `color` has
the value `red` or its label `size` has the value `big`.

If no query is specified, the call will return projects for which the user
has the `resourcemanager.projects.get` permission.

