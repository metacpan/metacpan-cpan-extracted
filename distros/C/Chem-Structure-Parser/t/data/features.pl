#!/usr/bin/env perl
# Freezes mdtraj's answer for the structures in this directory into features.txt.
#
# t/features.t compares this module's solvent-accessible surface, radius of
# gyration, mass and pi-stacking against mdtraj, which is a reader nobody here
# wrote.  mdtraj is not something the distribution can require, so the
# comparison has to survive an installer who has never heard of it: this script
# writes down what mdtraj said, and the test reads that instead of running
# python.  Where mdtraj *is* installed the test does both and checks the two
# still agree, which is what keeps the frozen file honest.
#
# Run it from t/data/ after adding or changing a structure here, and commit both
# the script and what it wrote:
#
#     STRUCTURE_INFO_PYTHON=/home/con/.pyenv/versions/3.14.2/bin/python3 \
#         perl features.pl
#
# The dump itself is t/data/features.py -- one copy, run by this script and by
# the test, so the frozen answer and the live one cannot drift into being
# answers to different questions.  mdtraj 1.11.1.
require 5.010;
use strict;
use warnings FATAL => 'all';
use autodie ':default';
use File::Basename 'dirname';
use Cwd 'abs_path';

my $dir  = dirname(abs_path(__FILE__));
my $py   = $ENV{STRUCTURE_INFO_PYTHON} || 'python3';
my $dump = "$dir/features.py";
# Biopython as well as mdtraj: the half-sphere exposure is Bio.PDB's and mdtraj
# has no equivalent of it.
system("$py -c 'import mdtraj, numpy, Bio' >/dev/null 2>&1") == 0
	or die "$py cannot import mdtraj, numpy and Bio; set STRUCTURE_INFO_PYTHON\n";

opendir(my $dh, $dir);
my @files = sort grep { /\.(?:pdb|ent|cif|mmcif)\z/ } readdir $dh;
closedir $dh;

my $version = qx($py -c 'import mdtraj; print(mdtraj.__version__)');
chomp $version;

my $out = "$dir/features.txt";
open my $fh, '>', "$out.new";
print $fh <<"HEAD";
# mdtraj's answer for the structures in this directory, frozen.
#
# Generated by t/data/features.pl from t/data/features.py with mdtraj $version.
# Do not edit: re-run the generator.  t/features.t reads this so that the
# comparison against another implementation runs on a machine with no python and
# no mdtraj, and checks it against the live one on a machine that has both.
#
# One section per structure: '== <file>' and then features.py's output, or
# '== <file> refused' for a file mdtraj will not read at all, which is a fact
# about mdtraj rather than about the file and is recorded rather than hidden.
#
# Every surface is printed twice: as mdtraj computes it, in float32, and as the
# same algorithm computes it in float64.  The head of features.py says why.
HEAD

for my $f (@files) {
	my $err = "$dir/features.err.$$";
	my $rows = qx($py \Q$dump\E \Q$dir/$f\E 2>\Q$err\E);
	my $rc = $?;
	open my $eh, '<', $err;
	my @err = <$eh>;
	close $eh;
	unlink $err;
	if ($rc != 0) {
		chomp(my $why = @err ? $err[-1] : 'no reason given');
		$why =~ s/\A\w*(?:Error|Exception): //;
		print $fh "\n== $f refused\n# mdtraj: $why\n";
		next;
	}
	print $fh "\n== $f\n$rows";
}
close $fh;
rename "$out.new", $out;
print "wrote $out\n";
