#!/usr/bin/perl
# Regenerate eTextSyms.h from the object files of the widget:
#   make && perl eTextSyms.PL && make
# Every global symbol defined by the widget's C files gets an eText_
# prefix, so that it can never be confused with the identically named
# internals of Tk's own text widget living in Tk.so.  (The objects may
# already carry the prefix from the previous header; it is stripped.)
# Makefile.PL sets PL_FILES => {} so that MakeMaker never runs this on
# its own.
use strict;
my @objs = map { "$_.o" } qw(tkText tkTextBTree tkTextDisp tkTextIndex
			     tkTextMark tkTextTag tkTextWind tkTextImage tkTextUndo
			     pperlGlue);
my %sym;
for my $o (@objs) {
  -f $o or die "$o: not built yet (run make first)\n";
  open my $nm, '-|', 'nm', '-g', '--defined-only', $o or die "nm: $!";
  while (<$nm>) {
    my ($type, $name) = (split)[1,2];
    next unless defined $name and $type =~ /^[TDBRC]$/;
    next if $name =~ /Vptr$/;
    $name =~ s/^eText_//;
    $sym{$name}++;
  }
}
die "no symbols found; refusing to write an empty eTextSyms.h\n" unless %sym;
open my $h, '>', 'eTextSyms.h' or die;
print $h <<'HDR';
/*
 * eTextSyms.h -- generated by eTextSyms.PL; do not edit.
 *
 * The eText widget is the tk4.0 text widget with blocks added; its
 * internal procedures and variables carry the same names as those of
 * Tk's own text widget, which lives in Tk.so.  Prefix all of ours so
 * that the two can never be confused by the dynamic linker.
 */
#ifndef _ETEXT_SYMS_H
#define _ETEXT_SYMS_H
HDR
printf $h "#define %-32s eText_%s\n", $_, $_ for sort keys %sym;
print $h "#endif /* _ETEXT_SYMS_H */\n";
close $h;
print "eTextSyms.h: ", scalar(keys %sym), " symbols\n";
