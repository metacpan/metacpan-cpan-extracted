=head1 NAME

FixMP3Tags - Command-line tool to fix and normalize MP3 tags

=head1 SYNOPSIS

    use FixMP3Tags;

    # Or use the command-line tool directly:
    # fix-mp3-tags --help

=head1 DESCRIPTION

This distribution provides the C<fix-mp3-tags> command-line tool and the
L<FixMP3Tags::Processor> module for processing and normalizing MP3 ID3 tags.

