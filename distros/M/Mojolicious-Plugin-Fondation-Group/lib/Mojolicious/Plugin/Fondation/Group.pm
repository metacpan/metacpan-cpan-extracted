=head1 NAME

Mojolicious::Plugin::Fondation::Group - Group management plugin for Fondation

=head1 VERSION

version 0.02

=head1 SYNOPSIS

  # myapp.conf
  {
      'Fondation' => {
          dependencies => [
              'Fondation::User',
              'Fondation::Group',
          ],
      },
  }

=head1 DESCRIPTION

L<Mojolicious::Plugin::Fondation::Group> provides group management:
the C<groups> and C<user_group> (pivot) tables, REST controllers,
and automatic many-to-many relations with users and permissions.

=head2 Many-to-many relations

When L<Fondation::User> is loaded, group↔user links are established
automatically in C<fondation_finalyze> via
L<DBIx::Class::Relationship::ManyToMany::Async>.

Similarly, when L<Fondation::Perm> is loaded, group↔perm links are
created in that plugin's C<fondation_finalyze>.

=head2 with() — many_to_many prefetch

  # Include perms (or users) in list/read responses
  GET /api/Group?with=perms
  GET /api/User?with=groups

  # Programmatically:
  $c->model('group')->with('perms')->TO_JSON->then(sub ($data) {
      $self->render(openapi => $data);
  });
  $c->model('user')->with('groups')->TO_JSON->then(sub ($data) {
      $self->render(openapi => $data);
  });

C<with()> triggers a single-query prefetch via the pivot table.
Target objects are auto-included in the C<TO_JSON> output by
L<Mojolicious::Plugin::Fondation::Schema::Result::Base>.

Without C<with()>, m2m relationships are silently excluded.

=head2 Controller

REST endpoints (routes generated by OpenAPI):

  GET    /api/Group           list all groups
  POST   /api/Group           create a group
  GET    /api/Group/:id       read a group
  PUT    /api/Group/:id       update a group
  DELETE /api/Group/:id       delete a group

  GET    /api/Group/:id/members      list members
  POST   /api/Group/:id/members      add a member
  DELETE /api/Group/:id/members/:uid remove a member

