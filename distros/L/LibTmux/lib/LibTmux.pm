package LibTmux;
use v5.44;
our $VERSION = '0.003';

=head1 NAME

LibTmux - Explicit tmux commands and captured graph queries

=head1 DESCRIPTION

Use L<LibTmux::Server> for acquisition and commands. Captured entities and
L<LibTmux::Selection> queries perform no tmux I/O.

=head1 DOCUMENTATION

L<Perl documentation|https://libtmux.org/en/perl/> provides installation,
guides, and runnable examples. Read the
L<API reference|https://libtmux.org/en/perl/latest/reference/> or start with
L<Server|https://libtmux.org/en/perl/latest/reference/libtmux-server/>.
The L<CPAN distribution|https://metacpan.org/dist/LibTmux> contains this POD
and the consumer examples. The C<0.x> API can change between releases.

=cut
