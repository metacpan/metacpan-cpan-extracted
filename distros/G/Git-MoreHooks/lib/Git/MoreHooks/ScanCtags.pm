=head1 NAME

Git::MoreHooks::ScanCtags - GitHooks plugin to create or update ctags after commit or merge

=head1 VERSION

version 0.019

=head1 SYNOPSIS

As a C<Git::Hooks> plugin you don't use this Perl module directly. Instead, you
may configure it in a Git configuration file like this:

  [githooks]

    # Enable the plugin
    plugin = Git::MoreHooks::ScanCtags

  [githooks "scanctags"]
    # Default values underneath:

    # Outfile (tags) name
    tags = tags

    # Directories to scan
    dir = lib
    dir = bin
    dir = t

    # File types (by suffix) to scan (in above dirs)
    suffix = pm
    suffix = pl
    suffix = t

    # Scan all executable files (in above dirs)
    executable = 1

    # verbose
    verbose = 1

=head1 DESCRIPTION

This L<Git::Hooks> plugin hooks itself to the hooks below to perform
post-commit and post-merge actions.

=over

=item * B<post-commit>, B<post-applypatch>, B<post-checkout>, B<post-merge>

=back

Keep tags file updated and in sync with committed code.

To enable this plugin you should add it to the githooks.plugin configuration
option:

    [githooks]
      plugin = Git::MoreHooks::ScanCtags

