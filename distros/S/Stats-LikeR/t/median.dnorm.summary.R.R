# Generator for t/median.R.numpy.t, t/dnorm.R.t and t/summary.R.t: prints the
# frozen R expected values.  Re-run with
#     Rscript t/median.dnorm.summary.R.R
# (R 4.6.2 printed the values committed in the three tests on 2026-11-26.)
f <- function(x) sprintf("%.17g", x)
p <- function(label, x) cat(label, ":", paste(f(x), collapse = ", "), "\n")
cat("== median\n")
p("median(1:4)", median(1:4))
p("median(c(1:3,100,1000))", median(c(1:3, 100, 1000)))
p("median(c(-Inf,-Inf,Inf,Inf))", median(c(-Inf, -Inf, Inf, Inf)))
p("median(numeric(0))", median(numeric(0)))
p("median(c(1e308,1e308))", median(c(1e308, 1e308)))
p("median(c(1,NA,3))", median(c(1, NA, 3)))
a <- c(0.0444502, 0.0463301, 0.141249, 0.0606775); p("numpy a", median(a))
p("median(c(-Inf,1,2))", median(c(-Inf, 1, 2)))
p("median(c(-Inf,Inf))", median(c(-Inf, Inf)))
p("median(c(5,5,5,5))", median(c(5, 5, 5, 5)))
p("median(c(-7,3))", median(c(-7, 3)))
cat("== dnorm\n")
p("dnorm(-4:4)", dnorm(-4:4))
p("dnorm(c(-1,.5,3),1,2)", dnorm(c(-1, .5, 3), 1, 2))
p("dnorm(c(-1,.5,3),1,2,log)", dnorm(c(-1, .5, 3), 1, 2, log = TRUE))
p("dnorm(c(-60,-30,0,30,50),log)", dnorm(c(-60, -30, 0, 30, 50), log = TRUE))
p("dnorm(30)", dnorm(30))
p("dnorm(c(0,1),0,0)", dnorm(c(0, 1), 0, 0))
p("dnorm(c(0,1),0,0,log)", dnorm(c(0, 1), 0, 0, log = TRUE))
p("dnorm(0,sd=Inf)", dnorm(0, sd = Inf))
p("dnorm(0,sd=Inf,log)", dnorm(0, sd = Inf, log = TRUE))
p("dnorm(c(-Inf,Inf))", dnorm(c(-Inf, Inf)))
p("dnorm(Inf,log)", dnorm(Inf, log = TRUE))
p("dnorm(Inf,mean=Inf)", dnorm(Inf, mean = Inf))
p("dnorm(0,mean=Inf)", dnorm(0, mean = Inf))
p("dnorm(0:1,sd=-Inf)", suppressWarnings(dnorm(0:1, sd = -Inf)))
p("dnorm(0,sd=-1)", suppressWarnings(dnorm(0, sd = -1)))
p("dnorm(c(0,1),mean=c(0,1),sd=c(1,2))", dnorm(c(0, 1), mean = c(0, 1), sd = c(1, 2)))
p("dnorm(1e-300)", dnorm(1e-300))
p("dnorm(0,mean=1e-5,sd=1e-5)", dnorm(0, 1e-5, 1e-5))
p("dnorm(NaN)", dnorm(NaN)); p("dnorm(NA)", dnorm(NA_real_))
p("dnorm(0)==1/sqrt(2pi)", dnorm(0) == 1/sqrt(2*pi))
p("dnorm(1)==exp(-1/2)/sqrt(2pi)", dnorm(1) == exp(-1/2)/sqrt(2*pi))
p("dnorm(1)==1/sqrt(2pi e)", dnorm(1) == 1/sqrt(2*pi*exp(1)))
p("integrate(dnorm,-1.96,1.96)", integrate(dnorm, -1.96, 1.96)$value)
cat("== summary (full precision; the test allows 4 significant digits)\n")
