#!/usr/bin/env perl
# G-code export: envelope profiles as CNC lathe toolpaths
# Generates G-code for turning envelope shapes on a CNC lathe
# Also generates 2D contour G-code for CNC router/laser/waterjet
#
# Output files can be loaded directly into LinuxCNC, Mach3, GRBL, etc.
use strict;
use warnings;
use Math::SegmentedEnvelope qw(spline env adsr perc);

my $out_dir = $ARGV[0] // '/tmp';

# Profiles to cut
my @profiles = (
    { name => 'vase',
      env => spline([0, 0.05, 0.15, 0.4, 0.6, 0.85, 0.95, 1.0],
                    [15, 17, 25, 10, 8, 20, 22, 21]),  # radius in mm
      height => 100,  # mm
      feed => 80 },
    { name => 'goblet',
      env => spline([0, 0.05, 0.1, 0.12, 0.5, 0.52, 0.7, 0.9, 1.0],
                    [15, 16, 12, 2, 2, 3, 12, 18, 18]),
      height => 120,
      feed => 60 },
    { name => 'bowl',
      env => env([[0, 25, 30, 30], [0.3, 0.4, 0.3], [-3, 1, 2]],
                 morpher_formula => 'smoothstep'),
      height => 50,
      feed => 100 },
    { name => 'spindle',
      env => spline([0, 0.1, 0.25, 0.5, 0.75, 0.9, 1.0],
                    [8, 12, 18, 20, 18, 12, 8]),
      height => 150,
      feed => 80 },
);

# CNC Lathe G-code (turning)
sub export_lathe_gcode {
    my ($profile, $file) = @_;
    my $e = $profile->{env};
    my $h = $profile->{height};
    my $f = $profile->{feed};
    my $steps = 200;
    my $s = $e->static;
    my $dur = $e->duration;

    open my $fh, '>', $file or die "Cannot write $file: $!";

    print $fh <<"HDR";
; CNC Lathe G-code: $profile->{name}
; Generated by Math::SegmentedEnvelope
; Height: ${h}mm, Steps: $steps
; Material: set spindle speed and tool for your material
;
G90 G21          ; absolute positioning, metric
G28              ; home
M03 S1200        ; spindle on, 1200 RPM (adjust for material)
G00 X30 Z2       ; rapid to safe position
HDR

    # Roughing pass: step down in 2mm increments
    my $max_r = 0;
    my @pts;
    for my $i (0 .. $steps) {
        my $t = $i / $steps;
        my $r = $s->($t * $dur);
        my $z = -$t * $h;  # Z goes negative into material
        push @pts, [$r, $z];
        $max_r = $r if $r > $max_r;
    }

    my $stock_r = $max_r + 3;  # 3mm stock allowance
    my $step_depth = 2;        # 2mm per roughing pass
    my $passes = int(($stock_r - 0) / $step_depth) + 1;

    print $fh "\n; === Roughing passes ===\n";
    for my $pass (1 .. $passes) {
        my $cut_r = $stock_r - $pass * $step_depth;
        print $fh "\n; Pass $pass: X=" . sprintf("%.1f", $cut_r * 2) . " diameter\n";
        printf $fh "G00 X%.3f Z2\n", $cut_r * 2;

        for my $pt (@pts) {
            my ($r, $z) = @$pt;
            next if $r < $cut_r;  # skip points inside this pass
            printf $fh "G01 X%.3f Z%.3f F%d\n", $cut_r * 2, $z, $f;
        }
        printf $fh "G00 X%.3f Z2\n", $stock_r * 2;  # retract
    }

    # Finishing pass: follow exact profile
    print $fh "\n; === Finishing pass ===\n";
    printf $fh "G00 X%.3f Z2\n", $pts[0][0] * 2 + 1;
    for my $pt (@pts) {
        printf $fh "G01 X%.3f Z%.3f F%d\n", $pt->[0] * 2, $pt->[1], $f / 2;
    }

    print $fh <<"FTR";

G00 X60 Z10      ; retract
M05              ; spindle off
M30              ; program end
FTR
    close $fh;
    printf "Lathe:  %s (%d bytes, %d roughing passes + finish)\n", $file, -s $file, $passes;
}

# 2D Contour G-code (router/laser/waterjet)
# Cuts the profile shape as a 2D outline
sub export_contour_gcode {
    my ($profile, $file) = @_;
    my $e = $profile->{env};
    my $h = $profile->{height};
    my $f = $profile->{feed};
    my $steps = 200;
    my $s = $e->static;
    my $dur = $e->duration;

    open my $fh, '>', $file or die "Cannot write $file: $!";

    print $fh <<"HDR";
; 2D Contour G-code: $profile->{name} (half-profile)
; Generated by Math::SegmentedEnvelope
; For CNC router, laser cutter, or waterjet
;
G90 G21          ; absolute, metric
G00 Z5           ; safe height
HDR

    # Right half of profile (positive X = radius, Y = height)
    print $fh "\n; === Right profile ===\n";
    printf $fh "G00 X%.3f Y0\n", $s->(0) ;
    printf $fh "G01 Z-3 F%d\n", $f;  # plunge

    for my $i (0 .. $steps) {
        my $t = $i / $steps;
        my $r = $s->($t * $dur);
        printf $fh "G01 X%.3f Y%.3f F%d\n", $r, $t * $h, $f;
    }

    # Connect across top
    printf $fh "G01 X%.3f Y%.3f\n", -$s->($dur), $h;

    # Left half (mirror)
    print $fh "\n; === Left profile (mirror) ===\n";
    for my $i (reverse 0 .. $steps) {
        my $t = $i / $steps;
        my $r = $s->($t * $dur);
        printf $fh "G01 X%.3f Y%.3f F%d\n", -$r, $t * $h, $f;
    }

    # Close bottom
    printf $fh "G01 X%.3f Y0\n", $s->(0);

    print $fh <<"FTR";

G00 Z5           ; retract
M05              ; spindle/laser off
M30              ; program end
FTR
    close $fh;
    printf "Contour: %s (%d bytes)\n", $file, -s $file;
}

# Generate all
for my $p (@profiles) {
    export_lathe_gcode($p, "$out_dir/$p->{name}_lathe.gcode");
    export_contour_gcode($p, "$out_dir/$p->{name}_contour.gcode");
}

# Print summary
print "\nG-code files in $out_dir/:\n";
for my $p (@profiles) {
    printf "  %-12s lathe=%s contour=%s\n", $p->{name},
        "$p->{name}_lathe.gcode", "$p->{name}_contour.gcode";
}

# Preview: ASCII side-view of each profile
print "\nProfile previews:\n";
for my $p (@profiles) {
    printf "\n  %s (h=%dmm):\n", $p->{name}, $p->{height};
    my $s = $p->{env}->static;
    my $dur = $p->{env}->duration;
    my $max_r = $p->{env}->max_value;
    for my $row (0 .. 15) {
        my $t = $row / 15;
        my $r = $s->($t * $dur);
        my $bar = int($r / ($max_r || 1) * 25);
        printf "  %4.0fmm |%s%s|\n", $t * $p->{height},
            ' ' x (25 - $bar), '#' x $bar;
    }
}
