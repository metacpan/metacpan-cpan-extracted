def pl(x):
    """Perl literal for a python value."""
    if x is None:
        return 'undef'
    if isinstance(x, (np.integer,)):
        x = int(x)
    if isinstance(x, (np.floating,)):
        x = float(x)
    if isinstance(x, (bool, np.bool_)):
        return '1' if x else '0'
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        if math.isnan(x):
            return 'undef'
        if x == int(x) and abs(x) < 1e15:
            return str(int(x))
        return repr(x)
    if isinstance(x, str):
        return "'" + x.replace('\\', '\\\\').replace("'", "\\'") + "'"
    if isinstance(x, (list, tuple)):
        return '[' + ', '.join(pl(v) for v in x) + ']'
    if isinstance(x, dict):
        return '{' + ', '.join('%s => %s' % (pl(str(k)), pl(v)) for k, v in x.items()) + '}'
    raise TypeError(type(x))


def clean(v):
    if isinstance(v, float) and math.isnan(v):
        return None
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.floating,)):
        v = float(v)
        return None if math.isnan(v) else v
    return v


def aoh(df):
    return [{str(k): clean(v) for k, v in r.items()} for r in df.to_dict('records')]


def hoa(df):
    return {str(k): [clean(v) for v in vs] for k, vs in df.to_dict('list').items()}


def hoh(df):
    return {str(i): {str(k): clean(v) for k, v in r.items()}
            for i, r in df.to_dict('index').items()}


def aoa(df):
    return [[clean(v) for v in r] for r in df.values.tolist()]


def flat(cols, sep='.'):
    """Join a column MultiIndex into the names pivot_table() generates."""
    out = []
    for c in cols:
        if isinstance(c, tuple):
            c = tuple('sd' if (i == 0 and p == 'std' and len(c) > 2) else p for i, p in enumerate(c))
        out.append(sep.join(str(p) for p in c if p != '') if isinstance(c, tuple) else str(c))
    return out


def emit(name, src, ins, opt, shape, exp, kind):
    print('\t{ kind => %s, name => %s, src => %s,' % (pl(kind), pl(name), pl(src)))
    print('\t  in => %s,' % pl(ins))
    print('\t  opt => %s,' % pl(opt))
    print('\t  shape => %s,' % pl(shape))
    print('\t  exp => %s },' % pl(exp))


def cat(name, src, frames, shape, **kw):
    """concat of record lists / column dicts, through pandas."""
    dfs = [pd.DataFrame(f) for f in frames]
    r = pd.concat(dfs, ignore_index=True, **kw)
    emit(name, src, frames, {}, shape, {'aoh': aoh, 'hoa': hoa}[shape](r), 'concat')


