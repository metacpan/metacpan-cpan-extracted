=head1 NAME

Git::MoreHooks::CreateTags - Git::Hooks plugin to create or update tags file

=head1 CONFIGURATION

The plugin is configured by the following git options under the
C<githooks.scanctags> subsection.

It can be disabled for specific references via the C<githooks.ref> and
C<githooks.noref> options about which you can read in the L<Git::Hooks>
documentation.

=head2 dir

Directories to scan.

=head2 suffix

Scan files with these file endings in the directories above.

=head2 executable BOOL, default: 1

Scan every executable file for tags in the directories above.

=head2 verbose BOOL, default: 1

Turn on or off verbose reporting.
Set this option to 0 if you don't want the hook to report
"Discovered total %s tags in %s files. Written to file '%s'."

