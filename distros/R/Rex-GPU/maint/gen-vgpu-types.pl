#!/usr/bin/env perl
# Regenerates the table of lib/Rex/GPU/NVIDIA/VGPU.pm -- the (device ID,
# subsystem ID) pairs that mark an NVIDIA vGPU guest device (karr #24) --
# from NVIDIA's own list, sVgpuUsmTypes[] in
# src/common/shared/inc/g_vgpu_chip_flags.h of open-gpu-kernel-modules.
#
# Only the region between "# BEGIN GENERATED" and "# END GENERATED" in the
# module is replaced: the lookup code and the POD around it are hand-written
# and stay as they are. The region carries the provenance (file, tag, date,
# count), NVIDIA's MIT notice read from the checkout's COPYING, and the
# methods `source` and `types`.
#
# Strict on purpose: every line of the array must be an ENTRY(dev, sub,
# 0x10de, "name") -- a changed format, another subsystem vendor, a duplicate
# pair or a quote in a name dies instead of writing a table that silently
# lost or mangled rows.
#
# A maint script, not part of the installed distribution: it is in the
# tarball (Git::GatherDir) but not installed (not lib/, not bin/) and not
# indexed (no package; MetaProvides::Package reads installed modules only).
#
# Usage:
#   git clone --depth 1 --branch 615.71.09 \
#     https://github.com/NVIDIA/open-gpu-kernel-modules.git /tmp/ogkm
#   maint/gen-vgpu-types.pl --source /tmp/ogkm [--tag 615.71.09] \
#     [--date 2026-09-24] [--output lib/Rex/GPU/NVIDIA/VGPU.pm]
#   git diff lib/Rex/GPU/NVIDIA/VGPU.pm
#
# --tag defaults to NVIDIA_VERSION in the checkout's version.mk, --date to
# today (UTC), --output to the module in this repository.

use strict;
use warnings;

use Carp qw( croak );
use Getopt::Long qw( GetOptions );
use Path::Tiny qw( path );
use POSIX qw( strftime );

my $HEADER = 'src/common/shared/inc/g_vgpu_chip_flags.h';
my $BEGIN  = '# BEGIN GENERATED by maint/gen-vgpu-types.pl -- do not edit by hand, rerun it';
my $END    = '# END GENERATED';

my %opt = (
  output => path(__FILE__)->absolute->parent(2)->child('lib/Rex/GPU/NVIDIA/VGPU.pm')->stringify
);
GetOptions(\%opt, 'source=s', 'tag=s', 'date=s', 'output=s', 'help')
  or die "usage: $0 --source DIR [--tag TAG] [--date YYYY-MM-DD] [--output FILE]\n";
die "usage: $0 --source DIR [--tag TAG] [--date YYYY-MM-DD] [--output FILE]\n"
  if $opt{help} || !$opt{source};

my $src  = path($opt{source});
my $tag  = $opt{tag} // version_of($src);
my $date = $opt{date} // strftime('%Y-%m-%d', gmtime);
croak "--date must be YYYY-MM-DD, not $date" unless $date =~ /\A\d{4}-\d{2}-\d{2}\z/;

my @rows   = read_types($src->child($HEADER));
my @mit    = mit_notice($src->child('COPYING'));
my $region = render($tag, $date, \@mit, @rows);

my $out  = path($opt{output});
my $text = $out->slurp_utf8;
my $n = ( $text =~ s/^\Q$BEGIN\E\n.*?^\Q$END\E\n/$region/ms );
croak "$out: no '$BEGIN' ... '$END' region to replace" unless $n;
$out->spew_utf8($text);
print scalar(@rows)." vGPU types from $HEADER ($tag) written to $out\n";

sub version_of {
  my ( $dir ) = @_;
  my $mk = $dir->child('version.mk');
  croak "$mk not found -- pass --tag" unless $mk->exists;
  my ( $v ) = $mk->slurp_utf8 =~ /^NVIDIA_VERSION\s*=\s*(\S+)/m;
  croak "no NVIDIA_VERSION in $mk -- pass --tag" unless defined $v;
  return $v;
}

sub read_types {
  my ( $file ) = @_;
  croak "$file not found -- is --source an open-gpu-kernel-modules checkout?"
    unless $file->exists;
  my ( $body ) = $file->slurp_utf8
    =~ /^static const VGPU_USM_TYPES sVgpuUsmTypes\[\] = \{\n(.*?)^\};/ms;
  croak "$file: no sVgpuUsmTypes[] array" unless defined $body;
  my ( @rows, %seen );
  for my $line (split /\n/, $body) {
    next if $line =~ /\A\s*\z/;
    my ( $dev, $sub, $vendor, $name ) = $line
      =~ /\AENTRY\(0x([0-9A-Fa-f]{4}), 0x([0-9A-Fa-f]{4}), 0x([0-9A-Fa-f]{4}), "([^"\\']+)"\),\z/
      or croak "$file: unexpected line in sVgpuUsmTypes[]: $line";
    croak "$file: subsystem vendor 0x$vendor is not 0x10de: $line" unless lc $vendor eq '10de';
    my $key = lc($dev).':'.lc($sub);
    croak "$file: pair $key listed twice" if $seen{$key}++;
    push @rows, [ $key, $name ];
  }
  croak "$file: sVgpuUsmTypes[] is empty" unless @rows;
  return sort { $a->[0] cmp $b->[0] } @rows;
}

# The MIT paragraph of the checkout's COPYING, from "licensed as MIT:" up to
# the dual-licence note for linked kernel modules.
sub mit_notice {
  my ( $file ) = @_;
  croak "$file not found" unless $file->exists;
  my ( $notice ) = $file->slurp_utf8 =~ /licensed as MIT:\s*\n(.*?)\n\s*However,/s;
  croak "$file: no MIT notice found" unless defined $notice;
  my @lines = split /\n/, $notice;
  s/\A\s+// for @lines;
  s/\s+\z// for @lines;
  pop @lines while @lines && $lines[-1] eq '';
  return @lines;
}

sub render {
  my ( $tag, $date, $mit, @rows ) = @_;
  my $count = scalar @rows;
  return join('', map { $_."\n" }
    $BEGIN,
    '#',
    '# Source: '.$HEADER.', sVgpuUsmTypes[]',
    '#   NVIDIA open-gpu-kernel-modules, tag '.$tag,
    '#   https://github.com/NVIDIA/open-gpu-kernel-modules/blob/'.$tag.'/'.$HEADER,
    '# Generated '.$date.', '.$count.' pairs (device ID:subsystem ID => vGPU type).',
    '#',
    '# The table is NVIDIA\'s, licensed as MIT (COPYING of that repository):',
    '#',
    ( map { $_ eq '' ? '#' : '#   '.$_ } @$mit ),
    '',
    'sub source {',
    '  return {',
    "    file      => '$HEADER',",
    "    tag       => '$tag',",
    "    generated => '$date',",
    "    entries   => $count",
    '  };',
    '}',
    '',
    'sub types {',
    '  return (',
    ( map { "    '".$_->[0]."' => '".$_->[1]."'".( $_ == $rows[-1] ? '' : ',' ) } @rows ),
    '  );',
    '}',
    $END
  );
}
