#!/usr/bin/env perl
# Regenerates lib/IO/K8s/AutoGen/CoreShapes.pm -- the precomputed core-shape
# index IO::K8s::AutoGen's reuse_core (D5) looks candidates up in (karr k104).
#
# Why an artifact at all: AutoGen builds that index by loading every shipped
# class under IO/K8s/Api and IO/K8s/Apimachinery and reading each one's
# attribute registry. Measured on this tree, that is ~6.5s in a fresh
# process -- 839 Module::Runtime loads at >99% of it, the File::Find walk
# and the registry reads together ~15ms. reuse_core is default on, so every
# first add_crd / generate / CRD inflate in a process paid it. The finished
# map loads in ~2ms instead, and the type-aware half of the reuse decision
# loads only the handful of candidate classes a looked-up shape actually
# names.
#
# This is NOT a codegen step for the API classes -- nothing under
# lib/IO/K8s/Api* is generated, then or ever. It is a maint-maintained data
# artifact in the same sense as maint/spec-drift-exceptions.yaml: checked
# in, regenerated by hand, and kept honest by a test.
#
# What it writes: IO::K8s::AutoGen::_scan_core_shapes()'s return value,
# verbatim. That function is AutoGen's own live-scan path, so the artifact
# cannot drift in SEMANTICS from the code that consumes it -- the metadata
# rule (part of an embedded type's shape, dropped for a top-level Kind,
# whose metadata Role::APIObject supplies outside the schema) and the
# preference order (LabelSelector, the rest of Meta::V1, Core::V1, then
# alphabetical) are computed there, not reimplemented here.
#
# What it CAN drift in is content, the moment a class is added, removed or
# renamed without a rerun. t/85_core_shape_index.t is what catches that: it
# scans live and compares against the checked-in module, and names this
# script in the failure message.
#
# The emitted $VERSION is read off IO::K8s::AutoGen at generation time, so a
# regenerated file carries the same version as every other module in the
# distribution (which is the rule here -- every package needs its own for
# PAUSE indexing; the release process bumps them all together).
#
# Usage:
#   maint/core-shape-index-gen.pl [--output PATH] [--help]
#
# Examples:
#   maint/core-shape-index-gen.pl
#     Rewrite DIST/lib/IO/K8s/AutoGen/CoreShapes.pm from the classes in
#     DIST/lib. Then `git diff` it to see exactly which shapes moved.
#
#   maint/core-shape-index-gen.pl --output -
#     Print the module to stdout and touch nothing.
#
# Never touches the network and never reads a Kubernetes spec: the shipped
# classes in lib/ are the only input.
use strict;
use warnings;
use v5.10;
use FindBin;
use File::Spec;
use Getopt::Long qw(GetOptions);

my $DIST_ROOT = File::Spec->rel2abs(File::Spec->catdir($FindBin::Bin, '..'));
my $INDEX_MODULE = 'IO::K8s::AutoGen::CoreShapes';

sub usage {
    my ($exit_code) = @_;
    print <<"USAGE";
Usage:
  $0 [--output PATH]

Rewrites the precomputed core-shape index AutoGen's reuse_core looks up,
from the classes currently shipped under DIST/lib. No network, no spec.

Options:
  --output PATH         File to write (default:
                        DIST/lib/IO/K8s/AutoGen/CoreShapes.pm). "-" prints
                        the module to stdout and writes nothing.
  --help                This message

Run this after adding, removing or renaming a class under
lib/IO/K8s/Api or lib/IO/K8s/Apimachinery. t/85_core_shape_index.t fails
until you do.
USAGE
    exit $exit_code;
}

my %opt;
GetOptions(\%opt, 'output=s', 'help|h') or usage(2);
usage(0) if $opt{help};

my $output = $opt{output}
    // File::Spec->catfile($DIST_ROOT, 'lib', 'IO', 'K8s', 'AutoGen', 'CoreShapes.pm');

# lib/ of THIS checkout, never an installed copy: the point is to index the
# classes that are about to ship from here.
unshift @INC, File::Spec->catdir($DIST_ROOT, 'lib');
require IO::K8s::AutoGen;

my $shapes = IO::K8s::AutoGen::_scan_core_shapes();
my $source = render_module($shapes, $IO::K8s::AutoGen::VERSION);

if ($output eq '-') {
    print $source;
}
else {
    open my $fh, '>', $output or die "cannot write $output: $!\n";
    print $fh $source;
    close $fh or die "cannot close $output: $!\n";
    my $classes = 0;
    $classes += scalar @$_ for values %$shapes;
    printf STDERR "%s: %d shapes, %d classes -> %s\n",
        $INDEX_MODULE, scalar keys %$shapes, $classes, $output;
}

exit 0;

# One shape per line, shapes sorted by key string and each class list left
# exactly as _scan_core_shapes ordered it (preference order -- re-sorting
# here would be the copy of the semantics this script exists not to make).
# The line-per-shape layout is deliberate: this file is reviewed as a diff,
# and adding one class should show as one changed line.
sub render_module {
    my ($shapes, $version) = @_;

    my $body = '';
    for my $shape (sort keys %$shapes) {
        $body .= sprintf "    %s => [ %s ],\n",
            _quote($shape), join(', ', map { _quote($_) } @{ $shapes->{$shape} });
    }

    return <<"HEADER" . $body . <<'FOOTER';
package $INDEX_MODULE;
# ABSTRACT: Precomputed core/apimachinery shape index for AutoGen's reuse_core
our \$VERSION = '$version';
use strict;
use warnings;

# GENERATED FILE -- do not edit by hand.
# Regenerate with:  perl maint/core-shape-index-gen.pl
# Drift-tested by:  t/85_core_shape_index.t
#
# "json,key,set" (sorted, comma-joined) -> every shipped class under
# IO::K8s::Api / IO::K8s::Apimachinery with exactly that key set, most
# preferred first. This is IO::K8s::AutoGen::_scan_core_shapes()'s output
# frozen: see that function and the block comment above it for the
# metadata rule and the preference order, and maint/core-shape-index-gen.pl
# for why the index is precomputed rather than built on first use.
#
# Names only -- no types, no required-ness. The type-aware half of the
# reuse decision (IO::K8s::AutoGen::_core_class_for) loads the candidates
# a shape names and reads their real registries, so nothing here can go
# stale in a way that changes what a class means.

my %SHAPES = (
HEADER
);

# The index as a hashref, shape string -> preference-ordered class names.
# Shared, not copied: IO::K8s::AutoGen copies the top level and treats the
# arrayrefs as read-only. Do not mutate them.
sub shapes { \%SHAPES }

1;
FOOTER
}

# Single-quoted Perl string literal. Class names and JSON key names are
# both far tamer than this allows for, but a generated file that quotes by
# assumption is a generated file that breaks on the first key with an
# apostrophe in it.
sub _quote {
    my ($string) = @_;
    $string =~ s/([\\'])/\\$1/g;
    return "'" . $string . "'";
}
