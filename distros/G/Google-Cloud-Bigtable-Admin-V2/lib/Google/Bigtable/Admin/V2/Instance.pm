=head2 Google::Bigtable::Admin::V2::Instance::HotTablet

A tablet is a defined by a start and end key and is explained in
https://cloud.google.com/bigtable/docs/overview#architecture and
https://cloud.google.com/bigtable/docs/performance#optimization.
A Hot tablet is a tablet that exhibits high average cpu usage during the time
interval from start time to end time.

Inherits from L<Protobuf::Message>.

=head3 Accessors

=over 4

=item * C<< $msg->name() >> / C<< $msg->name($value) >>

Type: C<String>

The unique name of the hot tablet. Values are of the form
`projects/{project}/instances/{instance}/clusters/{cluster}/hotTablets/[a-zA-Z0-9_-]*`.

=item * C<< $msg->table_name() >> / C<< $msg->table_name($value) >>

Type: C<String>

Name of the table that contains the tablet. Values are of the form
`projects/{project}/instances/{instance}/tables/[_a-zA-Z0-9][-_.a-zA-Z0-9]*`.

=item * C<< $msg->start_time() >> / C<< $msg->start_time($value) >>

Type: C<Message> (L<Google::Protobuf::Timestamp::Timestamp>)

Output only. The start time of the hot tablet.

=item * C<< $msg->end_time() >> / C<< $msg->end_time($value) >>

Type: C<Message> (L<Google::Protobuf::Timestamp::Timestamp>)

Output only. The end time of the hot tablet.

=item * C<< $msg->start_key() >> / C<< $msg->start_key($value) >>

Type: C<String>

Tablet Start Key (inclusive).

=item * C<< $msg->end_key() >> / C<< $msg->end_key($value) >>

Type: C<String>

Tablet End Key (inclusive).

=item * C<< $msg->node_cpu_usage_percent() >> / C<< $msg->node_cpu_usage_percent($value) >>

Type: C<Float>

Output only. The average CPU usage spent by a node on this tablet over the
start_time to end_time time range. The percentage is the amount of CPU used
by the node to serve the tablet, from 0% (tablet was not interacted with)
to 100% (the node spent all cycles serving the hot tablet).

=back

