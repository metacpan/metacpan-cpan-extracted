=head1 NAME

DBIO::Firebird::DDL - Generate Firebird DDL from DBIO Result classes

=head1 VERSION

version 0.900004

=head1 METHODS

=head2 server_major_version

    my $major = DBIO::Firebird::DDL->server_major_version($schema);

The major version of the server behind the schema's storage (C<3>, C<4>, C<5>
...), read from C<rdb$get_context('SYSTEM','ENGINE_VERSION')>, or C<undef> when
it cannot be asked (the storage does not connect). C<undef> means "no
judgement": nothing is refused on a guess. The one seam through which
L</install_ddl> learns the version, asked only when a column needs it; a test
sets the version by replacing this method (C<< local *DBIO::Firebird::DDL::server_major_version >>).

=head2 install_ddl

    my $ddl = DBIO::Firebird::DDL->install_ddl($schema);

Returns the full installation DDL as a single string.

Every identifier taken from a result class -- table, column, primary key
column, the name of a unique index -- is emitted double-quoted, exactly as
L<DBIO::Firebird::Storage::Common> quotes it in the statements the ORM sends.
Firebird folds a bare identifier to upper case, so C<< table('artist') >> has
to become C<CREATE TABLE "artist"> for C<SELECT ... FROM "artist"> to find it,
and a reserved word such as C<year> is only accepted as a column name when
quoted.

Firebird 3 is the minimum, and the rules of the Diff are measured against
Firebird 5.0.4 only; the neighbouring minimum is a decision, not a measurement.
A C<default_value> on a C<boolean> column is 0, 1, C<'true'> or C<'false'> (any
case) and is written as C<TRUE> or C<FALSE>: the server accepts C<DEFAULT '0'>
there and then fails every insert that takes the default (measured on Firebird
5.0.4). Any other value (C<'f'>, C<''>, C<'yes'>, 2) dies with a
C<DBIO::Exception>; a scalar ref holding another word is SQL as written.

A string C<default_value> is written as a SQL literal with each embedded
single quote doubled (C<it's> becomes C<DEFAULT 'it''s'>); a scalar ref
(C<< \'CURRENT_TIMESTAMP' >>) is literal SQL and is written as given.

The one exception is a scalar-ref name, C<< table(\'cd') >>: that is literal
SQL, the ORM writes it into C<FROM> as given, and so does this method -- the
server folds it to C<CD> on both sides. The body of a view
(C<view_definition>) is the user's SQL and is passed through untouched.

A column with C<is_auto_increment> is written as C<GENERATED BY DEFAULT AS
IDENTITY> (Firebird 3, the driver's minimum; no generator, no trigger), before
C<NOT NULL>. Identity and C<default_value> exclude each other, and only
C<smallint>, C<integer> and C<bigint> (and C<serial>/C<bigserial>, which map to
C<BIGINT>) and C<numeric> / C<decimal> with scale 0 (C<< size => 9 >> or C<<
size => [9, 0] >>; measured on Firebird 5.0.4) can carry it: any other
combination dies with a C<DBIO::Exception>. The introspected model carries the
column as C<is_auto_increment> (from C<rdb$identity_type>), so the target of
the diff has it, and a table or column created by C<Deploy-E<gt>upgrade> gets
the clause as well (L<DBIO::Firebird::Diff::Table>,
L<DBIO::Firebird::Diff::Column>).

Foreign keys and unique constraints are written after every C<CREATE TABLE> (so neither the order of the tables nor a
cycle matters), unique constraints first, as

    ALTER TABLE "child" ADD CONSTRAINT "child_code" UNIQUE ("code");
    ALTER TABLE "child" ADD CONSTRAINT "child_pid_fk" FOREIGN KEY ("pid") REFERENCES "parent" ("id") ON DELETE CASCADE;

A unique constraint is each C<add_unique_constraint>, under its
declared name; the primary key's own columns are skipped (the server refuses a
second constraint over them), and a name above 63 characters dies (Firebird
5.0.4 takes 63 characters, even two-byte ones, and refuses 64; Firebird 3's limit of 31 bytes is not measured). A key is
each C<belongs_to> without C<< is_foreign_key_constraint => 0 >>, named
C<E<lt>tableE<gt>_E<lt>columnsE<gt>_E<lt>targetE<gt>_fk> (the target is in the
name, so two keys over one column to different tables do not meet), or, above
31 B<bytes> (the limit of Firebird 3, the minimum), its first characters up to
22 bytes, C<_> and 8 hex digits of the md5 of the whole name. C<on_delete> and
C<on_update> are the relationship's own where it declares them (C<exists>, so
C<< on_delete =E<gt> undef >> or C<''> declares "no action" and switches the
derivation off); where it does not, they are derived from the other side, as
L<DBIO::Relationship::Base> describes: a C<has_many> over the same columns with
C<cascade_delete> makes C<ON DELETE CASCADE>, one with C<cascade_copy> C<ON
UPDATE CASCADE>. The ORM deletes the parent first (C<cascade_delete> runs after
the requested delete), so a key without the action would refuse to delete a
parent that has children. Written: C<NO ACTION>, C<CASCADE>, C<SET NULL>,
C<SET DEFAULT>; C<RESTRICT>, an empty or an absent value write no clause
(C<RESTRICT> is a syntax error on Firebird and what it reports for a key
without one); anything else dies, and so does C<< is_deferrable =E<gt> 1 >>
(Firebird has no deferrable constraints). Relationships
that declare one key write it once; one key declared with different actions
dies. A key must point at columns that are a primary key or a unique
constraint; otherwise the server says so ("could not find UNIQUE or PRIMARY
KEY constraint ... with specified columns"). The diff creates these for a new
table and writes DROP / ADD CONSTRAINT for a difference on an existing one:
L<DBIO::Firebird::Diff::Constraint>.

A table name with a dot (C<< table => 'other.t' >>) dies with a
C<DBIO::Exception>: Firebird has no schemas before version 6, so the dot would
become part of a literal name. A literal name (C<< table(\'x') >>) is SQL as
written. A column of C<data_type> C<bit> or C<enum> dies as well: Firebird has
no type for a bit string of a fixed width (C<BOOLEAN> is one bit, C<BINARY(n)>
counts bytes, so every mapping changes what the size means) and no enumerated
type; the message says C<refused> and names the table and the column.
So do the time zone types (C<timestamptz>, C<timestamp with time zone>, C<time
with time zone>): the server has them from Firebird 4 on, but DBD::Firebird 1.39
cannot bind a value to such a column and reads one back as the text
C<** unknown **> (measured, t/88-timezone-types-dbd-live.t), so a column the ORM
can neither write nor read is not built. C<binary> and C<varbinary> exist from
Firebird 4 on; on a server whose L</server_major_version> is below 4 they are
refused as well, naming the table and the column (when the version cannot be
asked, nothing is refused and the server judges). A C<numeric> or C<decimal>
with more than 18 digits is an INT128 and refused on every server, with table,
column and the reason: DBD::Firebird 1.39 can neither bind nor read it
(t/97-numeric-int128-dbd-live.t). The same refusals reach
C<Deploy-E<gt>diff> and C<upgrade>, which build their target through this method;
the Diff ops write the types of the introspected model and have no check of
their own.

A view with a dot in its name (C<< table => 'other.v' >>) dies like a table
does; a literal name is SQL as written.

C<string> without a C<size> is the text type (C<BLOB SUB_TYPE TEXT>, as in the
core canon), with a C<size> C<VARCHAR(n)>; C<real> is C<DOUBLE PRECISION>.

A column with C<is_unique> (or C<is_single_unique_key>) that a unique constraint
(C<add_unique_constraint>) over exactly that column covers gets no
C<CREATE UNIQUE INDEX> of its own: the constraint has its index, so the table
holds one, not two.

Indexes come from the canonical index declaration of the result source
(C<idx>, C<indices>; L<DBIO::ResultSource/index_declarations_for>), plain or
unique, with the columns as given. An index over exactly the columns, in the
same order, of the primary key or of a unique constraint written here, or (when
it is not unique) of a foreign key written here, is not built a second time: the
server has an index for each of those. A unique index over a foreign
key's columns is built; the target model of the diff is deployed
through this method. The C<firebird> block must be empty (C<< firebird =E<gt> {} >>):
an expression index (C<COMPUTED BY>), a partial one or a descending one is not
read back by L<DBIO::Firebird::Introspect>, so the diff could not hold it, and
it is refused with a C<DBIO::Exception>, like a C<type> other than C<unique>,
C<options>, and an entry that carries only another driver's block.

