def pv(name, src, shape, pyargs, plopt, frame=None, flatten=True, in_shape='hoa', out=None):
    """pivot_table through pandas; the result is flattened to AoH (or HoA)."""
    fr = pdata if frame is None else frame
    r = fr.pivot_table(**pyargs)
    idx = r.index.names
    cols = list(r.columns)
    r2 = r.copy()
    r2.columns = flat(cols)
    if idx != [None]:
        r2 = r2.reset_index()
    else:
        r2 = r2.reset_index(drop=True)
    r2.columns = [str(c) for c in r2.columns]
    exp = {'aoh': aoh, 'hoa': hoa}[shape](r2)
    emit(name, src, [{'hoa': hoa(fr), 'aoh': aoh(fr)}[in_shape]], plopt, shape, exp, 'pivot')


