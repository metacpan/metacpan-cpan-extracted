package targets.

=item * C<< $msg->desired_state() >> / C<< $msg->desired_state($value) >>

Type: C<Enum> (L<Google::Cloud::Osconfig::V1beta::DesiredState>)

The desired_state the agent should maintain for this package. The
default is to ensure the package is installed.

=item * C<< $msg->manager() >> / C<< $msg->manager($value) >>

Type: C<Enum> (L<Google::Cloud::Osconfig::V1beta::Package::Manager>)

