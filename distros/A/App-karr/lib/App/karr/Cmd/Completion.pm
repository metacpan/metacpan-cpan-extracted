=head1 NAME

App::karr::Cmd::Completion - Generate shell completion scripts for bash, zsh, and fish

=head1 VERSION

version 0.601

=head1 SYNOPSIS

    karr completion bash
    karr completion zsh > "${fpath[1]}/_karr"
    karr completion fish | source

=head1 DESCRIPTION

Prints a static shell completion script for bash, zsh, or fish, generated from
the command table in L<App::karr> and the option declarations MooX::Options
exposes on every command class. The script is static: it embeds the command
names, option names, and fixed value lists, and never invokes C<karr> at
completion time, so it works even where the board is not reachable.

The value lists are the cheap, fixed ones: the C<--sort> fields and the default
priorities. Board-specific values (statuses, tags, task ids) are deliberately
not embedded -- they are per-board configuration, and a static script has no
board to read.

