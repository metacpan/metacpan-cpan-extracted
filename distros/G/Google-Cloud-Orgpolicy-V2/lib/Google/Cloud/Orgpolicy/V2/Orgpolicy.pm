Type: C<Message> (L<Google::Protobuf::Timestamp::Timestamp>)

Output only. The time stamp this was previously updated. This
represents the last time a call to `CreatePolicy` or `UpdatePolicy` was
made for that policy.

=item * C<< $msg->rules() >> / C<< $msg->rules($value) >>

Type: C<Message> (L<Google::Cloud::Orgpolicy::V2::Orgpolicy::PolicySpec::PolicyRule>)

In policies for boolean constraints, the following requirements apply:

  - There must be one and only one policy rule where condition is unset.
  - Boolean policy rules with conditions must set `enforced` to the
    opposite of the policy rule without a condition.
  - During policy evaluation, policy rules with conditions that are
    true for a target resource take precedence.

=item * C<< $msg->inherit_from_parent() >> / C<< $msg->inherit_from_parent($value) >>

Type: C<Bool>

Determines the inheritance behavior for this policy.

If `inherit_from_parent` is true, policy rules set higher up in the
hierarchy (up to the closest root) are inherited and present in the
effective policy. If it is false, then no rules are inherited, and this
policy becomes the new root for evaluation.
This field can be set only for policies which configure list constraints.

=item * C<< $msg->reset() >> / C<< $msg->reset($value) >>

Type: C<Bool>

Ignores policies set above this resource and restores the
`constraint_default` enforcement behavior of the specific constraint at
this resource.
This field can be set in policies for either list or boolean
constraints. If set, `rules` must be empty and `inherit_from_parent`
must be set to false.

=back

