=item * C<< $msg->task() >> / C<< $msg->task($value) >>

Type: C<Message> (L<Google::Cloud::Tasks::V2beta3::Task::Task>)

Required. The task to add.

Task names have the following format:
`projects/PROJECT_ID/locations/LOCATION_ID/queues/QUEUE_ID/tasks/TASK_ID`.
The user can optionally specify a task
[name][google.cloud.tasks.v2beta3.Task.name]. If a name is not specified
then the system will generate a random unique task id, which will be set in
the task returned in the [response][google.cloud.tasks.v2beta3.Task.name].

If [schedule_time][google.cloud.tasks.v2beta3.Task.schedule_time] is not
set or is in the past then Cloud Tasks will set it to the current time.

Task De-duplication:

Explicitly specifying a task ID enables task de-duplication.  If
a task's ID is identical to that of an existing task or a task
that was deleted or executed recently then the call will fail
with [ALREADY_EXISTS][google.rpc.Code.ALREADY_EXISTS].
The IDs of deleted tasks are not immediately available for reuse.  It can
take up to 24 hours (or 9 days if the task's queue was created using a
queue.yaml or queue.xml) for the task ID to be released and made available
again.

Because there is an extra lookup cost to identify duplicate task
names, these [CreateTask][google.cloud.tasks.v2beta3.CloudTasks.CreateTask]
calls have significantly increased latency. Using hashed strings for the
task id or for the prefix of the task id is recommended. Choosing task ids
that are sequential or have sequential prefixes, for example using a
timestamp, causes an increase in latency and error rates in all
task commands. The infrastructure relies on an approximately
uniform distribution of task ids to store and serve tasks
efficiently.

