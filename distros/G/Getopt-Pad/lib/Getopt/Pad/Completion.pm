use v5.26;
use Object::Pad;

class Getopt::Pad::Completion :strict(params) {
	use Carp           qw(croak);
	use File::Basename qw(basename);
	use List::Util     qw(min);

	our $VERSION = '0.02';

	use constant SHELLS         => ['bash', 'zsh'];
	use constant SHELL_VARIABLE => 'GETOPT_PAD_COMPLETE';
	use constant INDEX_VARIABLE => 'GETOPT_PAD_COMPLETE_INDEX';

	# The answer to one request starts with a directive line telling the
	# shell which of its own completions to add (files, dirs or none),
	# followed by one candidate per line.
	use constant NO_DIRECTIVE => 'none';

	field $spec        :param;
	field $programName :param = undef;

	ADJUST {
		$programName //= basename($0);
	}

	# The shell scripts are thin: on every tab they run the program with
	# SHELL_VARIABLE set, the index of the word under the cursor in
	# INDEX_VARIABLE, and the words after the program name as arguments,
	# and print what comes back.
	my %scriptTemplate = (
		bash => <<'BASH',
# bash completion for {{prog}}, generated by Getopt::Pad.
# Install it as ~/.local/share/bash-completion/completions/{{prog}} or
# source it from your ~/.bashrc:
#   {{prog}} --create-completions bash > ~/.local/share/bash-completion/completions/{{prog}}

_{{ident}}_completion() {
	local -a words=()
	local cword=0 index word join=0

	# Bash splits words at '=' (COMP_WORDBREAKS); glue --name=value back together.
	for ((index = 0; index < ${#COMP_WORDS[@]}; index++)); do
		word=${COMP_WORDS[index]}
		if [[ $word == '=' && ${#words[@]} -gt 0 ]]; then
			words[${#words[@]}-1]+='='
			join=1
		elif (( join )); then
			words[${#words[@]}-1]+=$word
			join=0
		else
			words+=("$word")
		fi
		(( index == COMP_CWORD )) && cword=$(( ${#words[@]} - 1 ))
	done

	local IFS=$'\n'
	local -a lines
	mapfile -t lines < <({{shellVariable}}=bash {{indexVariable}}=$(( cword - 1 )) "${words[0]}" "${words[@]:1}" 2>/dev/null)

	# The program answers with whole words; bash only replaces the part
	# after the last '=', so strip what it keeps.
	local directive=${lines[0]}
	local cur=${COMP_WORDS[COMP_CWORD]}
	local prefix=${words[cword]%"$cur"}
	COMPREPLY=("${lines[@]:1}")
	COMPREPLY=("${COMPREPLY[@]#"$prefix"}")

	case $directive in
		files) compopt -o filenames 2>/dev/null; COMPREPLY+=($(compgen -f -- "$cur")) ;;
		dirs)  compopt -o filenames 2>/dev/null; COMPREPLY+=($(compgen -d -- "$cur")) ;;
	esac
}

complete -F _{{ident}}_completion {{prog}}
BASH
		zsh => <<'ZSH',
#compdef {{prog}}
# zsh completion for {{prog}}, generated by Getopt::Pad.
# Install it as _{{prog}} in a directory on your $fpath or source it from
# your ~/.zshrc:
#   {{prog}} --create-completions zsh > ~/.zsh/completions/_{{prog}}

_{{ident}}_completion() {
	local -a lines
	lines=("${(@f)$({{shellVariable}}=zsh {{indexVariable}}=$(( CURRENT - 2 )) "${words[1]}" "${(@)words[2,-1]}" 2>/dev/null)}")

	local directive=${lines[1]}
	shift lines
	(( ${#lines} )) && compadd -- "${lines[@]}"

	case $directive in
		files) compset -P '*='; _files ;;
		dirs)  compset -P '*='; _files -/ ;;
	esac
}

if [[ $zsh_eval_context[-1] == loadautofunc ]]; then
	_{{ident}}_completion "$@"
else
	compdef _{{ident}}_completion {{prog}}
fi
ZSH
	);

	method renderScript($shell) {
		my $template = $scriptTemplate{$shell // ''} // croak(sprintf("Getopt::Pad: no completion script for shell '%s'", $shell // ''));
		my %vars = (
			prog          => $programName,
			ident         => $programName =~ s/\W/_/gr,
			shellVariable => SHELL_VARIABLE,
			indexVariable => INDEX_VARIABLE,
		);
		return $template =~ s/\{\{(\w+)\}\}/$vars{$1}/gr;
	}

	method renderCandidates($words, $index) {
		return join("\n", $self->candidates($words, $index)) . "\n";
	}

	# The directive and the candidates for the word at $index of the
	# command line $words (the words after the program name). The word
	# under the cursor may be partial or missing; the words before it
	# decide the Level, and whether an Option is waiting for its value.
	method candidates($words, $index) {
		croak(sprintf('Getopt::Pad: the completion index must be a non-negative integer, not %s', $index // 'undef')) if ($index // '') !~ /\A\d+\z/;

		my $current = $words->[$index] // '';
		my $state   = $self->walk([$words->@[0 .. min($index, scalar $words->@*) - 1]]) // return (NO_DIRECTIVE);
		my $level   = $state->{level};

		my $pending = $state->{valueOption};
		return $self->valueCandidates($pending, $current, '') if defined $pending && !($pending->optionalValue && $current =~ /^-/);

		if (!$state->{optionsEnded} && $current =~ /^(--[^=]+)=(.*)$/s) {
			my ($spelling, $partial) = ($1, $2);
			my $option = $self->longOption($level, $spelling) // return (NO_DIRECTIVE);
			return (NO_DIRECTIVE) if !$option->type->takesValue;
			return $self->valueCandidates($option, $partial, $spelling . '=');
		}
		return $self->optionCandidates($level, $current) if !$state->{optionsEnded} && $current =~ /^-/;
		return (NO_DIRECTIVE, grep { $self->startsWith($_, $current) } $level->commandNames) if $level->hasCommands;

		my @args = $level->args;
		my $arg  = $args[$state->{positionals}] // (@args && $args[-1]->multiple ? $args[-1] : undef);
		return ($arg->type->completes // NO_DIRECTIVE) if defined $arg;
		return $state->{optionsEnded} ? (NO_DIRECTIVE) : $self->optionCandidates($level, $current);
	}

	# Replay the finished words: descend into the named commands, count the
	# positionals, and remember an Option that still waits for its value.
	# Returns undef when the words name an unknown command.
	method walk($words) {
		my %state = (level => $spec->root, positionals => 0, optionsEnded => 0, valueOption => undef);

		foreach my $word ($words->@*) {
			my $pending = delete $state{valueOption};
			next if defined $pending && !($pending->optionalValue && $word =~ /^-/);

			if (!$state{optionsEnded} && $word eq '--') {
				$state{optionsEnded} = 1;
				next;
			}
			if (!$state{optionsEnded} && $word =~ /^-/) {
				$state{valueOption} = $self->optionAwaitingValue($state{level}, $word);
				next;
			}
			if ($state{level}->hasCommands) {
				$state{level} = $state{level}->command($word) // return undef;
				next;
			}
			$state{positionals}++;
		}

		return \%state;
	}

	# The Option that takes the word after $word as its value, or undef when
	# the word carries its value itself, is a flag, or is unknown.
	method optionAwaitingValue($level, $word) {
		return undef if $word =~ /^--[^=]+=/;
		if ($word =~ /^--/) {
			my $option = $self->longOption($level, $word) // return undef;
			return $option->type->takesValue ? $option : undef;
		}

		# A cluster of single-letter names: the first one taking a value
		# swallows the rest of the cluster, or the next word if none is left.
		my @letters = split //, substr($word, 1);
		foreach my $position (0 .. $#letters) {
			my $option = $self->optionBySpelling($level, $letters[$position]) // next;
			next if !$option->type->takesValue;
			return $position == $#letters ? $option : undef;
		}
		return undef;
	}

	method longOption($level, $spelling) {
		my $name = $spelling =~ s/^--//r;
		return $self->optionBySpelling($level, $name) // do {
			my $negated = $name =~ s/^no-//r;
			my $option  = $self->optionBySpelling($level, $negated);
			defined $option && $option->negatable ? $option : undef;
		};
	}

	method optionBySpelling($level, $name) {
		foreach my $option ($level->options) {
			return $option if grep { $_ eq $name } $option->name, $option->aliases;
		}
		return undef;
	}

	method optionCandidates($level, $partial) {
		my @spellings;
		foreach my $option (grep { !$_->hidden } $level->options) {
			foreach my $name ($option->name, $option->aliases) {
				push @spellings, length $name == 1 ? "-$name" : "--$name";
				push @spellings, "--no-$name" if $option->negatable && length $name > 1;
			}
		}
		return (NO_DIRECTIVE, sort grep { $self->startsWith($_, $partial) } @spellings);
	}

	method valueCandidates($option, $partial, $prefix) {
		my $directive = $option->type->completes // NO_DIRECTIVE;
		return ($directive, map { $prefix . $_ } sort grep { $self->startsWith($_, $partial) } $option->validValues);
	}

	method startsWith($string, $prefix) {
		return index($string, $prefix) == 0 ? 1 : 0;
	}
}

1;

__END__

=encoding utf8

=head1 NAME

Getopt::Pad::Completion - shell completion scripts and their answers

=head1 DESCRIPTION

Both halves of shell completion for one Spec. renderScript($shell) returns the bash or zsh script the C<--create-completions> trigger prints: a thin function that, on every tab, runs the program again with the GETOPT_PAD_COMPLETE environment variable set to the shell name, GETOPT_PAD_COMPLETE_INDEX set to the index of the word under the cursor, and the words after the program name as arguments. GetOptions notices the variable and prints what candidates($words, $index) returns instead of parsing: a directive line (C<files>, C<dirs> or C<none>) telling the shell which of its own path completions to add, then one candidate per line. The candidates come from replaying the finished words through the Spec (commands descend a Level, options that take a value swallow the next word), and cover command names, the visible option spellings of the Level, the values an Option's C<valid> list allows (static or produced by its coderef), and the type's path completion.

Part of the L<Getopt::Pad> distribution; see its documentation for the user-facing API.

