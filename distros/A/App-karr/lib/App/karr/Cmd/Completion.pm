# ABSTRACT: Generate shell completion scripts for bash, zsh, and fish

package App::karr::Cmd::Completion;
our $VERSION = '0.601';
use Moo;
use MooX::Cmd;
use MooX::Options (
  usage_string => 'USAGE: karr completion bash|zsh|fish',
);
use App::karr;
use App::karr::Config;
use App::karr::Role::CliArgs;
use App::karr::Role::ExitCodes;
use Module::Runtime qw( use_module );

with 'App::karr::Role::CliArgs', 'App::karr::Role::ExitCodes';


sub execute {
  my ( $self, $args_ref, $chain_ref ) = @_;

  $self->check_positional_args( $args_ref, 1 );
  my ($shell) = $self->positional_args($args_ref);
  die "Usage: karr completion bash|zsh|fish\n"
    unless defined $shell && length $shell;
  $self->usage_error("unknown shell '$shell' (use bash, zsh, or fish)")
    unless $shell =~ /\A(?:bash|zsh|fish)\z/;

  my @command_data = $self->_command_data;
  my $commands = \@command_data;
  my $script =
      $shell eq 'bash' ? $self->_bash_script($commands)
    : $shell eq 'zsh'  ? $self->_zsh_script($commands)
    :                    $self->_fish_script($commands);
  print $script;
}

# The command table as hashes: name, description, and the class that implements
# it. Aliases are included (agentname, getrefs, setrefs), each carrying the
# description of the spelling it aliases, so completion offers every spelling
# the CLI accepts.
sub _command_data {
  my ($self) = @_;

  my $classes = App::karr->_build_command_commands( {} );
  my @out;
  for my $row ( App::karr->command_table ) {
    my ( $name, $desc ) = @$row;
    my $class = $classes->{$name} or next;
    push @out, { name => $name, desc => $desc, class => $class };
  }
  return sort { $a->{name} cmp $b->{name} } @out;
}

# The options of one command class as hashes: dashed name, --long spelling,
# short spelling, value format, and doc. --help is added by hand: MooX::Options
# declares it outside _options_data (describe_options adds it), and every
# command accepts it, so completion must offer it even though the option table
# does not. A negatable option (--color) also gets its --no- spelling.
sub _options_for {
  my ( $self, $class ) = @_;

  use_module($class);
  my %data = $class->_options_data;
  my @opts;
  for my $name ( sort keys %data ) {
    my $d = $data{$name};
    push @opts, {
      name   => $name,
      long   => '--' . $name,
      short  => defined $d->{short} ? '-' . $d->{short} : undef,
      format => $d->{format},
      doc    => $d->{doc},
    };
    if ( $d->{negatable} ) {
      push @opts, {
        name   => "no-$name",
        long   => "--no-$name",
        short  => undef,
        format => undef,
        doc    => "Negate --$name",
      };
    }
  }
  push @opts, {
    name   => 'help',
    long   => '--help',
    short  => '-h',
    format => undef,
    doc    => 'Show help',
  };
  return @opts;
}

# The fixed value list for an option, if it has one. Everything here is cheap
# and static: the --sort fields and the default priorities. Board-specific
# values are deliberately absent (see DESCRIPTION).
sub _value_list {
  my ( $self, $cmd, $opt ) = @_;

  return [qw( id title status priority created updated due )] if $opt eq 'sort';
  return [ @{ App::karr::Config->default_config->{priorities} } ]
    if $opt eq 'priority';
  return undef;
}

# --- bash ---------------------------------------------------------------

sub _bash_script {
  my ( $self, $commands ) = @_;

  my $commands_list = join ' ', map { $_->{name} } @$commands;
  my @root_opts = $self->_options_for('App::karr');
  my @global = map { $_->{long} } @root_opts;
  push @global, map { $_->{short} } grep { $_->{short} } @root_opts;
  my $global_opts = join ' ', @global;

  my %by_class;
  for my $cmd (@$commands) {
    push @{ $by_class{ $cmd->{class} } }, $cmd->{name};
  }

  my $out = '';
  $out .= "# bash completion for karr\n";
  $out .= "# Generated by `karr completion bash` -- static, never calls karr.\n";
  $out .= "\n";
  $out .= "_karr() {\n";
  $out .= "  local cur prev cmd\n";
  $out .= "  COMPREPLY=()\n";
  $out .= "  cur=\"\${COMP_WORDS[COMP_CWORD]}\"\n";
  $out .= "  prev=\"\${COMP_WORDS[COMP_CWORD-1]}\"\n";
  $out .= "\n";
  $out .= "  # The subcommand, if any: the first word that names one. Option\n";
  $out .= "  # values are skipped because they are not command names.\n";
  $out .= "  local commands=\"$commands_list\"\n";
  $out .= "  local i word\n";
  $out .= "  for (( i = 1; i < COMP_CWORD; i++ )); do\n";
  $out .= "    word=\"\${COMP_WORDS[i]}\"\n";
  $out .= "    case \" \$commands \" in\n";
  $out .= "      *\" \$word \"*) cmd=\"\$word\"; break ;;\n";
  $out .= "    esac\n";
  $out .= "  done\n";
  $out .= "\n";
  $out .= "  # Value completion for options with a fixed value list.\n";
  $out .= "  case \"\$prev\" in\n";
  my %seen_values;
  for my $cmd (@$commands) {
    for my $opt ( $self->_options_for( $cmd->{class} ) ) {
      my $values = $self->_value_list( $cmd->{name}, $opt->{name} );
      next unless $values;
      next if $seen_values{ $opt->{long} }++;
      $out .= "    $opt->{long})\n";
      $out .= "      COMPREPLY=( \$(compgen -W \"@$values\" -- \"\$cur\") )\n";
      $out .= "      return 0\n";
      $out .= "      ;;\n";
    }
  }
  $out .= "  esac\n";
  $out .= "\n";
  $out .= "  if [[ -z \"\$cmd\" ]]; then\n";
  $out .= "    COMPREPLY=( \$(compgen -W \"\$commands $global_opts\" -- \"\$cur\") )\n";
  $out .= "    return 0\n";
  $out .= "  fi\n";
  $out .= "\n";
  $out .= "  case \"\$cmd\" in\n";
  for my $class ( sort keys %by_class ) {
    my @opts = $self->_options_for($class);
    my @words = map { $_->{long} } @opts;
    push @words, map { $_->{short} } grep { $_->{short} } @opts;
    $out .= "    " . join( '|', @{ $by_class{$class} } ) . ")\n";
    $out .= "      COMPREPLY=( \$(compgen -W \"@words\" -- \"\$cur\") )\n";
    $out .= "      ;;\n";
  }
  $out .= "  esac\n";
  $out .= "}\n";
  $out .= "\n";
  $out .= "complete -F _karr karr\n";
  return $out;
}

# --- zsh ----------------------------------------------------------------

sub _zsh_script {
  my ( $self, $commands ) = @_;

  my %by_class;
  for my $cmd (@$commands) {
    push @{ $by_class{ $cmd->{class} } }, $cmd->{name};
  }

  my $out = '';
  $out .= "#compdef karr\n";
  $out .= "\n";
  $out .= "# zsh completion for karr\n";
  $out .= "# Generated by `karr completion zsh` -- static, never calls karr.\n";
  $out .= "\n";
  $out .= "_karr() {\n";
  $out .= "  local -a commands\n";
  $out .= "  commands=(\n";
  for my $cmd (@$commands) {
    $out .= "    " . $self->_zsh_quote( $cmd->{name} . ':' . $cmd->{desc} ) . "\n";
  }
  $out .= "  )\n";
  $out .= "  local -a names\n";
  $out .= "  names=( " . join( ' ', map { $_->{name} } @$commands ) . " )\n";
  $out .= "\n";

  # The root context (no subcommand yet) offers both the command names and the
  # root's own options, the same pair bash and fish embed there. _describe adds
  # the commands; _arguments adds the options.
  my @root_specs = map { $self->_zsh_spec( $_, '' ) } $self->_options_for('App::karr');
  my $root_body = "    _describe -t commands 'karr command' commands\n";
  $root_body .= "    _arguments \\\n";
  for my $i ( 0 .. $#root_specs ) {
    my $comma = $i == $#root_specs ? '' : ' \\';
    $root_body .= "      $root_specs[$i]$comma\n";
  }
  $root_body .= "    return\n";

  $out .= "  if (( CURRENT == 2 )); then\n";
  $out .= $root_body;
  $out .= "  fi\n";
  $out .= "\n";
  $out .= "  # The subcommand, if any: the first word that names one.\n";
  $out .= "  local cmd\n";
  $out .= "  local i word\n";
  $out .= "  for (( i = 2; i < CURRENT; i++ )); do\n";
  $out .= "    word=\"\${words[i]}\"\n";
  $out .= "    case \" \${names[*]} \" in\n";
  $out .= "      *\" \$word \"*) cmd=\"\$word\"; break ;;\n";
  $out .= "    esac\n";
  $out .= "  done\n";
  $out .= "\n";
  $out .= "  if [[ -z \"\$cmd\" ]]; then\n";
  $out .= $root_body;
  $out .= "  fi\n";
  $out .= "\n";
  $out .= "  case \"\$cmd\" in\n";
  for my $class ( sort keys %by_class ) {
    $out .= "    " . join( '|', @{ $by_class{$class} } ) . ")\n";
    $out .= "      _arguments \\\n";
    my @specs = map { $self->_zsh_spec( $_, $by_class{$class}[0] ) }
      $self->_options_for($class);
    for my $i ( 0 .. $#specs ) {
      my $comma = $i == $#specs ? '' : ' \\';
      $out .= "        $specs[$i]$comma\n";
    }
    $out .= "      ;;\n";
  }
  $out .= "  esac\n";
  $out .= "}\n";
  $out .= "\n";
  $out .= "compdef _karr karr\n";
  return $out;
}

# One _arguments spec for one option. A boolean is '--opt[doc]'; a value-taking
# option appends ':name:' and, when the option has a fixed value list, the list
# in parentheses. The short spelling is its own spec.
sub _zsh_spec {
  my ( $self, $opt, $cmd ) = @_;

  my $values = $self->_value_list( $cmd, $opt->{name} );
  my $action = $values ? '(' . join( ' ', @$values ) . ')' : '';
  my $spec = $self->_zsh_quote( '--' . $opt->{name} . '[' . ( $opt->{doc} // '' ) . ']' );
  if ( defined $opt->{format} ) {
    $spec = $self->_zsh_quote(
      '--' . $opt->{name} . '[' . ( $opt->{doc} // '' ) . ']:' . $opt->{name} . ':' . $action );
  }
  if ( defined $opt->{short} ) {
    my $short = $self->_zsh_quote( $opt->{short} . '[' . ( $opt->{doc} // '' ) . ']' );
    if ( defined $opt->{format} ) {
      $short = $self->_zsh_quote(
        $opt->{short} . '[' . ( $opt->{doc} // '' ) . ']:' . $opt->{name} . ':' . $action );
    }
    $spec .= ' ' . $short;
  }
  return $spec;
}

# Single-quote for zsh, escaping embedded single quotes the way bash does.
sub _zsh_quote {
  my ( $self, $s ) = @_;
  $s =~ s/'/'"'"'/g;
  return "'$s'";
}

# --- fish ---------------------------------------------------------------

sub _fish_script {
  my ( $self, $commands ) = @_;

  my %by_class;
  for my $cmd (@$commands) {
    push @{ $by_class{ $cmd->{class} } }, $cmd->{name};
  }

  my %root_names = map { $_->{name} => 1 } $self->_options_for('App::karr');

  my $out = '';
  $out .= "# fish completion for karr\n";
  $out .= "# Generated by `karr completion fish` -- static, never calls karr.\n";
  $out .= "\n";
  $out .= "complete -c karr -f\n";
  for my $opt ( $self->_options_for('App::karr') ) {
    $out .= $self->_fish_opt_spec( $opt, undef );
  }
  for my $cmd (@$commands) {
    $out .= "complete -c karr -n '__fish_use_subcommand' -a "
      . $self->_fish_quote($cmd->{name}) . ' -d '
      . $self->_fish_quote($cmd->{desc}) . "\n";
  }
  for my $class ( sort keys %by_class ) {
    my $cond = '__fish_seen_subcommand_from ' . join( ' ', @{ $by_class{$class} } );
    for my $opt ( $self->_options_for($class) ) {
      next if $root_names{ $opt->{name} };
      $out .= $self->_fish_opt_spec( $opt, $cond );
    }
  }
  return $out;
}

sub _fish_opt_spec {
  my ( $self, $opt, $cond ) = @_;

  my $out = 'complete -c karr';
  $out .= " -n '$cond'" if defined $cond;
  $out .= ' -l ' . $opt->{name};
  $out .= ' -s ' . $opt->{short} if defined $opt->{short};
  my $values = $self->_value_list( undef, $opt->{name} );
  $out .= ' -a "' . join( ' ', @$values ) . '"' if $values;
  $out .= ' -d ' . $self->_fish_quote( $opt->{doc} // '' );
  return $out . "\n";
}

# Single-quote for fish, escaping embedded single quotes with a backslash.
sub _fish_quote {
  my ( $self, $s ) = @_;
  $s =~ s/'/\\'/g;
  return "'$s'";
}

1;

