=item C<--context|-C> PATH

One or more files to submit with your code review file that provide
additional context for the LLM during the review.

=item C<--email|-e> EMAIL

Override the author email. Defaults to C<user.email> from your global
git config.

=item C<--finalize-annotations|-F>

See L</THE REVIEW WORKFLOW>

=item C<--force|-f>

Overwrite an existing project. Without this flag, the command dies if a
C<Makefile> already exists in the target directory.

=item C<--github-user|-g> USER

Override the GitHub username used to construct repository URLs in
C<buildspec.yml>. Defaults to C<user.github> from your global git config.

=item C<--import|-I> path

A path that contains C<.pm> or C<.pl> files for importing into the
project. You can specify multiple paths. You cannot use C<--stub> and
C<--import> together.

Example:

 cmb --module Foo::Bar -I ~/foo-bar/lib -I ~/foo-bar/bin

=over 8

=item * The primary module must be determinable from either directory
name or supplied using the C<--module> option. The corresponding
module file must exist beneath one of the import paths.  For example,
C<Foo::Bar> must be found as F<Foo/Bar.pm>.

=item * The F<Makefile> will automatically attempt to substitute the
token C<E<64>PACKAGE_VERSIONE<64>> inside your C<.pl.in> or C<.pm.in>
files with the current semantic version in the F<VERSION> file. If you
want to use that for versioning your scripts and modules add the token
as shown below:

 C<our $VERSION = 'E<64>PACKAGE_VERSIONE<64>';>

=back

=item C<--installdir|-i> DIR

Directory in which to create the project. When supplied, this overrides
the configured or command-line C<basedir>. The directory is created if
it does not exist.

Example:

  cmb --installdir ~/git/My-Module

The install directory should include the project name.

I<Note: C<--installdir> overrides C<--basedir>>.

=item C<--max-diff-files> LIMIT

The maximum number of changed files included in the release artifact
that may be uploaded to the LLM when generating release notes. Set to
C<0> for no limit.

default: 50

=item C<--max-tokens|-t> TOKENS

Maximum number of tokens the LLM may return in a single response.
Higher values reduce the risk of truncated reviews on large files.

default: 4096 (set by L<LLM::API>)

=item C<--model|-M> MODEL

Specifies the model id to use for the C<pod-review> and C<code-review>
commands.

For C<pod-review> the default model is C<claude-haiku-4-5-20251001>.

For C<code-review> the default model is C<claude-sonnet-4-6>.

The Haiku model tends to be better at summarizing documentation and
avoiding unnecessary analysis around edge cases that contribute to
noise.

I<Caution: Both models try hard to find issues to the point that you
will almost never get a clean run when asking for a POD review. When
your POD is complete, accurate and usable it's good enough. Avoid
shaving the yak!>

=item C<--module|-m> MODULE

The Perl module name for the new project, e.g. C<My::New::Module>.
Used to derive the project directory name, source file path, and
tarball name.

You may omit this option when the module name can be determined from
a custom stub file or from the project directory name.

=item C<--prompt|-p> PATH

Path to a text file that will be used to prompt the LLM for a code or pod review.

defaults:

 pod  => .prompts/pod-review.prompt
 code => .prompts/code-review.prompt

=item C<--prompt-profile|-P> NAME

The name of a prompt profile located in the F<.prompts> directory. One
or more profile names may be specified. You need only provide the name
(e.g. cli-tool).

See L</PROMPT PROFILES>

=item C<--resources|-r> github

Currently takes only a single value: 'github' that indicates that the
resources section of F<Makefile.PL> should be populated with GitHub
URL references. Future versions may support additional providers.

=item C<--strict>, C<--no-strict>

Controls how C<resolve-vars> treats an C<@TOKEN@> placeholder that
appears in code but has no value in the environment or C<--vars-file>.
C<--strict> (the default) makes this a fatal error. C<--no-strict>
downgrades it to a warning and leaves the placeholder literal in the
output.

This affects code placeholders only. Placeholders that appear solely in
POD or C<#> comments are always ignored by the missing-value check
regardless of this flag, so C<--no-strict> is not needed merely to
document a token.

=item C<--stub|-s> TYPE|PATH

Controls the module stub used to generate the initial C<.pm.in> source
file. Three forms are accepted:

=over 4

=item * Omitted - uses the default plain class stub (C<class-module.pm.tmpl>).

=item * C<cli> - uses the CLI stub (C<cli-module.pm.tmpl>), which
inherits from L<CLI::Simple> and includes a skeleton C<main>, C<init>,
and a placeholder command.

=item * A file path - uses the specified file as the stub. The file
must exist or the command will die with an error. This allows you to
supply your own template or bootstrap a project around a module you
have already started writing. You can omit the C<--module> option if
you supply your own stub file. See the explanation for the
C<--module> option for details.

=back

When specifying a stub you cannot use the C<--import> option.

=item C<--username|-u> NAME

Override the author name used in the module stub and C<buildspec.yml>.
Defaults to C<user.name> from your global git config.

=item C<--vars-file>

The path to a file containing template variable values used by
C<resolve-vars>.

=back

=head1 THE REVIEW WORKFLOW

C<CPAN::Maker::Bootstrapper> allows you to implement a structured
iterative code review workflow built around JSON review files and
developer-applied disposition annotations. The workflow converges over
several rounds, with each round potentially costing less as noise is
suppressed and findings are resolved.

=head2 Overview

Each review round consists of three steps:

=over 4

=item 1. Run a review

 cmb code-review --prompt-profile cli-tool lib/My/Module.pm

The review is written to a timestamped C<.code> file containing a JSON
object with C<findings>, C<confirmations>, and C<deferred> arrays.

=item 2. Annotate the findings

An annotation is how you mark a finding with a disposition. The
dispositions are used by the LLM during the next review. See L</Dispositions>.

 cmb annotate lib/My/Module.pm

This displays the current annotation state. Apply dispositions with
C<-a> options:

 cmb annotate -a 1:accept -a 2:wrong -a 3:reject -a 4:defer lib/My/Module.pm

You can annotate incrementally across multiple invocations. Each call
shows the updated state so you always know what remains.

Alternatively, use C<update-annotations> to maintain dispositions in an
annotation file rather than on the command line:

 cmb update-annotations lib/My/Module.pm

The first invocation creates an F<.annotate> file for editing. Run the
command again after editing the file to apply those dispositions to the
review.

=item 3. Submit the next review

Once all findings are annotated and code updated if necessary, run the
next review. The bootstrapper automatically finds and submits the
latest annotated review file with your updated code:

 cmb code-review lib/My/Module.pm

Alternatively, use C<--auto-annotate|-A> with the C<annotate> command
to annotate and immediately resubmit in one step:

 cmb annotate -a 1:wrong -a 2:reject --auto-annotate \
   lib/My/Module.pm

The LLM will honor all dispositions from the prior round, confirm
fixes marked C<ACCEPT>, carry forward C<DEFER> items, and suppress
C<REJECT> and C<WRONG> findings. New findings appear without noise
from settled questions.

=back

=head2 Dry Run Mode

Before the prompt and code are submitted for review, the script
displays estimated token usage and cost. The input token count is
obtained from the model's token-counting API using the message that
will actually be submitted, so the input count is accurate. The
output token count, and therefore the final cost, is an estimate.

To stop before submitting the review, use C<--dry-run>. The command
will abort immediately before the message is sent to the LLM.

=head2 Dispositions

Each finding in the annotations file must be given one of the
dispositions described below before the next review can be
submitted. The prompt sent to the LLM is designed around these
dispositions. This helps successive reviews converge by carrying forward the
developer's decisions from earlier rounds.

=over 4

=item ACCEPT

The finding is valid and has been fixed. On the next review the LLM
will confirm the fix is present. If the fix is not found the finding
will be re-raised.

=item REJECT

The finding has been reviewed and dismissed as inapplicable to this
codebase or context. It will not be raised again in subsequent reviews.

=item WRONG

The finding was based on faulty reasoning. The code is correct. The
finding will not be re-raised. Use this when the LLM has misread the
control flow, misunderstood the design intent, or applied an
inappropriate threat model.

=item WRONG-RECONSIDER

Applied automatically at finalization to all findings marked WRONG.
On the first review of the next version the LLM will re-examine the
specific function and code excerpt carefully. If the prior analysis
was still incorrect the finding reverts to WRONG. If the code has
changed and the finding is now valid it is raised as a new finding.
If the model understands specifically why its prior reasoning was
wrong it may mark the finding CONFIRMED.

=item DEFER

The finding is known and acknowledged but not yet addressed. It is
carried forward in the C<deferred> array of each subsequent review
without being treated as a new finding.

=item CONFIRMED

Used for logic confirmations rather than defects. Marks that both the
LLM and the developer agree the code is correct.

=back

=head2 Diminishing Returns and When to Stop

Run the C<annotate> command after each review submission to view the
findings. Each round tends to surface smaller and more obscure issues
as obvious findings are resolved. Despite some fairly aggressive
attempts to create prompts that prevent trivial or obscure findings
you should stop when you see these signals:

=over 4

=item *

All new findings are LOW severity.

=item *

The LLM is re-raising findings already marked WRONG or REJECT,
possibly rephrased (LLMs can and do make mistakes!).

=item *

New findings describe edge cases that cannot occur in normal usage.

=back

When all findings have dispositions and no new substantive issues
appear, the review should be considered complete.

=head2 The Release Artifact

When you are satisfied with the review state, finalize it with
C<--finalize-annotations>:

 cmb annotate --finalize-annotations -a 1:wrong -a 2:reject lib/My/Module.pm

This applies any remaining dispositions, validates that all findings
are annotated, reads the version from the F<VERSION> file, and writes
the versioned release artifact:

 CPAN-Maker-Bootstrapper-1.1.0-REVIEW.json

This file serves as a code review certification for the release - a
machine-readable record of every finding examined, every logic
confirmation made, and every disposition applied before the version
was published. Commit it to the repository alongside your ChangeLog.

All findings marked WRONG are automatically converted to
WRONG-RECONSIDER in the release artifact, prompting careful
re-examination on the first review of the next version rather
than permanent suppression.

=head2 Cost Management

Review cost depends on the selected model, source size, prompt
profiles, and number of findings. Costs generally decrease over
successive rounds as the model spends fewer output tokens
re-explaining suppressed findings.

Use your own prompt profiles (C<--prompt-profile>) to suppress entire
classes of noise before they reach the annotation file. A well-tuned
profile for your application type is the highest-leverage cost
reduction available.

=head2 See Also

L</LLM Commands>, L</PROMPT PROFILES>, L<CPAN::Maker::ConfigReader>

=head1 PROMPT PROFILES

Prompt profiles are additive prompt fragments that customize the review
behavior for specific application types. They are appended to the base
review prompt before submission and are intended to focus the review on
relevant concerns while suppressing noise that does not apply to the
target context.

I<NOTE: Prompts count toward your input token count. Be succinct and
accurate.>

=head2 Using Profiles

Pass one or more profiles using the C<--prompt-profile> option:

  cmb code-review --prompt-profile cli-tool MyModule.pm

Multiple profiles may be combined:

  cmb code-review --prompt-profile cli-tool --prompt-profile security MyModule.pm

Profiles are resolved from the F<.prompts/> directory in the current
project. A profile named C<cli-tool> resolves to
F<.prompts/cli-tool.prompt>. Add project-specific prompt profiles to
F<.prompts/> and commit them with your project.

=head3 Built-in Profiles

The following profile is installed with the distribution:

=over 4

=item cli-tool

Appropriate for single-user developer CLI tools. Suppresses security
findings that assume a multi-user or hostile environment, TOCTOU race
condition findings that assume concurrent invocation, and concerns about
C<qx{}> or C<system()> calls where input originates from the user's own
configuration. Also assumes C<perlcritic> and C<perltidy> are enforced
in the development environment.

=back

=head3 Creating Custom Profiles

A profile is a plain text file in F<.prompts/> containing additional
prompt instructions, one per line. Lines beginning with C<#> are
treated as comments and stripped before submission. Profile
instructions are appended verbatim to the base review prompt.  The
built-in profiles use one instruction per line, typically prefixed
with C<->.

Example F<.prompts/security.prompt>:

  # security profile - add to any review where input handling matters
  - Treat all caller-supplied input as untrusted regardless of source.
  - Flag any use of eval, system, or exec that incorporates external data.
  - Flag missing taint checks on data used in file or system operations.

=head3 Additional Profile Ideas

=over 4

=item library

Focuses on API contract correctness and caller assumptions. Appropriate
for CPAN distributions intended for use by unknown callers.

=item web-application

Treats external input as untrusted. Flags injection risks, authentication
gaps, and session handling concerns.

=item mod-perl-handler

Addresses Apache lifecycle concerns including global state, startup versus
request time initialization, and child process behavior.

=item lambda-function

Focuses on cold start performance, statelessness, and environment variable
handling appropriate for AWS Lambda deployments.

=back

Community contributions of additional profiles are welcome. See
L<https://github.com/rlauer6/CPAN-Maker-Bootstrapper/issues>.

=head1 EXTENDING THE BUILD SYSTEM

The installed F<Makefile> and files under F<.includes/> are managed by
C<CPAN::Maker::Bootstrapper>. They are intentionally write-protected and
may be replaced by C<make update> when the bootstrapper is upgraded.

Project-specific build logic belongs in F<project.mk>, which is always
writable and is never touched by C<make update>. This provides an
upgrade-safe extension point for project-specific targets, variables,
and build ordering.

The managed include files live in the F<.includes/> directory,
where they are write-protected and clearly separated from project
files. The F<Makefile> includes them automatically:

 include .includes/publish.mk
 include .includes/bootstrap.mk
 include .includes/perl.mk
 include .includes/local.mk
 include .includes/help.mk
 include .includes/version.mk
 include .includes/release-notes.mk
 include .includes/git.mk
 include .includes/update.mk
 include .includes/upgrade.mk
 include .includes/bash-completion.mk
 include .includes/modulino.mk

These files are included if they exist:

 include config.mk
 include project.mk
 include extra-files.mk

=head2 Immutability Is a Feature

The managed build system is deliberately B<immutable>: the
F<Makefile>, everything under F<.includes/>, and the generated
F<.pm>/F<.pl> files are write-protected on purpose. This is a feature,
not a restriction. It lets C<make update> replace those files with
newer, better versions without clobbering anything of yours, and it
guarantees that two projects on the same bootstrapper version use the
same managed build rules -- there is no per-project drift hiding in a
locally edited managed rule.

You I<can> override any of it -- these are your files, and nothing stops you
from C<chmod +w> and editing a generated module or a managed include. But
you should not need to, and if you do, C<make update> will overwrite your
change. Every legitimate customization has a sanctioned hook that survives
C<make update>:

=over 4

=item * B<Project-specific targets, rules, and build ordering> --
F<project.mk> (always writable; never touched by C<make update>).

Reach for F<project.mk> when your project needs to do something the
generic build system can't know about, for example:

=over 4

=item * B<Build a companion artifact> the managed build doesn't produce --
generate a F<.pm.in> from a JSON/YAML schema, render documentation, compile
assets, or (as C<Amazon::API> does) build a Storable data file consumed at
runtime.

=item * B<Declare inter-module build order> the scanner can't infer --
C<lib/Foo/Bar.pm: lib/Foo.pm> when one module must be built before another.

=item * B<Deploy or publish> -- an C<scp>/upload/notify target that runs
after C<all>.

=item * B<Extend cleanup> -- a C<clean-local::> double-colon rule to remove
your own generated files, and C<CLEANFILES +=> for anything else.

=back

See L</What Belongs in F<project.mk>> for worked examples of each, and
L</What Does NOT Belong in F<project.mk>> for the line between your extensions
and the managed core.

=item * B<Build-behavior toggles> (dependency scanning, linting, syntax
checking, version-drift strictness) -- make variables set on the command
line or in F<config.mk> (see L</CONFIGURATION> and the variable list below).

=item * B<Template tokens in your source> -- declare them in
C<TEMPLATE_VARS> and let C<cmb resolve-vars> fill them, rather than
hand-editing a generated F<.pm> (see L</Custom Template Tokens>).

=item * B<Extra distribution files> -- list them in F<buildspec.yml>;
C<extra-files.mk> wires them into the tarball automatically.

=item * B<Dependencies the scanner cannot see> -- the sticky C<+> prefix in
F<requires> (see L</Dependencies Management>).

=back

If you find yourself wanting to edit a managed file, check this list first:
the hook you need almost certainly exists, and using it keeps you on the
upgrade path instead of forking the build system.

I<Why the generated F<.pm>/F<.pl> files are read-only:> they are
regenerated from their F<.pm.in>/F<.pl.in> sources when its
prerequisites require regeneration, so any edit you make directly to a
generated F<.pm> would be silently lost on the next C<make>.  The
C<chmod -w> is there to stop you from making that mistake. Edit the
F<.pm.in> source, not the generated F<.pm>.

=head2 How the Makefile Works

The installed F<Makefile> is structured around a few key concepts:

=over 4

=item * B<Source files> live in F<lib/> as F<.pm.in> and in F<bin/> as
F<.pl.in>. The build generates the final F<.pm> and F<.pl> files from
these sources by substituting C<E<64>PACKAGE_VERSIONE<64>> and other
tokens, running syntax checks, and optionally running perltidy and
perlcritic.

=item * B<Sentinel files> - the build uses sentinel files to track
incremental quality-gate state. F<.checked> records successful syntax
and validation checks, F<.tdy> records successful perltidy processing,
and F<.crit> records successful perlcritic processing. Each sentinel is
regenerated only when the source or the prerequisites for that gate
change.

=item * B<Dependency scanning> - C<scandeps-static.pl> scans your
source files and maintains the dependency files used by L<CPAN::Maker>
when generating distribution metadata, including F<requires>,
F<test-requires>, F<recommends>, and F<suggests>. Controlled by
C<SCAN=ON|OFF>.

=item * B<The distribution tarball> is the final output of C<make>.
It is built by C<make-cpan-dist.pl> using F<buildspec.yml>.

=item * B<Inter-module dependency discovery> - the build scans modules
within the distribution and generates F<deps.mk> so C<make> can build
modules in dependency order before syntax checking them. Dependencies
that cannot be inferred automatically may be added in F<project.mk>.

=back

Key build variables you can override on the make command line or in
F<config.mk>:

=over 4

=item C<SCAN=OFF> - skip distribution dependency scanning

=item C<LINT=OFF> - skip perltidy and perlcritic

=item C<SYNTAX_CHECKING=OFF> - skip C<perl -wc> syntax checks

=item C<MIN_PERL_VERSION=5.016> - minimum Perl version for Makefile.PL

=item C<PERLTIDYRC=/path/to/rc> - path to perltidy configuration

=item C<PERLCRITICRC=/path/to/rc> - path to perlcritic configuration

=item C<SKIP_TESTS=1> - interpreted by L<CPAN::Maker>; skips running
the test suite when building the distribution tarball

=item C<PERLWC_SKIP="file1 file2">  - space-separated list of files
to exclude from syntax and POD checks

=item C<POD=extract|remove> - extract POD to a companion F<.pod> file
or strip it entirely from the built F<.pm>

=item C<PERLINCLUDE="-I path"> - additional include paths used during
the C<perl -wc> syntax check. Defaults to C<-I lib -I local/lib/perl5>
for hermetic checking; see L</The local dependency library>.

=item C<CPAN_INSTALLER=cpm|carton> - selects the installer used to
populate F<local/> for hermetic syntax checking. Auto-detected (C<cpm>
preferred) if unset.

=back

Two further toggles, C<CMB_UPDATE_CHECK> and C<CMB_VERSION_DRIFT>, are set
in F<config.mk> rather than on the command line; see L</Automatic Drift and
Update Checks>. F<config.mk> is read on every invocation of C<make> and is
the right place for durable, machine- or project-wide build settings such as
C<SYNTAX_CHECKING=OFF> on a box without an installer.

=head2 What Belongs in F<project.mk>

=over 4

=item Custom targets

Any target specific to your project - generating assets, running
linters, deploying, sending notifications:

 .PHONY: deploy
 deploy: all ## deploy the distribution
     scp $(TARBALL) user@myserver:/opt/cpan

Add C<##> followed by a description to a target definition to include
the target in the output from C<make help>. Because F<project.mk> is
included in C<MAKEFILE_LIST>, project-specific targets are discovered
automatically:

 make help

There is no separate help table to maintain.

=item Inter-module dependencies

If your modules have build-time dependencies on each other, declare
them here rather than modifying the Makefile:

 lib/Foo/Bar.pm: lib/Foo.pm

=item Additional file generation

If your project generates code or configuration from templates beyond
what the standard Makefile handles:

 lib/Foo/Generated.pm.in: schema/foo.json
     perl bin/generate-module.pl $< > $@

=item Project-specific variables

 DEPLOY_HOST = myserver.example.com
 DEPLOY_PATH = /opt/cpan/incoming

=item Extending CLEANFILES

Add project-specific generated files to the cleanup target by
appending to C<CLEANFILES>:

 CLEANFILES += mygenerated.pm config/generated.yml

=item Extending the clean target

  clean-local::
         rm -rf workdir

=item Extending the test recipe

Projects may have development or integration tests that should not be
included in the CPAN distribution. Add them to C<make test> by
extending C<test-local> with a double-colon rule:

 test-local::
     prove -I lib -v xt/

=back

=head2 What Does NOT Belong in F<project.mk>

=over 4

=item * Modifications to existing targets like C<all>, C<clean>, C<requires>

=item * Replacing managed variables such as C<DEPS> or C<CLEANFILES>.

Use documented extension points such as C<CLEANFILES +=> where
provided rather than redefining the managed value.

=item * Anything that duplicates logic already in the managed Makefile

=back

=head2 Custom Template Tokens

The build generates each F<.pm>/F<.pl> from its F<.pm.in>/F<.pl.in> source
by substituting C<E<64>TOKENE<64>> placeholders through C<cmb resolve-vars>.
The standard tokens (C<E<64>PACKAGE_VERSIONE<64>>, C<E<64>MODULE_NAMEE<64>>,
C<E<64>GIT_SHAE<64>>, and the other git-metadata variables) are always
available, but the mechanism is extensible: a project can define its own
tokens without editing any managed file.

To add a token, declare its name in C<TEMPLATE_VARS> (in
F<project.mk>) and provide a value -- as a make variable, an exported
environment variable, or through the variables file passed to
C<resolve-vars>. For example, to stamp a build timestamp:

  # in project.mk
  BUILD_DATE      := $(shell date -u +%Y-%m-%dT%H:%M:%SZ)
  TEMPLATE_VARS   += BUILD_DATE

  # in a .pm.in source
  our $BUILD_DATE = 'E<64>BUILD_DATEE<64>';

C<cmb resolve-vars> then fills C<E<64>BUILD_DATEE<64>> from the value
when its prerequisites require regeneration. The token grammar is
uppercase-only (C<E<64>[A-Z0-9_]+E<64>>), so placeholders never
collide with real Perl such as C<@_> or C<@ISA>.

By default, substitution is B<fail-loud> for placeholders that appear
in live code: if a token has no value, the build stops and names the
offending token rather than silently substituting an empty string.

Placeholders that occur only in POD or comments do not require values.
C<--no-strict> may be used to downgrade a missing live-code value to a
warning and leave the placeholder unchanged.

=head2 Keeping the build system up to date

The following targets manage the lifecycle of the build system itself:

=over 4

=item C<make check-upgrade> / C<make upgrade-check>

Checks MetaCPAN to see if a newer version of
C<CPAN::Maker::Bootstrapper> is available.

=item C<make publish>

Builds the distribution tarball, unpacks it into a temporary directory,
runs its normal C<Makefile.PL>, build, and test sequence, and uploads
the tarball to PAUSE if all checks succeed.

Set the PAUSE credentials with:

 make publish PAUSE_USER=username PAUSE_PASSWORD=password

=item C<make upgrade>

Checks MetaCPAN, installs the latest version via C<cpanm>, then
automatically runs C<make update> to refresh the managed project
files.

=item C<make update>

Copies the managed files from the currently installed bootstrapper
distribution into your project directory. After running, use
C<git diff> to review what changed.

The following files are managed and may be updated:

 Makefile
 .includes/bootstrap.mk
 .includes/perl.mk
 .includes/local.mk
 .includes/git.mk
 .includes/help.mk
 .includes/update.mk
 .includes/upgrade.mk
 .includes/version.mk
 .includes/release-notes.mk
 .includes/bash-completion.mk
 .includes/modulino.mk
 .includes/publish.mk

Your F<project.mk>, F<buildspec.yml>, F<requires>, F<VERSION>, source
files and tests are B<never> touched by C<make update>.

=item C<make cpanm>

Installs C<cpanminus> if it is not already available on your
C<PATH>. Required for C<make upgrade> to work:

 make cpanm && make upgrade

=back

=head2 Automatic Drift and Update Checks

Every build runs two checks before proceeding, so you don't have to
remember to run C<make check-upgrade> yourself:

=over 4

=item *

Is a newer C<CPAN::Maker::Bootstrapper> published on CPAN than the
one installed on this machine?

=item *

Do this project's managed files still match what the I<currently
installed> C<CPAN::Maker::Bootstrapper> would produce?

=back

These are independent questions - your installed bootstrapper can be
fully current while a given project has still drifted from it (most
commonly because the project hasn't been through C<make update>
since you last upgraded), or your bootstrapper itself can be behind
CPAN while every project stays perfectly in sync with it.

I<Drift> can happen for either of two reasons: your installed
C<CPAN::Maker::Bootstrapper> was upgraded since this project last ran
C<make update>, or a managed file was hand-edited despite the
warnings not to (see L</What You Should Never Modify>). C<make>
doesn't try to tell these apart - the fix is the same either way:

 make update

Two variables, set in F<config.mk>, control how strict these checks
are:

=over 4

=item C<CMB_UPDATE_CHECK> (C<ON>|C<OFF>, default C<ON>)

Set to C<OFF> to skip the MetaCPAN lookup - useful in CI or offline
environments where the network call would just fail or slow things
down.

=item C<CMB_VERSION_DRIFT> (C<FAIL>|C<WARN>|C<IGNORE>, default C<FAIL>)

Controls what happens when a project's managed files no longer match
the installed bootstrapper. C<FAIL> stops the build until you run
C<make update>; C<WARN> prints a message and continues; C<IGNORE>
skips the check entirely.

=back

=head2 What You Should Never Modify

The files in F<.includes/> - F<perl.mk>, F<git.mk>, F<help.mk> etc.  -
are managed files that will be overwritten by C<make update>.  Do not
modify managed files directly. Use F<config.mk> for documented build
variables and F<project.mk> for project-specific targets, rules, and
build ordering.

The F<Makefile> itself is also managed and will be overwritten by
C<make update>. Use the documented project-level configuration and
extension files instead.

=head2 Dependencies Management

The build system scans F<.pm.in> and F<.pl.in> source files and
maintains the dependency files used by L<CPAN::Maker> when generating
distribution metadata:

 F<requires>
 F<test-requires>
 F<recommends>
 F<suggests>

Distribution dependency scanning is controlled by C<SCAN>. Set
C<SCAN=OFF> to skip updates to F<requires>, F<test-requires>,
F<recommends>, and F<suggests> for a build; the default is C<ON>.

To prevent an entry from being removed by a rescan, prefix the module
name with C<+>. These entries are sticky and survive all subsequent
scans even if the scanner no longer detects them.  To pin a specific
version, simply edit the version number in the F<requires> file. If
the scanner subsequently detects a different version, the Makefile
will preserve your pinned version. Note that pinned versions are
B<never> updated automatically - if you want to adopt a newer version
you must edit the file manually.

In your requires file:

  +Foo::Bar 1.0    # sticky - survives all rescans
  Baz::Qux  2.5   # version pinned - scanner won't override this version

I<Note: These two mechanisms are independent - C<+> controls whether an entry
survives rescans, while the version number controls what version is
required.>

=head3 The local dependency library

Syntax checking is performed in a I<hermetic> environment: each
generated F<.pm> is compiled with C<perl -wc> against C<lib> and a
project-local library at F<local/lib/perl5> only, with C<PERL5LIB>
explicitly cleared for the check. This ensures a module's dependencies
are actually declared and installed, rather than being satisfied by
chance from whatever happens to be in your C<PERL5LIB> or system
C<@INC>. A dependency that compiles on your machine but is missing
from the declared dependency set will fail the build here instead of
surprising you on a clean install or CI box.

To populate that library, the build installs your declared dependencies into
F<local/> using C<cpm> (preferred) or C<carton>:

  make local # installs requires/recommends/suggests/test-requires into local/lib/perl5

This runs automatically as a prerequisite of the module build, so a
normal C<make> installs dependencies first, then syntax-checks against
them.

C<cpm> is preferred because it supports multiple resolvers directly
from F<build-mirrors>. C<carton> is also supported; see
L</build-mirrors> for its mirror behavior.

The use of a F<build-mirrors> file versus specifying the mirrors in
the dependency files determines the scope of their
use. F<build-mirrors> (and F<cpanfile> mirror declarations) set the
resolvers used for B<every> dependency in the build. To route a
B<single> module to a specific mirror, URL, or distribution -- without
affecting how anything else resolves -- annotate that module's entry
in F<requires> with C<mirror=>, C<url=>, or C<dist=> (see
L</build-mirrors>).

The C<+> prefix has a second use beyond protecting mirror annotations.
Because the check is hermetic, B<a module reached only at runtime will not
be found unless it is declared>. Static scanning (C<scandeps-static.pl>)
cannot see a dependency loaded dynamically -- for example a module pulled
in through a method call rather than a C<use> statement -- so it will never
add it to F<requires>. Declare such modules explicitly with C<+>, which
makes the entry sticky and survives every rescan:

  +Log::Log4perl    # loaded at runtime via a framework call; scanner can't see it

=head3 F<build-mirrors>

When using the preferred CPAN installer (C<cpm>), the build system
reads mirror URLs, one per line, from a F<build-mirrors> file in the
project root and passes each as a resolver. This allows the build to
resolve dependencies against one or more configured CPAN-compatible
repositories, including private DarkPAN repositories.

When C<carton> is used, because it does not support multiple mirrors
when setting the mirror using an environment variable, the build
system will use the first mirror in your F<build-mirrors> file if
present. C<carton> supports multiple mirrors only by specifying them
in the F<cpanfile>.

Entries in F<requires>, F<suggests>, and F<recommends> may carry optional
qualifiers after the version to control where a module resolves from:

  +Foo::Bar 1.0 mirror=https://cpan.openbedrock.net/orepan2
  +Baz::Qux 2.5 url=https://example.com/authors/id/D/DU/DUMMY/Baz-Qux-2.5.tar.gz
  +Xyz::Abc 0.9 dist=Xyz-Distribution

Only C<dist=>, C<url=>, and C<mirror=> are permitted after the version;
anything else is an error. Prefix such entries with the sticky C<+> so the
scanner does not strip the annotation on a later rescan. See L<CPAN::Maker>
for the full format.

=head1 MODULINOS

A modulino is a Perl module that doubles as a runnable script by
checking whether it was invoked directly or loaded as a library:

 package Foo::Bar;

 caller or __PACKAGE__->main;

 sub main {
   ...
   exit 0;
 }

Modulinos are useful for CLI scripts because they encourage
encapsulation, simplify unit testing, and keep logic organized
in named methods rather than inline code.

The C<Makefile> provides a C<modulino> target that generates a wrapper
script for invoking your module. By default it uses C<MODULE_NAME>,
producing a script named after the module:

 make modulino

For a project named C<Foo::Bar> this creates C<bin/foo-bar.in>.
C<make> then builds C<bin/foo-bar> from that source file via a
pattern rule, and the executable ends up in the distribution.

To create a modulino wrapper for a module other than the primary
project module, override C<MODULE_NAME>:

 make modulino MODULE_NAME=Foo::Bar::Buz

This creates C<bin/foo-bar-buz.in> invoking C<Foo::Bar::Buz>.

To give the wrapper a short or memorable name independent of the
module name, set C<ALIAS>:

 make modulino MODULE_NAME=Foo::Bar::Buz ALIAS=fbb

This creates C<bin/fbb.in> which still invokes C<Foo::Bar::Buz>.
C<ALIAS> accepts either a plain name (C<fbb>) or a module-style
name (C<Foo::Bar::Buz>) - colons are converted to hyphens and
the result is lowercased.

The generated wrapper scripts (without the C<.in> suffix) are
automatically added to F<.gitignore> since they are build artifacts.
The C<.in> source files are tracked by git.

=head2 Continuous Integration

CPAN::Maker::Bootstrapper provides a clean-room build path that can be
used locally or from a CI system.

The CI design separates source acquisition from project build
responsibilities:

  source acquisition       caller or CI system
  build environment        builder
  project build            make

A CI system such as GitHub Actions is responsible for checking out the
project. F<builder> then operates on that existing project directory,
installs the required build environment and dependencies, and runs the
project build.

C<make build-ci> provides the corresponding local clean-room build. It
uses the current working tree as its source, copies that tree into a
disposable container build directory, and invokes F<builder> there.

This separation keeps F<builder> independent of repository hosting,
branch selection, and source-control workflow while allowing the same
build mechanism to be used both locally and in CI.

The build lifecycle is:

 builder.env
     |
     v
 builder-pre
     |
     v
 make
     |
     v
 builder-post

F<builder> can run unmodified in GitHub Actions, in another CI runner,
or by hand from the command line.

=head3 Running builder manually

F<builder> operates on an existing project directory. Source acquisition
is deliberately outside its responsibility; the caller must clone,
check out, or otherwise provide the project before invoking F<builder>.

Run it from the root of a project:

  ./builder

or pass the project directory explicitly:

  /builder /path/to/project

The project directory defaults to the current working directory.

F<builder> changes to that directory, installs the build environment and
declared dependencies, loads the project CI environment, and runs the
configured build lifecycle.

For the standard containerized clean-room build, use:

  make build-ci

C<make build-ci> copies the current working tree into a disposable build
environment and invokes F<builder> there. Because it operates on the
current working tree rather than cloning the repository, the build may
include uncommitted and untracked files present on disk.

=head3 Environment variables

F<builder> accepts environment variables that control dependency
installation and build behavior.

=over 4

=item C<INSTALLER>

The command used to install Perl dependencies.

The default is:

  cpm install -g --show-build-log-on-failure --verbose

=item C<NO_ECHO>

Passed through to the generated Makefile when set.

=item C<CMB_VERSION_DRIFT>

Controls how F<builder> handles differences between the installed
CPAN::Maker::Bootstrapper version and the version expected by the
project.

The generated F<builder.env> defaults this to:

  CMB_VERSION_DRIFT=ignore

=back

=head3 F<builder.env>

Before running the project build, F<builder> loads F<builder.env> from
the project root when that file exists.

Variables defined there are exported to the build environment.

A generated project includes:

  CMB_VERSION_DRIFT=ignore
  NO_ECHO=

F<builder.env> provides a project-local place to customize CI build
behavior without modifying F<builder> itself.

=head3 Builder lifecycle hooks

F<builder> exposes two Makefile hooks around the main project build:

  builder-pre
  builder-post

The build lifecycle is:

  builder.env
      |
  builder-pre
      |
  make
      |
  builder-post

C<builder-pre> runs after F<builder.env> has been loaded and before the
main C<make> invocation.

C<builder-post> runs only after the main build completes successfully.

Generated projects define both targets as empty double-colon targets:

  builder-pre::

  builder-post::

Projects may extend them in F<project.mk> without modifying the managed
Makefile.

For example:

  builder-pre::
          ./prepare-ci-environment

  builder-post::
          ./collect-build-artifacts

These hooks are intended for project-specific CI setup and post-build
work that should remain outside the managed build files.

=head3 C<make build-ci>

C<make build-ci> runs the current project in a disposable containerized
build environment.

Unlike a CI workflow that clones the repository, C<build-ci> uses the
current working tree as its source. The project is mounted read-only,
copied into the container build area, and then passed to F<builder>.

This means the build reflects the files currently present on disk,
including uncommitted changes and untracked files.

The source tree itself is not modified by the container build.

C<make build-ci> accepts the following variables:

  DOCKER_BUILD_IMAGE  - container image used for the build
  DOCKER_CPAN_INSTALLER
                      - dependency installer command used in the container
  BUILD_LOG           - path used for captured build output
  MODULE_NAME         - primary module name passed into the clean-room build

For example:

  make build-ci

or:

  make build-ci DOCKER_BUILD_IMAGE=debian:trixie

The command exits with the status of the container build even though
the output is also written to C<BUILD_LOG>.

=head3 Builder input files

F<builder> recognizes project files that supply additional build
requirements without modifying F<builder> itself.

=over 4

=item F<build-apt-deps>

A whitespace-separated list of additional Debian packages required by
the project build.

F<builder> installs these packages in addition to its standard build
environment before installing Perl dependencies.

For example:

  libxml2-dev
  libpq-dev

=item F<build-mirrors>

A list of CPAN mirror URLs, one per line.

Use this file when the build requires a DarkPAN or another additional
CPAN-compatible repository.

For example:

  https://cpan.openbedrock.net
  https://cpan.metacpan.org

The configured mirrors are used when resolving project dependencies.

=back

These files describe build inputs. For environment variables use
F<builder.env>; for project-specific Makefile behavior use
F<project.mk>.

