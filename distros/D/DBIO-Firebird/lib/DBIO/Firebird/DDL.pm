# Firebird's identifier quoter: ALWAYS quotes. DBIO::SQL::Util::_quote_ident
# leaves a simple name bare, which is right where a bare name folds to lower
# case and wrong here: Firebird folds a bare name to UPPER case and does not
# parse a bare reserved word (year, position, value, type, ...) at all. The
# storage is a quote-everything storage (sql_quote_char '"' on
# Storage::Common, with or without quote_names), so the ORM asks for "artist";
# a table created as `CREATE TABLE artist` is ARTIST and is then
# `Table unknown` (karr k32). The same holds on the way back: the names in an
# introspected model are the server's exact spelling, and a lower-case one
# written bare into a diff statement addresses a different object. So every
# name this distribution emits -- DDL.pm and the three Diff ops -- goes through
# here. An embedded `"` is doubled, per the SQL standard.
sub _firebird_quote_ident {
  my ($name) = @_;
  croak 'DBIO::Firebird::DDL::_firebird_quote_ident: undef identifier'
    unless defined $name;
  $name =~ s/"/""/g;
  return qq{"$name"};
}

# The SQL literal of a column's default_value: a string goes between single
# quotes with each embedded ' doubled (the SQL standard), so "it's" cannot end
# the literal early or let the rest run as SQL (karr k47). A number is quoted
# too, as ever; the server converts it to the column's type. A scalar ref is
# literal SQL by contract and passes unchanged. Only for a default that comes
# from a result class: the Diff ops get theirs from the introspected model,
# i.e. rdb$default_source, which is already a literal.
#
# A BOOLEAN column is the exception to "the server converts" (karr k36):
# Firebird 5.0.4 accepts DEFAULT '0', '1', 0 and 1 on a BOOLEAN in CREATE
# TABLE and then fails every insert that uses the default ("conversion error
# from string"). So for a boolean column the four spellings 0, 1, 'true' and
# 'false' (any case; also as a scalar ref holding just that word) are written
# as TRUE / FALSE, and any other value -- 'f', '', 'yes', 2 -- dies with a
# DBIO::Exception instead of becoming a default that breaks every insert. A
# scalar ref holding anything else is SQL as written (an expression).
sub _firebird_default_literal {
  my ($value, $info, $where) = @_;
  if ($info and is_boolean_type($info->{data_type})) {
    my $plain = ref $value eq 'SCALAR' ? $$value : $value;
    if (!ref $plain) {
      return 'FALSE' if $plain =~ /\A(?:0|false)\z/i;
      return 'TRUE'  if $plain =~ /\A(?:1|true)\z/i;
    }
    DBIO::Exception->throw(sprintf
      q{%sdefault_value '%s' on a boolean column is none of 0, 1, 'true', 'false'; }
      . q{Firebird accepts any other default at CREATE TABLE and then fails every insert that takes it},
      (defined $where ? "$where: " : ''), $plain)
      unless ref $value eq 'SCALAR';
  }
  return $$value if ref $value eq 'SCALAR';
  $value =~ s/'/''/g;
  return "'$value'";
}

# What follows the type in a column definition, in the one order Firebird's
# column clause has: IDENTITY, DEFAULT, NOT NULL (DEFAULT after NOT NULL is
# `Token unknown`). Shared by install_ddl and the CREATE / ADD of the Diff ops
# (karr k46), so a column is spelled the same way wherever it is written.
# $default is SQL text, already a literal.
sub _firebird_column_clauses {
  my (%a) = @_;
  return join '',
    ($a{identity} ? ' GENERATED BY DEFAULT AS IDENTITY' : ()),
    (defined $a{default} ? " DEFAULT $a{default}" : ()),
    ($a{not_null} ? ' NOT NULL' : ());
}

# Whether the server takes IDENTITY on a column of this type (rendered SQL
# text, e.g. 'INTEGER' or 'DECIMAL(9,0)'): "exact number type with zero scale"
# -- SMALLINT, INTEGER, BIGINT, and NUMERIC / DECIMAL with scale 0 (measured on
# Firebird 5.0.4: NUMERIC(9,0), NUMERIC(4,0) and DECIMAL(18,0) are accepted,
# NUMERIC(9,2) and VARCHAR refused).
sub _firebird_identity_type_ok {
  my ($type) = @_;
  return $type =~ /\A(?:SMALLINT|INTEGER|BIGINT)\z/i
      || $type =~ /\A(?:NUMERIC|DECIMAL)\(\d+(?:,\s*0)?\)\z/i;
}

# --- constraints (karr k34) ---------------------------------------------------
#
# Written as ALTER TABLE ... ADD CONSTRAINT after every CREATE TABLE, so the
# order of the tables and a cycle between them do not matter. Shared by
# install_ddl and Diff::Constraint (a table created by upgrade).
#
# Firebird's identifier limit is 63 characters from Firebird 4 on (measured on
# 5.0.4: 63 accepted, 64 "Name longer than database column size") and 31 bytes
# on Firebird 3, the driver's minimum, which is not measured here. Firebird 5
# counts CHARACTERS (measured: 63 two-byte characters accepted, 64 refused);
# Firebird 3's 31 are bytes. A name this module makes up (a foreign key's) is
# therefore kept to 31 BYTES, so every server takes it; a name the schema
# declares (a unique constraint's) is used as declared and refused above 63
# characters, where no server takes it -- refusing by bytes would refuse names
# Firebird 4 and later accept.
my $NAME_MAX = 63;
my $MADE_UP_MAX = 31;

# "<table>_<columns>_<target>_fk": the target is in the name, so two keys over
# one column to different tables do not meet in one name (a constraint name is
# the database's, not the table's). When that is longer than 31 BYTES (the
# limit of Firebird 3 is in bytes) it becomes its first characters up to 22
# bytes, "_" and 8 hex digits of the md5 of the whole name: the same input gives
# the same name every time, and two long names that share a prefix still differ.
sub _firebird_fk_name {
  my ($table, $columns, $to_table) = @_;
  my $name = join '_', $table, @$columns, $to_table, 'fk';
  return $name if _bytes($name) <= $MADE_UP_MAX;
  return _cut_bytes($name, 22) . '_' . substr(Digest::MD5::md5_hex(_encoded($name)), 0, 8);
}

sub _encoded { my ($s) = @_; utf8::encode(my $b = $s); return $b }
sub _bytes   { length _encoded($_[0]) }

# The longest prefix of $s that is at most $n bytes, cut between characters.
sub _cut_bytes {
  my ($s, $n) = @_;
  my $out = '';
  for my $ch (split //, $s) {
    last if _bytes($out . $ch) > $n;
    $out .= $ch;
  }
  return $out;
}

# Whether some has_many of $target (the referenced table's source) over the
# column pairs of this key has $attr set: the other side of the belongs_to,
# which is what DBIO::Relationship::Base describes as the autodetection of
# on_delete (cascade_delete) and on_update (cascade_copy). Firebird holds the
# key itself, and DBIO's own cascade deletes the parent FIRST, so a key without
# the action refuses to delete a parent that has children (karr k34).
sub _firebird_cascading_has_many {
  my ($target, $table, $from, $to, $attr) = @_;
  my $want = join "\0", sort map { "$from->[$_]\t$to->[$_]" } 0 .. $#$from;
  for my $rel ($target->relationships) {
    my $info = $target->relationship_info($rel) or next;
    next unless $info->{attrs} && $info->{attrs}{$attr};
    next unless ref $info->{cond} eq 'HASH';
    my $other = eval { $target->related_source($rel) } or next;
    my $oname = $other->name;
    $oname = $$oname if ref $oname eq 'SCALAR';
    next unless !ref $oname && $oname eq $table;
    my @pairs;
    for my $k (keys %{ $info->{cond} }) {
      my ($f) = $k =~ /\Aforeign\.(\w+)\z/ or next;
      my ($sc) = ($info->{cond}{$k} // '') =~ /\Aself\.(\w+)\z/ or next;
      push @pairs, "$f\t$sc";    # the child's column, the parent's column
    }
    return 1 if (join "\0", sort @pairs) eq $want;
  }
  return 0;
}

# The ON UPDATE / ON DELETE text of one rule. Firebird takes NO ACTION,
# CASCADE, SET NULL and SET DEFAULT; RESTRICT is a syntax error there, though
# it is what the server reports for a key written without a clause, so it (and
# an absent value) is written as no clause at all. Anything else is refused.
sub _firebird_fk_action {
  my ($event, $rule, $where) = @_;
  return '' unless defined $rule;
  (my $r = uc $rule) =~ s/\A\s+|\s+\z//g;
  $r =~ s/\s+/ /g;
  return '' if $r eq '' || $r eq 'RESTRICT';
  DBIO::Exception->throw(
    "$where: $event '$rule' is none of NO ACTION, CASCADE, SET NULL, SET DEFAULT")
    unless $r =~ /\A(?:NO ACTION|CASCADE|SET NULL|SET DEFAULT)\z/;
  return " $event $r";
}

sub _firebird_check_name_length {
  my ($name, $where) = @_;
  DBIO::Exception->throw(
    "$where: the constraint name '$name' is " . length($name)
    . " characters, Firebird takes at most $NAME_MAX")
    if length $name > $NAME_MAX;
  return $name;
}

# $table_sql and $to_table_sql are SQL as written (quoted, or a literal table
# name as given); the columns are bare names.
sub _firebird_add_foreign_key {
  my (%a) = @_;
  my $where = "foreign key '$a{name}' on $a{table_sql}";
  _firebird_check_name_length($a{name}, $where);
  return sprintf 'ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s)%s%s;',
    $a{table_sql}, _firebird_quote_ident($a{name}),
    join(', ', map { _firebird_quote_ident($_) } @{ $a{from} }),
    $a{to_table_sql},
    join(', ', map { _firebird_quote_ident($_) } @{ $a{to} }),
    _firebird_fk_action('ON DELETE', $a{on_delete}, $where),
    _firebird_fk_action('ON UPDATE', $a{on_update}, $where);
}

sub _firebird_add_unique {
  my (%a) = @_;
  _firebird_check_name_length($a{name}, "unique constraint '$a{name}' on $a{table_sql}");
  return sprintf 'ALTER TABLE %s ADD CONSTRAINT %s UNIQUE (%s);',
    $a{table_sql}, _firebird_quote_ident($a{name}),
    join(', ', map { _firebird_quote_ident($_) } @{ $a{columns} });
}

# The column lists of the foreign keys install_ddl writes for $source, in the
# order it writes them (the foreign columns sorted by name): the same reading
# of the belongs_to relationships as the loop in install_ddl below.
sub _firebird_fk_column_lists {
  my ($schema, $source) = @_;
  my @lists;
  for my $rel (sort $source->relationships) {
    my $info = $source->relationship_info($rel);
    next unless $info && $info->{attrs} && $info->{attrs}{is_foreign_key_constraint};
    my $foreign = $info->{class};
    next unless eval { $schema->source($foreign) } // eval { $schema->source($foreign =~ s/.*:://r) };
    my $cond = $info->{cond};
    next unless ref $cond eq 'HASH';
    push @lists, [ map { (my $c = $cond->{$_}) =~ s/^self\.//; $c } sort keys %$cond ];
  }
  return @lists;
}

# What the shared conformance table (karr k55) asks to be refused rather than
# built as something else: no Firebird type means what the declaration says.
my $TZ_REASON = 'the server has the type (Firebird 4 and later) but DBD::Firebird 1.39 '
  . 'does not know it: a value cannot be bound to the column and one read '
  . 'comes back as the text "** unknown **" (t/88-timezone-types-dbd-live.t)';

# More than 18 digits of a NUMERIC / DECIMAL is an INT128 (karr k60).
my $INT128_REASON = 'more than 18 digits is an INT128; the server has it from Firebird 4 on '
  . 'but DBD::Firebird 1.39 cannot bind or read an INT128 (a value is not bound, '
  . 'one read comes back wrong; t/97-numeric-int128-dbd-live.t)';

# These types exist from Firebird 4 on; the driver supports 3. On a server
# below 4 install_ddl refuses them, naming the table and the column, instead
# of leaving the server's "Token unknown" for the middle of a deploy. (The
# time zone types are refused on every server, see $TZ_REASON.)
my %NEEDS_FIREBIRD_4 = map { $_ => 1 } qw(binary varbinary);

my %REFUSED_TYPE = (
  timestamptz                => $TZ_REASON,
  'timestamp with time zone' => $TZ_REASON,
  'time with time zone'      => $TZ_REASON,
  bit  => 'Firebird has no type for a bit string of a fixed width: BOOLEAN is one '
        . 'bit and BINARY(n) counts bytes, so any mapping changes what the size means',
  enum => 'Firebird has no enumerated type, and a VARCHAR with a CHECK would '
        . 'be a different column (its values are not a list the server knows)',
);


sub server_major_version {
  my ($class, $schema) = @_;
  my $version = eval {
    my ($v) = $schema->storage->dbh_do(sub {
      $_[1]->selectrow_array(
        q{SELECT rdb$get_context('SYSTEM', 'ENGINE_VERSION') FROM rdb$database});
    });
    $v;
  };
  return defined $version && $version =~ /\A\s*(\d+)/ ? $1 : undef;
}


sub install_ddl {
  my ($class, $schema) = @_;
  my @stmts;
  my @view_stmts;
  my (@unique_stmts, @fk_stmts, %seen_fk);
  my %seen_table;
  my %seen_view;

  for my $source_name (sort $schema->sources) {
    my $source = $schema->source($source_name);
    my $table_name = $source->name;

    # Views: emit CREATE VIEW after all tables; skip virtual views.
    if ($source->isa('DBIO::ResultSource::View')) {
      next if $source->can('is_virtual') && $source->is_virtual;
      my $vliteral = ref $table_name eq 'SCALAR';
      my $vname    = $vliteral ? $$table_name : $table_name;
      # no schemas before Firebird 6: a dot would become part of the name
      $source->throw_exception(
        "view '$vname': refused, Firebird has no schemas before version 6 "
        . "and a dot would become part of a literal view name")
        if !$vliteral && !ref $vname && $vname =~ /\./;
      next if ref $vname || $seen_view{$vname}++;
      my $def = $source->can('view_definition') ? $source->view_definition : undef;
      next unless defined $def && length $def;
      push @view_stmts, sprintf 'CREATE VIEW %s AS %s;',
        ($vliteral ? $vname : _firebird_quote_ident($vname)), $def;
      next;
    }

    # A scalar-ref name is either a literal table name (\'cd', emitted
    # unquoted) or an inline subquery source; deref the former, skip the latter.
    # The literal stays unquoted because the SQLMaker writes it into FROM as
    # given: quoting it here would create "cd" while the ORM selects FROM cd.
    my $literal = ref $table_name eq 'SCALAR';
    if ($literal) {
      $table_name = $$table_name;
      next if $table_name =~ /\s|\(/;
    }
    next if ref $table_name;

    # Firebird has no schemas before version 6 (karr k55): a dot in a quoted
    # name is a character of the name, not a schema, so `other.t` would become
    # a table of that literal name. Refused, not reinterpreted. A literal name
    # (\'...') is SQL as written and is the caller's.
    $source->throw_exception(
      "table '$table_name': refused, Firebird has no schemas before version 6 "
      . "and a dot would become part of a literal table name")
      if !$literal && $table_name =~ /\./;

    # Several result sources can map to one physical table; emit it once.
    next if $seen_table{$table_name}++;

    my @col_defs;
    my %is_pk;
    my @pk_cols = $source->primary_columns;
    @is_pk{@pk_cols} = (1) x @pk_cols;

    for my $col_name ($source->columns) {
      my $info = $source->column_info($col_name);
      if (my $why = $REFUSED_TYPE{ lc($info->{data_type} // '') }) {
        $source->throw_exception(
          "column '$col_name' on '$table_name': data_type '$info->{data_type}' "
          . "is refused: $why");
      }
      if ($NEEDS_FIREBIRD_4{ lc($info->{data_type} // '') }) {
        my $major = $class->server_major_version($schema);
        $source->throw_exception(
          "column '$col_name' on '$table_name': data_type '$info->{data_type}' "
          . "is refused: the type exists from Firebird 4 on and the server is "
          . "Firebird $major")
          if defined $major && $major < 4;
      }
      # NUMERIC / DECIMAL of more than 18 digits is stored as an INT128 (the
      # server has it from Firebird 4 on); DBD::Firebird 1.39 can neither bind
      # nor read one, so it is refused on every server (karr k60, t/97)
      if (lc($info->{data_type} // '') =~ /\A(?:numeric|decimal)\z/) {
        my $precision = ref $info->{size} eq 'ARRAY' ? $info->{size}[0] : $info->{size};
        $source->throw_exception(
          "column '$col_name' on '$table_name': data_type '$info->{data_type}' "
          . "with $precision digits is refused: $INT128_REASON")
          if defined $precision and $precision =~ /\A\d+\z/ and $precision > 18;
      }
      my $type = ddl_type_from_info($info);
      my $def = sprintf '  %s %s', _firebird_quote_ident($col_name), $type;
      # IDENTITY (karr k46): Firebird 3, the driver's minimum, generates the
      # key itself; the clause sits between the type and NOT NULL. Identity
      # and DEFAULT exclude each other, and only an integer type can carry it:
      # refused, never simplified.
      if ($info->{is_auto_increment}) {
        $source->throw_exception(
          "column '$col_name' on '$table_name': is_auto_increment cannot be "
          . "built as IDENTITY on a $type column (only SMALLINT, INTEGER, BIGINT, "
          . "NUMERIC / DECIMAL with scale 0)")
          unless _firebird_identity_type_ok($type);
        $source->throw_exception(
          "column '$col_name' on '$table_name': is_auto_increment (IDENTITY) "
          . "and default_value exclude each other")
          if defined $info->{default_value};
      }
      # ADR 0043: a missing is_nullable means NOT NULL; only 1 is nullable.
      $def .= _firebird_column_clauses(
        identity => $info->{is_auto_increment},
        default  => (defined $info->{default_value}
                       ? _firebird_default_literal($info->{default_value}, $info, "column '$col_name' on '$table_name'") : undef),
        not_null => !$info->{is_nullable},
      );
      push @col_defs, $def;
    }

    if (@pk_cols) {
      push @col_defs, sprintf '  PRIMARY KEY (%s)',
        join(', ', map { _firebird_quote_ident($_) } @pk_cols);
    }

    my $qualified = $literal ? $table_name : _firebird_quote_ident($table_name);
    push @stmts, sprintf "CREATE TABLE %s (\n%s\n);", $qualified, join(",\n", @col_defs);

    # The canonical index declarations of the source (Cake idx, indices;
    # ADR 0061 in core, karr k51). The reader refuses an entry that carries
    # only another driver's block and an unknown key in the firebird block;
    # no key is allowed, so a firebird block must be empty (the plain index).
    # What Firebird can express but the introspector does not read back
    # (COMPUTED BY, partial, DESC) is not offered, so no index is built that
    # the diff would then drop again. type (other than unique) and options
    # have no meaning here and are refused, never a plainer index.
    my %declared;
    for my $decl ($source->index_declarations_for('firebird', [])) {
      if (defined $decl->{type} && lc $decl->{type} ne 'unique') {
        $source->throw_exception(
          "index '$decl->{name}' on '$table_name': type '$decl->{type}' "
          . "cannot be built on Firebird (only a plain or unique index)");
      }
      if (defined $decl->{options}) {
        $source->throw_exception(
          "index '$decl->{name}' on '$table_name': options cannot be built "
          . "on Firebird");
      }
      $declared{ $decl->{name} } = $decl;
    }

    # Unique indexes. A column that a unique constraint over exactly this one
    # column covers gets no second index: the constraint has its own (karr k55).
    my %constraint_alone;
    {
      my %u = $source->unique_constraints;
      for my $uname (keys %u) {
        next if $uname eq 'primary';
        $constraint_alone{ $u{$uname}[0] } = 1 if @{ $u{$uname} } == 1;
      }
    }
    for my $col_name ($source->columns) {
      my $info = $source->column_info($col_name);
      next if $declared{"${table_name}_${col_name}_idx"};
      next if $constraint_alone{$col_name};
      if ($info->{is_unique} || $info->{is_single_unique_key}) {
        push @stmts, sprintf 'CREATE UNIQUE INDEX %s ON %s (%s);',
          _firebird_quote_ident("${table_name}_${col_name}_idx"),
          $qualified,
          _firebird_quote_ident($col_name);
      }
    }

    # An index the server has already (karr k55): the key of a primary key,
    # of a unique constraint written below, and (for a non-unique index) the
    # one Firebird builds for each foreign key. Same columns in the same
    # order. A UNIQUE index over a foreign key's columns says more than the
    # key and is built.
    my (%has_index, %has_fk_index);
    $has_index{ join "\0", @pk_cols } = 1 if @pk_cols;
    {
      my %u = $source->unique_constraints;
      for my $uname (keys %u) {
        next if $uname eq 'primary';
        next if join("\0", sort @{ $u{$uname} }) eq join("\0", sort @pk_cols);
        $has_index{ join "\0", @{ $u{$uname} } } = 1;
      }
    }
    $has_fk_index{ join "\0", @$_ } = 1 for _firebird_fk_column_lists($schema, $source);

    for my $name (sort keys %declared) {
      my $decl = $declared{$name};
      my $key = join "\0", @{ $decl->{columns} };
      next if $has_index{$key} || (!$decl->{unique} && $has_fk_index{$key});
      push @stmts, sprintf 'CREATE %sINDEX %s ON %s (%s);',
        ($decl->{unique} ? 'UNIQUE ' : ''),
        _firebird_quote_ident($name),
        $qualified,
        join(', ', map { _firebird_quote_ident($_) } @{ $decl->{columns} });
    }

    # Unique constraints (add_unique_constraint), under the name declared.
    my %uniques = $source->unique_constraints;
    for my $uname (sort keys %uniques) {
      next if $uname eq 'primary';
      # A unique constraint over exactly the columns of the primary key says
      # nothing the key does not, and the server refuses it ("Same set of
      # columns cannot be used in more than one PRIMARY KEY and/or UNIQUE
      # constraint definition", measured on 5.0.4): it is not written.
      next if join("\0", sort @{ $uniques{$uname} }) eq join("\0", sort @pk_cols);
      push @unique_stmts, _firebird_add_unique(
        table_sql => $qualified, name => $uname, columns => $uniques{$uname},
      );
    }

    # Foreign keys from the belongs_to relationships (is_foreign_key_constraint),
    # in the order of the relationship names. on_delete / on_update are the
    # relationship's own attributes where it declares them (exists, so
    # `on_delete => undef` or '' declares "no action" and switches the
    # derivation off); where it does not, they come from the other side as
    # DBIO::Relationship::Base describes: a has_many over the same columns with
    # cascade_delete is ON DELETE CASCADE, one with cascade_copy ON UPDATE
    # CASCADE. DBIO's own cascade deletes the parent first, so without the
    # action the server refuses the delete of a parent that has children
    # (karr k34).
    for my $rel (sort $source->relationships) {
      my $info = $source->relationship_info($rel);
      next unless $info && $info->{attrs} && $info->{attrs}{is_foreign_key_constraint};

      my $foreign = $info->{class};
      my $foreign_source = eval { $schema->source($foreign) }
        // eval { $schema->source($foreign =~ s/.*:://r) };
      next unless $foreign_source;
      my $cond = $info->{cond};
      next unless ref $cond eq 'HASH';

      # Firebird has no DEFERRABLE; the attribute is not left out silently.
      $source->throw_exception(
        "relationship '$rel' on '$table_name': is_deferrable cannot be built, "
        . "Firebird has no deferrable constraints")
        if $info->{attrs}{is_deferrable};

      my (@from, @to);
      for my $foreign_col (sort keys %$cond) {
        (my $fcol = $foreign_col) =~ s/^foreign\.//;
        (my $scol = $cond->{$foreign_col}) =~ s/^self\.//;
        push @to, $fcol;
        push @from, $scol;
      }

      my $to_name = $foreign_source->name;
      my $to_bare = ref $to_name eq 'SCALAR' ? $$to_name : $to_name;
      my $to_sql  = ref $to_name eq 'SCALAR' ? $$to_name : _firebird_quote_ident($to_name);
      my $attrs   = $info->{attrs};
      my %fk = (
        table_sql => $qualified, name => _firebird_fk_name($table_name, \@from, $to_bare),
        from => \@from, to_table_sql => $to_sql, to => \@to,
        on_delete => (exists $attrs->{on_delete} ? $attrs->{on_delete}
          : _firebird_cascading_has_many($foreign_source, $table_name, \@from, \@to, 'cascade_delete')
            ? 'CASCADE' : undef),
        on_update => (exists $attrs->{on_update} ? $attrs->{on_update}
          : _firebird_cascading_has_many($foreign_source, $table_name, \@from, \@to, 'cascade_copy')
            ? 'CASCADE' : undef),
      );
      my $stmt = _firebird_add_foreign_key(%fk);

      # Relationships that declare the same key are one key. The same columns
      # with other actions would be a second constraint under the same name:
      # refused, never one of them quietly.
      my $by_cols = join "\0", $table_name, @from, '->', $to_sql, @to;
      if (defined(my $prev = $seen_fk{$by_cols})) {
        next if $prev eq $stmt;
        $source->throw_exception(
          "relationship '$rel' on '$table_name' declares a foreign key over "
          . join(', ', @from) . " that another relationship declares with other "
          . "on_delete / on_update actions; Firebird cannot hold both");
      }
      $seen_fk{$by_cols} = $stmt;
      push @fk_stmts, $stmt;
    }
  }

  return join "

", @stmts, @unique_stmts, @fk_stmts, @view_stmts;
}

1;

