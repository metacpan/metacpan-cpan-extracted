use v5.26;
use Object::Pad qw(:experimental(mop));

class Getopt::Pad::Result {
	# Carp is called fully qualified: an imported croak would be a method
	# of every Result and reserve its name for no reason.
	use Carp ();

	our $VERSION = '0.06';

	# Names Perl looks up on an object by itself; a Reader by one of these
	# would run at the wrong time with the wrong arguments.
	my %isPerlHook = map { $_ => 1 } qw(DESTROY AUTOLOAD);

	field $command    :param :reader = undef;
	field $subcommand :param :reader = undef;
	field $helper     :param         = undef;

	# Whether a Reader named $name would clash with what every Result
	# already answers to: a method (including the ones Object::Pad and
	# UNIVERSAL provide), a constructor param, or a Perl hook. Derived from
	# the class itself, so nothing here can drift from it.
	method reservesReader :common ($name) {
		return 1 if $isPerlHook{$name};
		return 1 if $class->can($name);
		my @params = map { $_->get_attribute_value('param') } grep { $_->has_attribute('param') } Object::Pad::MOP::Class->for_class($class)->fields;
		return (grep { $_ eq $name } @params) ? 1 : 0;
	}

	method help() {
		Carp::croak('Getopt::Pad: no help renderer attached to this result') unless defined $helper;
		$helper->printHelp;
		exit 0;
	}

	method version() {
		Carp::croak('Getopt::Pad: no help renderer attached to this result') unless defined $helper;
		$helper->printVersion;
		exit 0;
	}
}

1;

__END__

=encoding utf8

=head1 NAME

Getopt::Pad::Result - The object GetOptions returns

=head1 SYNOPSIS

=for highlighter language=perl

    my $opt = GetOptions(
        options  => { 'log-level' => { type => 'string', default => 'info' } },
        commands => {
            resize => { options => { width => { type => 'int' } } },
        },
    );

    # tool --log-level debug resize --width 640
    $opt->logLevel;                   # 'debug'
    $opt->command;                    # 'resize'
    $opt->subcommand->width;          # 640

    $opt->help;                       # prints the help and exits
    $opt->version;                    # prints the version and exits

=head1 DESCRIPTION

C<GetOptions> returns a result object for the top level of the spec. For
every command the command line selects, there is one more result object,
reachable through C<subcommand>. Each result object has one reader per
option and arg of its level, plus the methods below.

The class of a result object is generated by Getopt::Pad for the readers
of its level, and inherits from Getopt::Pad::Result. Its name is internal;
use C<< $opt->isa('Getopt::Pad::Result') >> to check for a result object.

The readers are read-only: there are no methods to set values, and
calling a reader with an argument is an error. The values are plain Perl
data: strings, numbers, and for options with several values arrayrefs
and hashrefs. These references belong to the result object; if your
program changes their contents, the reader returns the changed data from
then on. Other parses are not affected. An option or arg with
C<processValue> returns what its coderef returned instead, see
L<Getopt::Pad/processValue>. What each kind of option returns is
listed in L<Getopt::Pad/Values by option kind>, and how reader names are
derived from option names in L<Getopt::Pad/Reader names>.

=head1 METHODS

=head2 command

=for highlighter language=perl

    my $name = $opt->command;

The name of the command selected on this level, as declared in the spec.
C<undef> if the level has no commands, or if the command is optional (see
L<Getopt::Pad/commandRequired>) and was not given.

=head2 subcommand

=for highlighter language=perl

    my $commandResult = $opt->subcommand;

The result object of the selected command, with the readers of that
command's options and args. C<undef> whenever C<command> is C<undef>.

=head2 help

=for highlighter language=perl

    $opt->help;

Prints the help text of this result object's level to STDOUT and exits the
program with status 0. It is the same text that C<--help> prints on that
level. C<< $opt->subcommand->help >> prints the help of the selected
command.

=head2 version

=for highlighter language=perl

    $opt->version;

Prints the program name and version to STDOUT, as the automatic
C<--version> option does, and exits the program with status 0.

=head1 RESERVED NAMES

Because every result object has the methods above and the methods every
Perl object has, some names cannot be used for options and args. See
L<Getopt::Pad/Reserved names> for the list.

