sub _fill_foundation
{
	my ($input) = @_;
	$input ||= \%input;

	my $foundation;

	foreach my $field (keys %{$input}) {
		my $spec = $input->{$field} || {};
		my $type = $spec->{type} || 'string';

		if(($type eq 'number') || ($type eq 'float')) {
			if(defined $spec->{min}) {
				if(defined $spec->{max}) {
					$foundation->{$field} = $spec->{max};	# border
				} else {
					$foundation->{$field} = abs(rand_num()) + $spec->{'min'};
				}
			} else {
				if(defined $spec->{max}) {
					$foundation->{$field} = $spec->{max};	# border
				} else {
					$foundation->{$field} = -0.01;	# No min, so -0.01 should be allowable
				}
			}
		} elsif($type eq 'string') {
			$foundation->{$field} = _random_string_for_spec($spec, 'test_value');
		} elsif ($type eq 'integer') {
			if (defined $spec->{min}) {
				$foundation->{$field} = $spec->{min};
			} elsif (defined $spec->{max}) {
				$foundation->{$field} = rand_int() + $spec->{max};
			} else {
				$foundation->{$field} = rand_int();
			}
		} elsif ($type eq 'boolean') {
			$foundation->{$field} = 1;
		} elsif ($type eq 'arrayref') {
			$foundation->{$field} = _random_array_for_spec($spec,
				defined($spec->{'min'}) ? $spec->{'min'} : ($spec->{'max'} // 5));
		} elsif ($type eq 'hashref') {
			$foundation->{$field} = _random_hash_for_spec($spec, $spec->{min} // 5);
		} else {
			carp "unhandled transform type '$type' for foundation; skipping field '$field'";
			next;
		}
	}
	return $foundation;
}

