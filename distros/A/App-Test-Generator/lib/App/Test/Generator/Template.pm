sub fuzz_inputs
{
	my @cases;

	# Are any options mandatory?
	my $all_optional = 1;
	my %mandatory_strings;	# List of mandatory strings to be added to all tests, always put at start so it can be overwritten
	my %mandatory_objects;
	my %mandatory_numbers;
	my $class_simple_loaded;

	# Create a hash ref of the mandatory args
	foreach my $field (keys %input) {
		my $spec = $input{$field} || {};
		if((ref($spec) eq 'HASH') && (!$spec->{optional})) {
			$all_optional = 0;
			if($spec->{'type'} eq 'string') {
				local $config{'test_undef'} = 0;
				local $config{'test_nuls'} = 0;
				local $config{'test_empty'} = 0;
				if(($spec->{'semantic'} // '') eq 'bytes') {
					# Every other case is built on this filler, so it must be a
					# byte string as well: handing a routine that reads octets a
					# text value failed the case for the wrong reason.
					$mandatory_strings{$field} = _random_bytes_for_spec($spec);
				} elsif($spec->{'matches'}) {
					# The field's declared length is what a validator will
					# enforce, so the shared value must honour it too.
					$mandatory_strings{$field} = _random_string_matching(
						$spec->{'matches'}, _length_bounds($spec),
					) // '';
				} elsif(defined $spec->{memberof}) {
					my @set = @{$spec->{memberof}};
					$mandatory_strings{$field} = $set[-1];
				} else {
					# Every case is built on this filler, so it has to satisfy
					# what the schema states: an empty one made every case of an
					# argument the code refuses when empty die for that reason
					# instead of the one under test.
					$mandatory_strings{$field} = rand_ascii_str($spec->{max} // $spec->{min} // 8);
					$mandatory_strings{$field} = 'value'
						if $spec->{'_not_empty'} && !length($mandatory_strings{$field});
				}
			} elsif($spec->{'type'} eq 'object') {
				my $method = $spec->{'can'};
				if(!defined($method)) {
					die "$field: type is object, but 'can' is not specified which is needed to mock the object";
				}
				if(!$class_simple_loaded) {
					require_ok('Class::Simple');
					eval {
						Class::Simple->import();
						$class_simple_loaded = 1;
					};
				}
				my $simple_obj = new_ok('Class::Simple');
				$simple_obj->$method(1);
				$mandatory_objects{$field} = $simple_obj;
			} elsif(($spec->{'type'} eq 'float') || ($spec->{'type'} eq 'number') || ($spec->{'type'} eq 'integer')) {
				# As for strings: a value outside the list is not a valid filler
				$mandatory_numbers{$field} = _has_memberof($spec)
					? $spec->{memberof}[-1]
					: _random_number_for_spec($spec, $spec->{'type'} eq 'integer');
			} elsif($spec->{type} eq 'hashref') {
				$mandatory_objects{$field} = _random_hash_for_spec($spec, $spec->{min} // 1);
			} elsif(($spec->{type} eq 'arrayref') || ($spec->{type} eq 'array')) {
				# A filler must satisfy the declared minimum: an empty array
				# here contradicted the below-minimum cases, so a routine that
				# enforces min => 1 failed a case it was never given a chance
				# to pass.
				$mandatory_objects{$field} = _random_array_for_spec($spec, $spec->{min} // 0);
			} elsif($spec->{type} eq 'coderef') {
				# A callback is required, but its behaviour is not: a no-op
				# coderef satisfies the contract of the call being tested.
				$mandatory_objects{$field} = sub { };
			} elsif($spec->{type} eq 'any') {
				$mandatory_strings{$field} = rand_ascii_str(8);
			} else {
				carp __PACKAGE__, ": unhandled mandatory-arg type '${\$spec->{'type'}}'; skipping field '$field'";
				next;
			}
		}
	}

	# Don't do for now, until transform object code is added
	# my %mandatory_args;
	# if(my $foundation = _fill_foundation()) {
		# %mandatory_args = %{$foundation};
	# }
	my %mandatory_args = (%mandatory_strings, %mandatory_objects, %mandatory_numbers);

	if(($all_optional) || ((scalar keys %input) > 1)) {
		# Basic test cases
		if(((scalar keys %input) == 1) && exists($input{'type'}) && !ref($input{'type'})) {
			# our %input = ( type => 'string' );
			my $type = $input{'type'};

			if($input{'enum'}) {
				if($input{'memberof'}) {
					die 'input has both enum and memberof';
				}
				$input{'memberof'} = delete $input{'enum'};
			}
			foreach my $field(keys %input) {
				next if($field =~ /^_/);	# Ignore comments
				if(!grep({ $_ eq $field } ('type', 'min', 'max', 'sample_max', 'optional', 'matches', 'can', 'memberof', 'position', 'named'))) {
					carp "unhandled schema keyword '$field'; skipping";
					next;
				}
			}

			if ($type eq 'string') {
				push @cases, @{_generate_string_cases('_input', \%input, \%mandatory_args, _LINE => __LINE__)};
				# push @cases, { '_input' => "emoji \x{1F600}" };
			} else {
				carp "unhandled single-input type '$type'; skipping test generation";
			}
		} else {
			# our %input = ( str => { type => 'string' } );

			foreach my $arg_name (keys %input) {
				my $spec = $input{$arg_name} || {};
				my $type = lc((!ref($spec)) ? $spec : $spec->{type}) || 'string';

				if(ref($spec) && $spec->{'enum'}) {
					if($spec->{'memberof'}) {
						die "$arg_name has both enum and memberof";
					}
					$spec->{'memberof'} = delete $spec->{'enum'};
				}
				foreach my $field(keys %{$spec}) {
					next if($field =~ /^_/);	# Ignore comments
					if(!grep({ $_ eq $field } ('type', 'min', 'max', 'sample_max', 'optional', 'matches', 'can', 'memberof', 'position', 'named', 'isa'))) {
						diag(__LINE__, ": TODO: handle schema keyword '$field'");
					}
				}

				# --- Type-based seeds ---
				if(($type eq 'number') || ($type eq 'float')) {
					push @cases, @{_generate_float_cases($arg_name, $spec, \%mandatory_args, _LINE => __LINE__)};
				} elsif ($type eq 'integer') {
					# Probably duplicated below, but here as well just in case
					push @cases, @{_generate_integer_cases($arg_name, $spec, \%mandatory_args, _LINE => __LINE__)};
				} elsif ($type eq 'string') {
					push @cases, @{_generate_string_cases($arg_name, $spec, \%mandatory_args, _LINE => __LINE__)};
				} elsif ($type eq 'boolean') {
					push @cases, @{_generate_boolean_cases($arg_name, $spec, \%mandatory_args, _LINE => __LINE__)};
				} elsif ($type eq 'hashref') {
					push @cases, { %mandatory_args, $arg_name => _random_hash_for_spec($spec) };
					# A documented type is intent: only a routine that checks its
					# arguments promises to reject the wrong type.
					if(_spec_checks_types($spec)) {
						push @cases,
							{ %mandatory_args, $arg_name => [], _STATUS => 'DIES' },
							{ %mandatory_args, $arg_name => 66, _STATUS => 'DIES' },
							{ %mandatory_args, $arg_name => sub { die 'fail' }, _STATUS => 'DIES' },
							{ %mandatory_args, $arg_name => 'scalar when hashref is needed', _STATUS => 'DIES' },
							{ %mandatory_args, $arg_name => \'scalarref when hashref is needed', _STATUS => 'DIES' };
					}
					if($config{test_undef}) {
						push @cases,
							{ %mandatory_args, $arg_name => { nested => { 'first', undef, 'third' } }, _DESCRIPTION => 'nested hash with undef' } if($config{test_undef});
					}
				} elsif ($type eq 'arrayref') {
					push @cases, { %mandatory_args, $arg_name => _random_array_for_spec($spec, 2) };
					if(_spec_checks_types($spec)) {
						push @cases, { %mandatory_args, $arg_name => { a => 1 }, _STATUS => 'DIES' };
					}
				} elsif($type eq 'object') {
					if($spec->{'isa'}) {
						push @cases, { $arg_name => { a => 1 }, _STATUS => 'DIES', _LINE => __LINE__ };
						push @cases, { $arg_name => [], _STATUS => 'DIES', _LINE => __LINE__ };

						# Test dies when given the wrong type of object
						push @cases, { $arg_name => new_ok('MyTestPackage'), _STATUS => 'DIES', _LINE => __LINE__ };

						use_ok($spec->{isa});
						push @cases, { $arg_name => new_ok($spec->{isa}) };
					} elsif(!$spec->{can}) {
						Carp::carp("neither 'isa' nor 'can' is defined - what type of object should be sent?");
					}
				} elsif($type eq 'any') {
					push @cases,
						{ %mandatory_args, $arg_name => 'string_value' },
						{ %mandatory_args, $arg_name => 42 },
						{ %mandatory_args, $arg_name => 3.14 },
						{ %mandatory_args, $arg_name => [] },
						{ %mandatory_args, $arg_name => {} };
					if($config{test_undef}) {
						push @cases, { %mandatory_args, $arg_name => undef };
					}
				}

				# --- matches (regex) ---
					if (defined $spec->{matches}) {
					my $regex = $spec->{matches};
					for my $string(@regex_tests) {
						if($string =~ $regex) {
							push @cases, { %mandatory_args, ( $arg_name => $string ) };
						} elsif(!_constraint_is_documented($spec, 'matches')) {
							push @cases, { %mandatory_args, ( $arg_name => $string, _STATUS => 'DIES' ) };
						}
					}
				}

				# --- nomatch (regex) ---
				if (defined $spec->{nomatch}) {
					my $regex = $spec->{nomatch};
					for my $string(@regex_tests) {
						if($string =~ $regex) {
							push @cases, { %mandatory_args, ( $arg_name => $string, _STATUS => 'DIES' ) };
						} else {
							push @cases, { %mandatory_args, ( $arg_name => $string ) };
						}
					}
				}

				# --- memberof ---
				push @cases, _memberof_cases($arg_name, $spec, \%mandatory_args) if _has_memberof($spec);

				# --- notmemberof ---
				if (defined $spec->{notmemberof}) {
					my @set = @{ $spec->{notmemberof} };
					push @cases, { %mandatory_args, ( $arg_name => $set[0], _STATUS => 'DIES' ) } if @set;
					push @cases, { %mandatory_args, ( $arg_name => '_not_in_set_' ) };
				}

				# --- semantic ---
				if(defined(my $semantic = $spec->{'semantic'})) {
					if($semantic eq 'unix_timestamp') {
						push @cases, { %mandatory_args, ( -1, _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => 0 ) },
							{ %mandatory_args, ( $arg_name => 1 ) },
							{ %mandatory_args, ( $arg_name => time ) },
							{ %mandatory_args, ( $arg_name => 2147483647 ) },
							{ %mandatory_args, ( 45.67, _STATUS => 'DIES', _DESCRIPTION => 'UNIX timestamp should not be a float' ) },
							{ %mandatory_args, ( $arg_name => 2147483648, _STATUS => 'DIES' ) };
					} elsif($semantic eq 'bytes') {
						# A byte string holds arbitrary octets, not text: high bytes
						# are valid data, and nothing about them is a document
						# violation.
						push @cases,
							{ %mandatory_args, ( $arg_name => "\x00\x01\xfe\xff" ) },
							{ %mandatory_args, ( $arg_name => join('', map { chr } 0 .. 255) ) };
					} elsif($semantic eq 'email') {
						push @cases,
							{ %mandatory_args, ( $arg_name => 'user@example.com' ) },
							{ %mandatory_args, ( $arg_name => 'user+tag@sub.example.co.uk' ) },
							{ %mandatory_args, ( $arg_name => '@nodomain', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => 'noatsign', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => 'user@', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => '', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => 'user@' . ('a' x 256) . '.com', _STATUS => 'DIES' ) };
					} elsif($semantic eq 'filepath') {
						push @cases,
							{ %mandatory_args, ( $arg_name => '/tmp/test.txt' ) },
							{ %mandatory_args, ( $arg_name => 'relative/path.txt' ) },
							{ %mandatory_args, ( $arg_name => '.' ) },
							{ %mandatory_args, ( $arg_name => '..' ) },
							{ %mandatory_args, ( $arg_name => '../../etc/passwd', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => '/etc/passwd' . "\0", _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => '', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => '/' . ('a' x 4096), _STATUS => 'DIES' ) };
						if($^O eq 'MSWin32') {
							push @cases,
								{ %mandatory_args, ( $arg_name => 'C:\\Users\\test\\file.txt' ) },
								{ %mandatory_args, ( $arg_name => 'D:\\' ) },
								{ %mandatory_args, ( $arg_name => 'relative\\path.txt' ) },
								{ %mandatory_args, ( $arg_name => 'C:\\..\\..\\Windows\\System32', _STATUS => 'DIES' ) },
								{ %mandatory_args, ( $arg_name => 'C:\\path\\' . "\0" . 'file', _STATUS => 'DIES' ) },
								{ %mandatory_args, ( $arg_name => 'COM1', _STATUS => 'DIES' ) },   # reserved device name
								{ %mandatory_args, ( $arg_name => 'NUL', _STATUS => 'DIES' ) },    # reserved device name
								{ %mandatory_args, ( $arg_name => 'C:\\path\\file?.txt', _STATUS => 'DIES' ) },   # wildcard
								{ %mandatory_args, ( $arg_name => 'C:\\path\\file*.txt', _STATUS => 'DIES' ) },   # wildcard
								{ %mandatory_args, ( $arg_name => '\\\\server\\share\\file.txt' ) };  # UNC path
						}
					} elsif($semantic eq 'date_string') {
						push @cases,
							{ %mandatory_args, ( $arg_name => '2024-01-01' ) },
							{ %mandatory_args, ( $arg_name => '1970-01-01' ) },
							{ %mandatory_args, ( $arg_name => '2024-02-29' ) },   # leap day
							{ %mandatory_args, ( $arg_name => '2023-02-29', _STATUS => 'DIES' ) },  # not a leap year
							{ %mandatory_args, ( $arg_name => '2024-13-01', _STATUS => 'DIES' ) },  # month 13
							{ %mandatory_args, ( $arg_name => '2024-00-01', _STATUS => 'DIES' ) },  # month 0
							{ %mandatory_args, ( $arg_name => '01-01-2024', _STATUS => 'DIES' ) },  # wrong order
							{ %mandatory_args, ( $arg_name => '2024/01/01', _STATUS => 'DIES' ) },  # wrong separator
							{ %mandatory_args, ( $arg_name => 'not-a-date', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => '', _STATUS => 'DIES' ) };
					} elsif($semantic eq 'iso8601_string') {
						push @cases,
							{ %mandatory_args, ( $arg_name => '2024-01-01T00:00:00Z' ) },
							{ %mandatory_args, ( $arg_name => '2024-06-15T12:30:45Z' ) },
							{ %mandatory_args, ( $arg_name => '2024-01-01T00:00:00+05:30' ) },
							{ %mandatory_args, ( $arg_name => '2024-01-01' ) },          # date only - check if accepted
							{ %mandatory_args, ( $arg_name => '2024-01-01T25:00:00Z', _STATUS => 'DIES' ) },  # hour 25
							{ %mandatory_args, ( $arg_name => '2024-01-01T00:61:00Z', _STATUS => 'DIES' ) },  # minute 61
							{ %mandatory_args, ( $arg_name => 'not-a-datetime', _STATUS => 'DIES' ) },
							{ %mandatory_args, ( $arg_name => '', _STATUS => 'DIES' ) };
					} else {
						diag("semantic type $semantic is not yet supported");
					}
				}
			}
		}
	}

	# Optional deduplication
	# my %seen;
	# @cases = grep { !$seen{join '|', %$_}++ } @cases;

	# Random data test cases
	# Uses type_edge_cases sometimes
	if(scalar keys %input) {
		if(((scalar keys %input) == 1) && exists($input{'type'}) && !ref($input{'type'})) {
			# our %input = ( type => 'string' );
			my $type = $input{'type'};
			for (1..[% iterations_code %]) {
				my $case_input;
				if (@edge_case_array && rand() < PROB_EDGE_CASE) {
					# Sometimes pick a field-specific edge-case
					$case_input = _pick_from(\@edge_case_array);
				} elsif(exists $type_edge_cases{$type} && rand() < 0.3) {
					# Sometimes pick a type-level edge-case
					$case_input = _pick_from($type_edge_cases{$type});
				} elsif($type eq 'string') {
					if($input{matches}) {
						$case_input = _random_string_matching($input{'matches'}, _length_bounds(\%input));
					} else {
						$case_input = _random_string_for_spec(\%input);
					}
				} elsif($type eq 'integer') {
					$case_input = _random_number_for_spec(\%input, 1);
					# If it's takes an integer, a float should die
					# Adding 0.1 to a large integer is lost to floating point
					# precision, so only claim the value is a non-integer when
					# it actually is one.
					my $float_input = $case_input + 0.1;
					push @cases, { _input => $float_input, _STATUS => 'DIES', _LINE => __LINE__ }
						if(($float_input != int($float_input)) && _spec_type_is_enforced(\%input));
				} elsif(($type eq 'number') || ($type eq 'float')) {
					$case_input = _random_number_for_spec(\%input, 0);
				} elsif($type eq 'boolean') {
					$case_input = rand_bool();
				} else {
					carp "unhandled single-param type '$type'; skipping test generation";
					next;
				}
				push @cases, { _input => $case_input, _STATUS => 'OK', _LINE => __LINE__ } if($case_input);
			}
		} else {
			# our %input = ( str => { type => 'string' } );
			push @cases, @{generate_tests(\%input, \%mandatory_args, _LINE => __LINE__)};

		}
	}

	# edge-cases
	if($config{'test_undef'}) {
		if($all_optional) {
			push @cases, { '_DESCRIPTION' => 'No args since all are optional' };
		} else {
			# Note that this is set on the input rather than output
			push @cases, { '_STATUS' => 'DIES' };	# At least one argument is needed
		}
	}

	if(scalar keys %input) {
		push @cases, { '_STATUS' => 'DIES', map { $_ => undef } keys %input } if($config{'test_undef'});
	} else {
		push @cases, { '_DESCRIPTION' => 'Takes no input' };	# Takes no input
	}

	# If it's not in mandatory_strings it sets to 'undef' which is the idea, to test { value => undef } in the args
	# _LINE has to go first or else the undef in there mucks up the hash format
	# Parentheses matter: without them the map also consumes the flattened
	# %mandatory_objects pairs, so a mandatory hashref/arrayref/coderef value
	# became a bogus 'HASH(0x...)' key and the field itself was overwritten
	# with undef.
	push @cases, { _LINE => __LINE__, (map { $_ => $mandatory_strings{$_} } keys %input), %mandatory_objects } if($config{'test_undef'} && !$positions);

	push @candidate_bad, '' if($config{'test_empty'});
	push @candidate_bad, undef if($config{'test_undef'});
	push @candidate_bad, "\0" if($config{'test_nuls'});

	# Type-specific edge cases for the single-schema form.  The named-field
	# form does the same work through _generate_type_cases(), below.
	if(((scalar keys %input) == 1) && exists($input{'type'}) && !ref($input{'type'})) {
		# our %input = ( type => 'string' );
		_note_documented_constraint('_input', \%input);
		if(_has_memberof(\%input)) {
			push @cases, _memberof_cases('_input', \%input, \%mandatory_args);
		} else {
			push @cases, @{_generate_type_cases('_input', $input{type}, \%input, \%mandatory_args)};

			# Test all edge cases
			foreach my $edge(@edge_case_array) {
				push @cases, { _input => $edge, _DESCRIPTION => 'edge case' };
			}
		}
	} else {
		# our %input = ( str => { type => 'string' } );
		push @cases, @{generate_tests(\%input, \%mandatory_args)};
	}

	# A POD-derived bound is a hint for valid data, not a promise that values
	# outside it die.  Explicit probes are kept and report acceptance as a
	# documentation contradiction.  Some ordinary cases are built from fixed
	# samples rather than the bounds (e.g. a newline-containing string, or
	# 43.56); drop any that a documented bound excludes.  A hand-written bound
	# keeps its strict outside cases.
	@cases = @{_filter_documented_bound_cases(\@cases, \%input)};

	# fuzzing can easily generate repeats
	if($config{'dedup'}) {
		return _dedup_cases(\@cases);
	}

	# use Data::Dumper;
	# die(Dumper(@cases));

	return \@cases;
}

# Functions to generate test cases
sub _generate_integer_cases {
	my ($arg_name, $spec, $mandatory_args) = @_;
	my @cases;

	# Same rule as strings and arrays: a documented-only bound sizes valid
	# data and does not make an outside value an error.  Each bound is decided
	# on its own, so a code-enforced one stays strict beside a documented one.
	my $min_strict = !_constraint_is_documented($spec, 'min');
	my $max_strict = !_constraint_is_documented($spec, 'max');

	foreach my $i (-42, -1, 42) {
		if(((!defined $spec->{min}) || ($spec->{min} <= $i)) && ((!defined($spec->{max})) || ($spec->{max} >= $i))) {
			push @cases, { %{$mandatory_args}, ( $arg_name => $i ) };
		} elsif((defined($spec->{min}) && ($i < $spec->{min}) && $min_strict)
			|| (defined($spec->{max}) && ($i > $spec->{max}) && $max_strict)) {
			push @cases, { %{$mandatory_args}, ( $arg_name => $i, _STATUS => 'DIES' ) };
		}
	}

	[% IF module %]
		# Send wrong data type - builtins aren't good at checking this
		push @cases,
			_spec_type_is_enforced($spec) ? (
			{ %{$mandatory_args}, ( $arg_name => "test string in integer field $arg_name", _STATUS => 'DIES', _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => {}, _STATUS => 'DIES', _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => 3.14, _STATUS => 'DIES' ) },	# Float
			{ %{$mandatory_args}, ( $arg_name => 'xyz', _STATUS => 'DIES' ) },
			{ %{$mandatory_args}, ( $arg_name => \42, _STATUS => 'DIES' ) },	# Scalar ref
			{ %{$mandatory_args}, ( $arg_name => *STDOUT, _STATUS => 'DIES' ) },	# Global variable
			{ %{$mandatory_args}, ( $arg_name => [], _STATUS => 'DIES', _LINE => __LINE__ ) }
			) : ();
	[% END %]

	# min/max numeric boundaries
	if (defined $spec->{min}) {
		my $min = $spec->{min};
		if($min_strict) {
			push @cases, { %{$mandatory_args}, ( $arg_name => $min - 1, _STATUS => 'DIES' ) };
		} else {
			push @cases, _documented_constraint_probe_case(
				$mandatory_args, $arg_name, $min - 1, 'documented minimum probe'
			);
		}
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => "  $min  ", _LINE => __LINE__ ) },	# border, padded integer
			{ %{$mandatory_args}, ( $arg_name => $min, _LINE => __LINE__ ) };	# border
		push @cases, { %{$mandatory_args}, ( $arg_name => $min + 1 ) }	# just inside
			if(!defined($spec->{max}) || (($min + 1) <= $spec->{max}));

		if(!defined $spec->{max}) {
			push @cases, { %{$mandatory_args}, ( $arg_name => int($min + abs(rand_int())) ), _LINE => __LINE__ };
		}
		if($min <= 0) {
			push @cases, { %{$mandatory_args}, ( $arg_name => -0.0, _STATUS => 'OK' ) }	# Negative 0
				if(!defined($spec->{max}) || ($spec->{max} >= 0));
		}
	} else {
		# These fixed samples are only valid when no max excludes them.
		push @cases, { %{$mandatory_args}, ( $arg_name => 1e5, _STATUS => 'OK' ) }	# Scientific notation
			if(!defined($spec->{max}) || ($spec->{max} >= 1e5));
		push @cases, { %{$mandatory_args}, ( $arg_name => 1_000, _STATUS => 'OK' ) }	# Underscored
			if(!defined($spec->{max}) || ($spec->{max} >= 1_000));
		push @cases, { %{$mandatory_args}, ( $arg_name => '   42   ', _STATUS => 'OK' ) }	# Padded integer
			if(!defined($spec->{max}) || ($spec->{max} >= 42));
	}

	if (defined $spec->{max}) {
		my $max = $spec->{max};
		# Valid data stops at the sampling ceiling; the documented bound
		# still decides what counts as outside.
		my $sampled = $spec->{sample_max} // $max;
		push @cases, { %{$mandatory_args}, ( $arg_name => $sampled - 1 ) }
			if(!defined($spec->{min}) || (($sampled - 1) >= $spec->{min}));
		push @cases, { %{$mandatory_args}, ( $arg_name => $sampled ) }
			if(!defined($spec->{min}) || ($sampled >= $spec->{min}));
		if($max_strict) {
			push @cases, { %{$mandatory_args}, ( $arg_name => $max + 1, _STATUS => 'DIES' ) };
		} else {
			push @cases, _documented_constraint_probe_case(
				$mandatory_args, $arg_name, $max + 1, 'documented maximum probe'
			);
		}

		if(defined $spec->{min}) {
			# Test 0 only when it is inside the declared range
			push @cases, { %{$mandatory_args}, ( $arg_name => 0 ) }
				if(($spec->{'min'} <= 0) && (!defined($spec->{max}) || ($spec->{max} >= 0)));
		} else {
			push @cases, { %{$mandatory_args}, ( $arg_name => _random_number_for_spec($spec, 1) ), _DESCRIPTION => 'max is defined but min is not' };
			if($max >= 0) {
				push @cases, { %{$mandatory_args}, ( $arg_name => -0.0, _STATUS => 'OK' ) };	# Negative 0
				if($max == 0) {
					push @cases, { %{$mandatory_args}, ( $arg_name => abs(rand_int()) * -1 ), _LINE => __LINE__ };	# Any negative integer
				}
			}
		}
	} elsif(!defined $spec->{min}) {
		# Can take any number, so give it one
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => rand_int() ), _LINE => __LINE__ },
			{ %{$mandatory_args}, ( $arg_name => 0) };	# 0 is in range
	}

	return \@cases;
}

sub _generate_float_cases {
	my ($arg_name, $spec, $mandatory_args) = @_;
	my @cases;

	my $min_strict = !_constraint_is_documented($spec, 'min');
	my $max_strict = !_constraint_is_documented($spec, 'max');

	if((!defined $spec->{min}) || ($spec->{min} <= -0.1)) {
		push @cases, { %{$mandatory_args}, ( $arg_name => -0.1, _LINE => __LINE__ ) }
			if(!defined($spec->{max}) || ($spec->{max} >= -0.1));
	}
	if((!defined $spec->{min}) || ($spec->{min} <= 43.56)) {
		push @cases, { %{$mandatory_args}, ( $arg_name => 43.56 ) }
			if(!defined($spec->{max}) || ($spec->{max} >= 43.56));
	}

	[% IF module %]
		# Send wrong data type - builtins aren't good at checking this
		push @cases,
			_spec_type_is_enforced($spec) ? (
			{ %{$mandatory_args}, ( $arg_name => "test string in float field $arg_name", _STATUS => 'DIES', _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => {}, _STATUS => 'DIES', _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => \42.1, _STATUS => 'DIES' ) },	# Scalar ref
			# NaN and Inf are valid according to looks_like_number() so we
			# cannot assume they die
			# { %{$mandatory_args}, ( $arg_name => "NaN", _STATUS => 'DIES' ) },
			{ %{$mandatory_args}, ( $arg_name => [], _STATUS => 'DIES', _LINE => __LINE__ ) }
			) : ();
	[% END %]

	# min/max numeric boundaries
	if (defined $spec->{min}) {
		my $min = $spec->{min};
		if($min_strict) {
			push @cases, { %{$mandatory_args}, ( $arg_name => $min - 0.001, _STATUS => 'DIES' ), _DESCRIPTION => 'float below minimum value is denied' };
		} else {
			push @cases, _documented_constraint_probe_case(
				$mandatory_args, $arg_name, $min - 0.001, 'documented minimum probe'
			);
		}
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => $min, _LINE => __LINE__ ), _DESCRIPTION => 'float minimum value is allowed' };	# border
		push @cases, { %{$mandatory_args}, ( $arg_name => $min + 0.001 ), _DESCRIPTION => 'float above minimum value is allowed' }	# just inside
			if(!defined($spec->{max}) || (($min + 0.001) <= $spec->{max}));

		[% IF module %]
			push @cases, { %{$mandatory_args}, ( $arg_name => "-inf", _STATUS => 'DIES' ) } if $min_strict;
		[% END %]

		if(!defined $spec->{max}) {
			if($min <= 0) {
				push @cases, { %{$mandatory_args}, ( $arg_name => $min + abs(rand_num()) ), _LINE => __LINE__ };	# Any positive number
			} else {
				push @cases, { %{$mandatory_args}, ( $arg_name => $min + abs(rand_num()) ), _DESCRIPTION => 'min is defined but max is not' };
			}
		}
	}
	if (defined $spec->{max}) {
		my $max = $spec->{max};
		my $sampled = $spec->{sample_max} // $max;
		push @cases, { %{$mandatory_args}, ( $arg_name => $sampled - 0.000001 ) }
			if(!defined($spec->{min}) || (($sampled - 0.000001) >= $spec->{min}));
		push @cases, { %{$mandatory_args}, ( $arg_name => $sampled ) }
			if(!defined($spec->{min}) || ($sampled >= $spec->{min}));
		if($max_strict) {
			push @cases, { %{$mandatory_args}, ( $arg_name => $max + 0.000001, _STATUS => 'DIES' ) };
		} else {
			push @cases, _documented_constraint_probe_case(
				$mandatory_args, $arg_name, $max + 0.000001, 'documented maximum probe'
			);
		}

		[% IF module %]
			push @cases,
				{ %{$mandatory_args}, ( $arg_name => "inf", _STATUS => 'DIES' ) },
				{ %{$mandatory_args}, ( $arg_name => 9**9**9, _STATUS => 'DIES' ) } if $max_strict;
		[% END %]

		if(defined $spec->{min}) {
			# Test 0 if it's in range
			push @cases, { %{$mandatory_args}, ( $arg_name => 0 ) }
				if(($spec->{'min'} >= 0) && ($max >= 0));
		} else {
			push @cases, { %{$mandatory_args}, ( $arg_name => _random_number_for_spec($spec, 0) ), _LINE => __LINE__ };
			if($max == 0) {
				push @cases, { %{$mandatory_args}, ( $arg_name => abs(rand_num()) * -0.00000001 ) };	# Any negative number
			}
		}
	} elsif(!defined $spec->{min}) {
		# Can take any number, so give it some
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => rand_num(), _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => 1.23 ) },
			{ %{$mandatory_args}, ( $arg_name => -42.1 ) },
			{ %{$mandatory_args}, ( $arg_name => -0.0 ) },	# -0 is in range
			{ %{$mandatory_args}, ( $arg_name => 0 ) };	# 0 is in range
	}

	return \@cases;
}

# basic boolean edge cases
sub _generate_boolean_cases {
	my ($arg_name, $spec, $mandatory_args) = @_;

	my @cases;

	if(_has_memberof($spec)) {
		# memberof already defines allowed booleans
		foreach my $val (@{$spec->{memberof}}) {
			push @cases, { %{$mandatory_args}, ( $arg_name => $val ) };
		}
	} else {
		@cases = (
			{ %{$mandatory_args}, ( $arg_name => 0 ) },
			{ %{$mandatory_args}, ( $arg_name => 1 ) },
			{ %{$mandatory_args}, ( $arg_name => 'true' ) },
			{ %{$mandatory_args}, ( $arg_name => 'false' ) },
			{ %{$mandatory_args}, ( $arg_name => 'off' ) },
			{ %{$mandatory_args}, ( $arg_name => 'on' ) },
			{ %{$mandatory_args}, ( $arg_name => 'yes' ) },
			{ %{$mandatory_args}, ( $arg_name => 'no' ) },
		);
		push @cases, (
			{ %{$mandatory_args}, ( $arg_name => 'xyzzy', _STATUS => 'DIES' ) },	# invalid boolean
			{ %{$mandatory_args}, ( $arg_name => -1, _STATUS => 'DIES' ) },	# invalid boolean
			{ %{$mandatory_args}, ( $arg_name => 2, _STATUS => 'DIES' ) },	# invalid boolean
			{ %{$mandatory_args}, ( $arg_name => bless({}, 'Evil::Class'), _STATUS => 'DIES', _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => [ 1 ], _STATUS => 'DIES' ) }	# invalid boolean
		) if(_spec_type_is_enforced($spec));
	}

	push @cases, { %{$mandatory_args}, ( $arg_name => undef, _STATUS => 'DIES' ) } if($config{'test_undef'});
	push @cases, { %{$mandatory_args}, ( $arg_name => "\0", _STATUS => 'DIES' ) }
		if($config{'test_nuls'} && _spec_type_is_enforced($spec));

	return \@cases;
}

# The field's source decides whether the routine's own validator checks
# types.  Each constraint has its own provenance: a documented minimum and a
# maximum confirmed in the code on the same field are separate decisions.
sub _spec_source
{
	my ($spec) = @_;

	return (ref($spec) eq 'HASH') ? ($spec->{_source} // '') : '';
}

sub _constraint_source
{
	my ($spec, $constraint) = @_;

	if((ref($spec) eq 'HASH') && (ref($spec->{_constraint_source}) eq 'HASH')) {
		my $source = $spec->{_constraint_source}{$constraint};
		return $source if defined($source) && length($source);
	}

	return _spec_source($spec);
}

sub _constraint_is_documented
{
	my $source = _constraint_source(@_);

	return $documented_sources{$source} ? 1 : 0;
}


sub _spec_checks_types
{
	return _spec_source($_[0]) eq $type_checks_source;
}

# Whether the routine's own checks reject a value of the wrong type.  A
# hand-written schema carries no marker and keeps that expectation; a type
# the extractor inferred only from the code, a signature or a field
# declaration says the parameter exists, not that anything else dies.
sub _spec_type_is_enforced
{
	my $source = _spec_source($_[0]);

	return 1 unless defined($source) && length($source);
	return ($source eq $type_checks_source) ? 1 : 0;
}

# A documented string or numeric bound sizes the valid data.  Some cases are
# built from fixed samples rather than from the bound, so drop any that the
# bound excludes; otherwise a routine that enforces its documented range
# fails on a value the harness generated as expected-to-live.
sub _filter_documented_bound_cases
{
	my ($cases, $input) = @_;

	my @kept;
	CASE:
	foreach my $case (@{$cases}) {
		# Explicit out-of-bound probes are meant to be run and reported; they
		# must survive this filter even though their value is outside a bound.
		if($case->{_DOCUMENTED_CONSTRAINTS}) {
			push @kept, $case;
			next CASE;
		}

		foreach my $field (keys %{$input}) {
			my $spec = $input->{$field};
			next unless(ref($spec) eq 'HASH');
			next unless _constraint_is_documented($spec, 'min')
				|| _constraint_is_documented($spec, 'max');

			my $type = $spec->{type} // 'string';
			next unless($type =~ /^(?:string|integer|number|float)$/);

			my ($value, $found);
			if(exists($case->{$field})) {
				($value, $found) = ($case->{$field}, 1);
			} elsif((ref($case->{'_input'}) eq 'HASH') && exists($case->{'_input'}{$field})) {
				($value, $found) = ($case->{'_input'}{$field}, 1);
			} elsif(($field eq '_input') && exists($case->{'_input'})) {
				($value, $found) = ($case->{'_input'}, 1);
			}
			next unless $found;

			# References, undef and other type probes are not size or range
			# values, so the bound does not apply to them.
			next unless defined($value) && !ref($value);

			if($type eq 'string') {
				next CASE unless _string_length_in_documented_bounds($spec, length($value));
			} else {
				next unless Scalar::Util::looks_like_number($value);
				next CASE if _constraint_is_documented($spec, 'min')
					&& defined($spec->{min}) && ($value < $spec->{min});
				next CASE if _constraint_is_documented($spec, 'max')
					&& defined($spec->{max}) && ($value > $spec->{max});
			}
		}

		push @kept, $case;
	}

	return \@kept;
}

sub _string_length_in_bounds
{
	my ($spec, $length) = @_;

	return 0 if defined($spec->{min}) && ($length < $spec->{min});
	return 0 if defined($spec->{max}) && ($length > $spec->{max});
	return 1;
}

sub _string_length_in_documented_bounds
{
	my ($spec, $length) = @_;

	return 0 if _constraint_is_documented($spec, 'min')
		&& defined($spec->{min}) && ($length < $spec->{min});
	return 0 if _constraint_is_documented($spec, 'max')
		&& defined($spec->{max}) && ($length > $spec->{max});
	return 1;
}

sub _has_memberof
{
	my ($spec) = @_;

	return (ref($spec) eq 'HASH') && (ref($spec->{memberof}) eq 'ARRAY') && @{$spec->{memberof}};
}

# A member list is the whole valid domain.  A value outside a hand-written
# list is an error the routine promised to reject; outside a documented list
# it is simply not documented, so no must-die case is invented for it.
sub _memberof_cases
{
	my ($arg_name, $spec, $mandatory_args) = @_;

	my @set = @{$spec->{memberof}};
	my @cases = map { { %{$mandatory_args}, ( $arg_name => $_ ) } } @set;

	# The harness injected this list itself (a temporary file or directory
	# the routine's -e/-f/-d test needs), so it is not the routine's domain
	# and a value outside it is not an error the routine promised to reject.
	return @cases if($spec->{'_fixture'});

	my $type = $spec->{type} // 'string';
	my $outside = ($type =~ /^(?:integer|number|float)$/)
		? (sort { $a <=> $b } @set)[-1] + 1
		: 'INVALID_MEMBEROF';

	if(_constraint_is_documented($spec, 'memberof')) {
		# Advisory: run the outside value.  A death means the routine does
		# enforce the documented list; survival is reported as a documented
		# constraint the routine does not keep.
		push @cases, _documented_constraint_probe_case(
			$mandatory_args, $arg_name, $outside, 'documented memberof probe'
		);
		return @cases;
	}

	push @cases, { %{$mandatory_args}, ( $arg_name => $outside, _STATUS => 'DIES' ) };

	return @cases;
}

# Size bounds for an arrayref parameter.  A documented bound is a probe that
# may die; a hand-written one is an error the routine must report.
sub _generate_arrayref_cases
{
	my ($arg_name, $spec, $mandatory_args) = @_;

	my @cases;
	my $min_documented = _constraint_is_documented($spec, 'min');
	my $max_documented = _constraint_is_documented($spec, 'max');

	if(defined $spec->{min}) {
		my $len = $spec->{min};
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => _random_array_for_spec($spec, $len + 1) ) },	# just inside
			{ %{$mandatory_args}, ( $arg_name => _random_array_for_spec($spec, $len) ) };	# border
		if($len > 0) {
			push @cases, $min_documented
				? _documented_constraint_probe_case($mandatory_args, $arg_name, _random_array_for_spec($spec, $len - 1), 'documented minimum probe')
				: { %{$mandatory_args}, ( $arg_name => _random_array_for_spec($spec, $len - 1), _STATUS => 'DIES' ) };
		}
	} elsif($config{'test_empty'}) {
		push @cases, { %{$mandatory_args}, ( $arg_name => [] ) };	# No min, empty array is allowable
	}

	if(defined $spec->{max}) {
		my $len = $spec->{max};
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => _random_array_for_spec($spec, $len - 1) ) },	# just inside
			{ %{$mandatory_args}, ( $arg_name => _random_array_for_spec($spec, $len) ) };	# border
		push @cases, $max_documented
			? _documented_constraint_probe_case($mandatory_args, $arg_name, _random_array_for_spec($spec, $len + 1), 'documented maximum probe')
			: { %{$mandatory_args}, ( $arg_name => _random_array_for_spec($spec, $len + 1), _STATUS => 'DIES' ) };
	}

	return \@cases;
}

# The same for a hashref parameter's key count.
sub _generate_hashref_cases
{
	my ($arg_name, $spec, $mandatory_args) = @_;

	my @cases;
	my $min_documented = _constraint_is_documented($spec, 'min');
	my $max_documented = _constraint_is_documented($spec, 'max');
	my $hash_of = sub { my ($len) = @_; return _random_hash_for_spec($spec, $len); };

	# A schema that maps key names to element schemas fixes the key set, so
	# there is no size to vary: one valid hash covers it.
	my $nested = $spec->{schema};
	if((ref($nested) eq 'HASH') && !exists($nested->{type})) {
		return [ { %{$mandatory_args}, ( $arg_name => _random_hash_for_spec($spec) ) } ];
	}

	if(defined $spec->{min}) {
		my $len = $spec->{min};
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => $hash_of->($len + 1) ) },
			{ %{$mandatory_args}, ( $arg_name => $hash_of->($len) ) };
		if($len > 0) {
			push @cases, $min_documented
				? _documented_constraint_probe_case($mandatory_args, $arg_name, $hash_of->($len - 1), 'documented minimum probe')
				: { %{$mandatory_args}, ( $arg_name => $hash_of->($len - 1), _STATUS => 'DIES' ) };
		}
	} elsif($config{'test_empty'}) {
		push @cases, { %{$mandatory_args}, ( $arg_name => {} ) };	# No min, empty hash is allowable
	}

	if(defined $spec->{max}) {
		my $len = $spec->{max};
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => $hash_of->($len - 1) ) },
			{ %{$mandatory_args}, ( $arg_name => $hash_of->($len) ) };
		push @cases, $max_documented
			? _documented_constraint_probe_case($mandatory_args, $arg_name, $hash_of->($len + 1), 'documented maximum probe')
			: { %{$mandatory_args}, ( $arg_name => $hash_of->($len + 1), _STATUS => 'DIES' ) };
	}

	return \@cases;
}

# One entry point for every parameter type, so the single-schema and
# named-field forms cannot drift apart.
sub _generate_type_cases
{
	my ($arg_name, $type, $spec, $mandatory_args) = @_;

	return _generate_integer_cases($arg_name, $spec, $mandatory_args) if($type eq 'integer');
	return _generate_float_cases($arg_name, $spec, $mandatory_args) if(($type eq 'number') || ($type eq 'float'));
	return _generate_string_cases($arg_name, $spec, $mandatory_args) if($type eq 'string');
	return _generate_arrayref_cases($arg_name, $spec, $mandatory_args) if(($type eq 'arrayref') || ($type eq 'array'));
	return _generate_hashref_cases($arg_name, $spec, $mandatory_args) if($type eq 'hashref');
	return _generate_boolean_cases($arg_name, $spec, $mandatory_args) if($type eq 'boolean');

	return [];
}

# Build an out-of-bound case for a POD-derived bound.  The case is run
# like any other expected-to-live input, but a death is accepted; survival
# is recorded as a documentation contradiction.  _DOCUMENTED_CONSTRAINTS
# marks the case as a documented-constraint probe: it is kept by
# _filter_documented_bound_cases and reported rather than expected to die.
sub _documented_constraint_probe_case
{
	my ($mandatory_args, $field, $value, $description) = @_;

	return {
		%{$mandatory_args},
		$field => $value,
		_DOCUMENTED_CONSTRAINTS => 1,
		_DESCRIPTION => $description,
	};
}

# Record a documented-only constraint once per parameter.  Every kind of
# constraint is reported the same way: bounds, member lists and patterns.
sub _note_documented_constraint
{
	my ($name, $spec) = @_;

	return unless ref($spec) eq 'HASH';
	my @documented;
	push @documented, 'min' if defined($spec->{min}) && _constraint_is_documented($spec, 'min');
	push @documented, 'max' if defined($spec->{max}) && _constraint_is_documented($spec, 'max');
	push @documented, 'memberof' if _has_memberof($spec) && _constraint_is_documented($spec, 'memberof');
	push @documented, 'matches' if defined($spec->{matches}) && _constraint_is_documented($spec, 'matches');
	return unless @documented;

	(my $shown = $name) =~ s/^_+//;
	my $which = join(', ', @documented);
	diag("documented-only constraint on '$shown' ($which) is not enforced (from POD); values outside it are not expected to die")
		unless $_documented_bound_logged{$shown}++;
}

# Measure the value against the kind of bound the spec declares.  Non-values
# such as undef, references sent to a scalar parameter and non-numeric strings
# sent to a numeric parameter are type probes, not bound observations.
sub _documented_bound_measure
{
	my ($spec, $value) = @_;

	my $type = $spec->{type} // 'string';
	if($type eq 'string') {
		return unless defined($value) && !ref($value);
		return (length($value), 'length');
	}
	if(($type eq 'integer') || ($type eq 'number') || ($type eq 'float')) {
		return unless defined($value) && !ref($value) && looks_like_number($value);
		return (0 + $value, 'value');
	}
	if(($type eq 'arrayref') || ($type eq 'array')) {
		return unless ref($value) eq 'ARRAY';
		return (scalar(@{$value}), 'element count');
	}
	if($type eq 'hashref') {
		return unless ref($value) eq 'HASH';
		return (scalar(keys %{$value}), 'key count');
	}
	return;
}

sub _documented_bound_range
{
	my ($spec) = @_;

	my @bounds;
	push @bounds, "min $spec->{min}"
		if defined($spec->{min}) && _constraint_is_documented($spec, 'min');
	push @bounds, "max $spec->{max}"
		if defined($spec->{max}) && _constraint_is_documented($spec, 'max');
	return join(', ', @bounds);
}

sub _failure_context
{
	my ($input) = @_;

	my $seed = defined($seed) ? $seed : 'none';
	my $shown = eval {
		require Data::Dumper;
		local $Data::Dumper::Terse = 1;
		local $Data::Dumper::Indent = 0;
		local $Data::Dumper::Sortkeys = 1;
		Data::Dumper::Dumper($input);
	};
	$shown = '?' unless defined($shown);
	$shown =~ s/\s+/ /g;
	$shown = substr($shown, 0, 300) . '...' if(length($shown) > 300);

	return "seed = $seed; input = $shown";
}

sub _short_value
{
	my ($value) = @_;

	return 'undef' unless defined($value);
	return ref($value) if ref($value);
	(my $shown = $value) =~ s/\s+/ /g;
	return (length($shown) > 40) ? substr($shown, 0, 37) . '...' : $shown;
}

# Split the case's observed values into those inside and outside their POD
# constraints (bounds, member lists and patterns).  A death is a contradiction
# for the first list; survival is a contradiction for the second.
sub _documented_constraint_findings
{
	my ($input, $schema) = @_;

	my @checks;
	if((ref($schema) eq 'HASH') && exists($schema->{type}) && !ref($schema->{type})) {
		# A single scalar schema: type/min/max are the parameter's spec.
		push @checks, ['_input', $schema, $input];
	} elsif((ref($input) eq 'HASH') && (ref($schema) eq 'HASH')) {
		foreach my $field (sort keys %{$schema}) {
			my $spec = $schema->{$field};
			next unless ref($spec) eq 'HASH';
			next unless exists($input->{$field});
			push @checks, [$field, $spec, $input->{$field}];
		}
	}

	my (@inside, @outside);
	foreach my $check (@checks) {
		my ($field, $spec, $value) = @{$check};
		my $min_documented = _constraint_is_documented($spec, 'min') && defined($spec->{min});
		my $max_documented = _constraint_is_documented($spec, 'max') && defined($spec->{max});

		my $shown = $field;
		$shown =~ s/^_+//;

		if(($min_documented || $max_documented) && defined($value)) {
			my ($measured, $unit) = _documented_bound_measure($spec, $value);
			if(defined($measured)) {
				my $range = _documented_bound_range($spec);
				my $example = "$unit $measured";
				my $inside = ((!$min_documented || ($measured >= $spec->{min})) &&
					(!$max_documented || ($measured <= $spec->{max})));
				if($inside) {
					push @inside, {
						key => "routine rejected a value inside the documented bound on '$shown' ($range)",
						example => $example,
					};
				} else {
					push @outside, {
						key => "routine accepted a value outside the documented bound on '$shown' ($range)",
						example => $example,
					};
				}
			}
		}

		# References and undef are type probes, not members or matches.
		next unless defined($value) && !ref($value);
		my $example = "value '" . _short_value($value) . "'";

		if(_has_memberof($spec) && _constraint_is_documented($spec, 'memberof')) {
			my %member = map { $_ => 1 } @{$spec->{memberof}};
			my $list = 'one of: ' . join(', ', @{$spec->{memberof}});
			if($member{$value}) {
				push @inside, {
					key => "routine rejected a value inside the documented memberof list on '$shown' ($list)",
					example => $example,
				};
			} else {
				push @outside, {
					key => "routine accepted a value outside the documented memberof list on '$shown' ($list)",
					example => $example,
				};
			}
		}

		if(defined($spec->{matches}) && _constraint_is_documented($spec, 'matches')) {
			my $re = $spec->{matches};
			$re = qr/$re/ if(ref($re) ne 'Regexp');
			my $matched = eval { $value =~ $re ? 1 : 0 };
			if(defined($matched) && $matched) {
				push @inside, {
					key => "routine rejected a value matching the documented pattern on '$shown' ($re)",
					example => $example,
				};
			} elsif(defined($matched)) {
				push @outside, {
					key => "routine accepted a value that does not match the documented pattern on '$shown' ($re)",
					example => $example,
				};
			}
		}

		if(defined($spec->{nomatch}) && _constraint_is_documented($spec, 'nomatch')) {
			my $re = $spec->{nomatch};
			$re = qr/$re/ if(ref($re) ne 'Regexp');
			my $matched = eval { $value =~ $re ? 1 : 0 };
			if(defined($matched) && $matched) {
				push @outside, {
					key => "routine accepted a value matching the documented nomatch pattern on '$shown' ($re)",
					example => $example,
				};
			}
		}
	}

	return (\@inside, \@outside);
}

sub _record_documented_constraint_contradictions
{
	my ($findings) = @_;

	foreach my $finding (@{$findings}) {
		my $entry = $_documented_constraint_contradictions{$finding->{key}} ||= {
			count => 0,
			example => $finding->{example},
		};
		$entry->{count}++;
	}
}

# The replacement for lives_ok in cases whose arguments carry a documented
# constraint.  A case that dies on a value the POD says is valid is recorded
# and tolerated instead of failing; a normal death still fails.  An
# outside-constraint probe that dies is expected and passes; one that survives
# records a documentation contradiction, reported at the end of the run.
sub _documented_lives_ok(&$)
{
	my ($code, $name) = @_;

	local $@;
	my $ok = eval { $code->(); 1 };
	my $err = $@;

	if($ok) {
		pass($name);
		_record_documented_constraint_contradictions($_documented_outside);
		return 1;
	}

	if($documented_constraint_probe && (!defined($err) || ($err !~ /__TIMEOUT__/))) {
		pass($name);
		return 1;
	}

	if((!defined($err) || ($err !~ /__TIMEOUT__/)) && @{$_documented_inside}) {
		_record_documented_constraint_contradictions($_documented_inside);
		$documented_tolerated = 1;
		pass($name);
		return 1;
	}

	fail($name);
	diag($err) if defined($err) && length($err);
	diag(_failure_context($_current_input));
	return 0;
}

# The DIES counterpart of _documented_lives_ok: a case that should die but
# survives fails and names the seed and input, so the run can be replayed.
sub _dies_with_context(&$;$)
{
	my ($code, $name, $allow_undef) = @_;

	local $@;
	my $died = !eval { $code->(); 1 };
	my $err = $@;

	if($died) {
		pass($name);
		return $err;
	}

	# A routine whose contract reports invalid input by returning undef is
	# not also required to croak, so the caller records the tolerance with
	# its own pass rather than this call failing the case here.
	return if($allow_undef);

	fail($name);
	diag(_failure_context($_current_input));
	return;
}

sub _report_documented_constraint_contradictions
{
	return unless keys %_documented_constraint_contradictions;

	my @keys = sort keys %_documented_constraint_contradictions;
	diag('Documented-constraint contradictions found by fuzzing (advisory, seed '
		. (defined($seed) ? $seed : 'none') . '):');
	foreach my $key (@keys) {
		my $entry = $_documented_constraint_contradictions{$key};
		my $times = ($entry->{count} == 1) ? '' : " ($entry->{count} times)";
		diag("  $key$times; example: $entry->{example}");
	}

	if($config{'strict_documented'}) {
		fail("strict-documented: $_ (seed " . (defined($seed) ? $seed : 'none') . ')') for @keys;
	} else {
		diag('These contradictions are tolerated; use --strict-documented to fail on them.');
	}
}

sub _generate_string_cases
{
	my ($arg_name, $spec, $mandatory_args) = @_;

	my @cases;

	# A constraint taken from POD sizes valid data; it does not promise that
	# the routine rejects what lies outside it.  Each constraint is decided on
	# its own, so a code-enforced maximum stays strict on a field whose
	# minimum is only documented.
	my $min_strict = !_constraint_is_documented($spec, 'min');
	my $max_strict = !_constraint_is_documented($spec, 'max');
	my $matches_strict = !_constraint_is_documented($spec, 'matches');

	return [ _memberof_cases($arg_name, $spec, $mandatory_args) ] if _has_memberof($spec);

	if(defined $spec->{min}) {
		my $len = $spec->{min};
		my $re = $spec->{matches};
		$re = qr/$re/ if defined($re) && (ref($re) ne 'Regexp');

		if(defined($re)) {
			my $str = _random_string_matching($re, length => $len);
			push @cases, { %{$mandatory_args}, ( $arg_name => $str ) }
				if defined($str) && ($str =~ $re);
		} else {
			push @cases, { %{$mandatory_args}, ( $arg_name => _random_string_with_length($spec, $len) ) };
			if($len > 1) {
				my $newline = "he\nlo";
				push @cases, { %{$mandatory_args}, ( $arg_name => $newline, _LINE => __LINE__ ) }
					if _string_length_in_bounds($spec, length($newline));
			}
		}

		if($min_strict) {
			if($len > 1) {
				push @cases, { %{$mandatory_args}, ( $arg_name => _random_string_with_length($spec, $len - 1), _STATUS => 'DIES' ) };
			} elsif(($len == 1) && $config{'test_empty'}) {
				push @cases, { %{$mandatory_args}, ( $arg_name => '', _STATUS => 'DIES' ) };
			}
		} elsif($len > 0) {
			my $short = ($len > 1) ? ('x' x ($len - 1)) : '';
			push @cases, _documented_constraint_probe_case(
				$mandatory_args, $arg_name, $short, 'documented minimum probe'
			);
		}

		if(!$spec->{'_directory'} && !defined($spec->{matches}) && !defined($spec->{nomatch}) && ($len <= 1)) {
			foreach my $sample (' ', "\n", " \n ") {
				push @cases, { %{$mandatory_args}, ( $arg_name => $sample, _LINE => __LINE__ ) }
					if _string_length_in_bounds($spec, length($sample));
			}
		}

		if($len <= 0) {
			# A documented minimum of zero allows "0"; a hand-written
			# bound outside the accepted lengths still expects it to die.
			if(_string_length_in_bounds($spec, 1)) {
				push @cases, { %{$mandatory_args}, ( $arg_name => '0', _LINE => __LINE__ ) };
			} elsif($min_strict) {
				push @cases, { %{$mandatory_args}, ( $arg_name => '0', _STATUS => 'DIES' ) };
			}

			if($config{'test_security'}) {
				foreach my $sample ('<script>alert(1)</script>', "'; DROP TABLE foo --") {
					push @cases, { %{$mandatory_args}, ( $arg_name => $sample, _LINE => __LINE__ ) }
						if _string_length_in_bounds($spec, length($sample));
				}
			}
		}
	}
	if(defined $spec->{max}) {
		my $len = $spec->{max};
		if(!defined($spec->{min}) || ($spec->{min} != $len)) {
			my $re = $spec->{matches};
			$re = qr/$re/ if defined($re) && (ref($re) ne 'Regexp');

			if(defined($re)) {
				foreach my $count ($len - 1, $len) {
					next if $count < 0;
					next unless _string_length_in_bounds($spec, $count);
					my $str = _random_string_matching($re, length => $count);
					push @cases, { %{$mandatory_args}, ( $arg_name => $str, _LINE => __LINE__ ) }
						if defined($str) && ($str =~ $re);
				}
			} else {
				push @cases, { %{$mandatory_args}, ( $arg_name => _random_string_with_length($spec, $len - 1), _LINE => __LINE__ ) }
					if ($len > 0) && _string_length_in_bounds($spec, $len - 1);
				push @cases, { %{$mandatory_args}, ( $arg_name => _random_string_with_length($spec, $len), _LINE => __LINE__ ) };
			}

		}
		if($max_strict) {
			push @cases, { %{$mandatory_args}, ( $arg_name => rand_str($len + 1), _LINE => __LINE__, _STATUS => 'DIES' ) };
		} else {
			push @cases, _documented_constraint_probe_case(
				$mandatory_args, $arg_name, 'x' x ($len + 1), 'documented maximum probe'
			);
		}
	} elsif(!$spec->{matches} && !$spec->{nomatch} && !$spec->{'_directory'}) {
		my $long = defined($spec->{min}) ? (($spec->{min} + 1) * 1_000) : 65_536;
		push @cases, { %{$mandatory_args}, ( $arg_name => rand_str($long), _LINE => __LINE__ ) };
		# A byte string is not text: a wide character is not a value the
		# routine was asked to accept, so it gets no BOM probe.
		push @cases, { %{$mandatory_args}, ( $arg_name => "\x{FEFF}", _STATUS => 'OK', _LINE => __LINE__, _DESCRIPTION => 'Byte order marker' ) }
			unless (($spec->{'semantic'} // '') eq 'bytes');
	}

	# A directory parameter gets no '' case: routines commonly read an empty
	# path as "not given" rather than as a directory that does not exist.
	# A minimum of zero already produced the empty string above, and a pattern
	# is not assumed to match it.
	if(!$spec->{'_directory'} && !defined($spec->{min}) && !defined($spec->{matches})
		&& (!defined($spec->{max}) || ($spec->{max} > 0))) {
		if($config{'test_empty'}) {
			# An empty value the code refuses is an error, not a survival case.
			push @cases, { %{$mandatory_args}, ( $arg_name => '',
				($spec->{_not_empty} ? (_STATUS => 'DIES') : (_NAME => $arg_name)),
				_LINE => __LINE__ ) };
		}
	}

	if(!$spec->{'_directory'} && !defined($spec->{min}) && !defined($spec->{max})
		&& !defined($spec->{matches}) && !defined($spec->{nomatch})) {
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => "\n" ) },	# new lines are fun
			{ %{$mandatory_args}, ( $arg_name => ' ' ) },
			{ %{$mandatory_args}, ( $arg_name => " \n " ) };
	}

	if(defined $spec->{matches}) {
		my $re = $spec->{matches};

		# --- Positive controls ---
		foreach my $val (@candidate_good) {
			next unless $val =~ $re;
			next unless _string_length_in_bounds($spec, length($val));
			push @cases, { %{$mandatory_args}, ( $arg_name => $val ) };
			last; # one good match is enough
		}

		# --- Negative controls ---
		foreach my $val (@candidate_bad) {
			if(!defined($val)) {
				push @cases, { _input => undef, _STATUS => 'DIES', _LINE => __LINE__ } if($config{'test_undef'});
			} elsif($matches_strict && ($val !~ $re)) {
				push @cases, { _input => $val, _STATUS => 'DIES', _LINE => __LINE__ };
			} elsif($val !~ $re) {
				# Documented pattern: run one non-matching value as an
				# advisory probe instead of demanding that it dies.
				push @cases, _documented_constraint_probe_case(
					$mandatory_args, $arg_name, $val, 'documented pattern probe'
				);
				last;
			}
		}
		push @cases, { $arg_name => undef, _STATUS => 'DIES' } if($config{'test_undef'});
	}
	if(defined $spec->{nomatch}) {
		my $re = $spec->{nomatch};

		# --- Positive controls ---
		foreach my $val (@candidate_good) {
			next if $val =~ $re;
			next unless _string_length_in_bounds($spec, length($val));
			push @cases, { %{$mandatory_args}, ( $arg_name => $val ) };
			last; # one good match is enough
		}

		# --- Negative controls ---
		foreach my $val (@candidate_bad) {
			next unless defined($val);
			next unless $val =~ $re;
			if(_constraint_is_documented($spec, 'nomatch')) {
				push @cases, _documented_constraint_probe_case(
					$mandatory_args, $arg_name, $val, 'documented nomatch probe'
				);
				last;
			}
			push @cases, { $arg_name => $val, _STATUS => 'DIES' };
		}
	}

	[% IF module %]
		# Send wrong data type - builtins aren't good at checking this,
		# and only where the routine's own validator enforces the type.
		# A type declared in POD is documentation, not a promise to
		# reject a reference, so asserting that it dies invents a
		# contract the routine never made.
		if(_spec_checks_types($spec)) {
		if($config{'test_nuls'}) {
			push @cases,
				{ %{$mandatory_args}, $arg_name => "\0", _STATUS => 'DIES', _LINE => __LINE__ },
				{ %{$mandatory_args}, $arg_name => "nul\0", _STATUS => 'DIES', _LINE => __LINE__ },
				{ %{$mandatory_args}, $arg_name => "\0nul", _STATUS => 'DIES', _LINE => __LINE__ };
			if(defined($spec->{matches})) {
				my $re = $spec->{matches};
				foreach my $val (@candidate_good) {
					$val = "$val\0";
					if ($val !~ $re) {
						push @cases, { %{$mandatory_args}, ( $arg_name => $val, _STATUS => 'DIES', _DESCRIPTION => 'Nul byte after regex' ) };
					}
					$val = "\0$val";
					if ($val !~ $re) {
						push @cases, { %{$mandatory_args}, ( $arg_name => $val, _STATUS => 'DIES', _DESCRIPTION => 'Nul byte before regex' ) };
					}
				}
			}
		}
		if($config{'test_empty'}) {
			push @cases,
				{ %{$mandatory_args}, ( $arg_name => [], _STATUS => 'DIES', _LINE => __LINE__ ) },
				{ %{$mandatory_args}, ( $arg_name => {}, _STATUS => 'DIES', _LINE => __LINE__ ) };
		}
		push @cases,
			{ %{$mandatory_args}, ( $arg_name => \'ref to scalar', _STATUS => 'DIES', _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => sub { die 'boom' }, _STATUS => 'DIES', _LINE => __LINE__ ) },
			{ %{$mandatory_args}, ( $arg_name => bless({}, 'Evil::Class'), _STATUS => 'DIES', _LINE => __LINE__ ) },
			# { %{$mandatory_args}, ( $arg_name => [1, 2, 3], _STATUS => 'DIES', _LINE => __LINE__ ) },	# Generates false positives. Why?
			{ %{$mandatory_args}, ( $arg_name => { a => 1 }, _STATUS => 'DIES', _LINE => __LINE__ ) };
		}
	[% END %]

	return \@cases;
}

# dedup, fuzzing can easily generate repeats
# FIXME: I don't think this catches them all
# FIXME: Handle cases with Class::Simple calls
# FIXME: The JSON encoding fails on various data types that are sent (e.g. scalar refs, objects) so don't bother
sub _dedup_cases
{
	my $cases = shift;

	# Do not use JSON::MaybeXS because it will fail on non utf-8 characters
	require JSON::PP;
	JSON::PP->import();

	# return inside eval{} returns from the eval block, not from
	# _dedup_cases — the deduped result must be captured here, or
	# this always falls through to the unduplicated $cases below.
	#
	# encode_json() does not sort hash keys, so two structurally
	# identical case hashrefs can serialize with different key order
	# (Perl's per-hash iteration order randomisation) and dodge the
	# %seen check below — use ->canonical to make the dump order-stable.
	my $rc = eval {
		my $json = JSON::PP->new->canonical;
		my %seen;
		my @rc = grep {
			my $dump = $json->encode($_);
			!$seen{$dump}++
		} @{$cases};

		return \@rc;
	};
	# Carp::carp(__PACKAGE__, ": disabling deduping: $@");

	return $@ ? $cases : $rc;
}

sub generate_tests
{
	my $input = $_[0];
	my %mandatory_args = %{$_[1]};

	my @cases;

	foreach my $field (keys %input) {
		my $spec = $input{$field} || {};
		_note_documented_constraint($field, $spec);
		foreach my $field(keys %{$spec}) {
			next if($field =~ /^_/);	# Ignore comments
			if(!grep({ $_ eq $field } ('type', 'min', 'max', 'sample_max', 'optional', 'matches', 'can', 'position', 'named', 'memberof', 'semantic', 'isa'))) {
				carp "unhandled schema keyword '$field'; skipping";
				next;
			}
		}
	}

	# Build a test of the mandatory args
	push @cases, { _input => \%mandatory_args, status => 'OK' } if(keys %mandatory_args);

	for (1..[% iterations_code %]) {
		# One by one change each of the mandatory fields
		foreach my $field (keys %input) {
			my $spec = $input{$field} || {};
			next if $spec->{'memberof'};	# Memberof data is created below
			my $type = $spec->{type} || 'string';

			my %case_input = (%mandatory_args);
			# 1) Sometimes pick a field-specific edge-case
			if (exists $edge_cases{$field} && rand() < PROB_EDGE_CASE) {
				push @cases, { _input => {%case_input}, status => 'OK' } if(keys %case_input);
				$case_input{$field} = _pick_from($edge_cases{$field});
				next;
			}

			# 2) Sometimes pick a type-level edge-case
			if (exists $type_edge_cases{$type} && rand() < 0.3) {
				$case_input{$field} = _pick_from($type_edge_cases{$type});
				push @cases, { _input => \%case_input, status => 'OK' } if(keys %case_input);
				next;
			}

			# 3) Sormal random generation by type
			if ($type eq 'string') {
				if(my $re = $spec->{matches}) {
					if(ref($re) ne 'Regexp') {
						$re = qr/$re/;
					}
					my $generated = _random_string_matching($re, _length_bounds($spec));
					# No string can satisfy this pattern: skip this case rather
					# than sending a value that cannot match it.
					next unless defined($generated);
					$case_input{$field} = $generated;
				} elsif(my $semantic = $spec->{'semantic'}) {
					if($semantic eq 'bytes') {
						# A byte string holds octets, not characters: leaving the
						# text filler in place never exercised a high byte.
						$case_input{$field} = _random_bytes_for_spec($spec);
					} elsif($semantic eq 'email') {
						$case_input{$field} = rand_email($spec->{'max'} // $spec->{'min'});
					} else {
						diag(__LINE__, ": TODO: handle semantic type '$semantic'");
					}
				} elsif(!$spec->{'memberof'}) {
					$case_input{$field} = _random_string_for_spec($spec);
					if($config{'test_empty'} && !defined($spec->{min}) && (!defined($spec->{max}) || $spec->{max} > 0)) {
						push @cases, { _input => {%case_input}, status => 'OK' } if(keys %case_input);
						my $non_empty = $case_input{$field};
						$case_input{$field} = '';
						if($spec->{'_not_empty'}) {
							# An empty value the code refuses is an error, not a
							# survival case.  Leave the field non-empty for the
							# shared push below, which expects a clean return.
							push @cases, { _input => {%case_input}, _STATUS => 'DIES', _LINE => __LINE__ };
							$case_input{$field} = $non_empty;
						}
					}
				}
			} elsif ($type eq 'integer') {
				$case_input{$field} = _random_number_for_spec($spec, 1);
				if(!defined($spec->{min}) && !defined($spec->{max})) {
					# Only claim a float when the fraction survives floating point:
					# rand_int() can return values large enough for +0.2 to be lost,
					# which would demand that an integral value be rejected.
					my $float_input = $case_input{$field} + 0.2;
					# These are cases for a single named parameter of a hash-style
					# API, so they must carry the field name.  Passing the value as
					# _input would call a multi-parameter routine with one bare
					# positional argument, which tests the argument count instead
					# of the parameter's type.
					push @cases,
						# If it's takes an integer, a float should die
						(($float_input == int($float_input)) || !_spec_type_is_enforced($spec)) ? () : ({ %case_input, ($field => $float_input), _STATUS => 'DIES', _LINE => __LINE__ }),
						# Integers passed as a string
						{ %case_input, ($field => "007"), _STATUS => 'OK', _LINE => __LINE__ },
						# Not integer literals to Perl's number parser, so they must be
						# rejected; they were previously expected to survive, which no
						# validator that uses looks_like_number (Params::Validate::Strict
						# included) can satisfy
						!_spec_type_is_enforced($spec) ? () : (
							{ %case_input, ($field => "0x10"), _STATUS => 'DIES', _LINE => __LINE__ },
							{ %case_input, ($field => "1_000"), _STATUS => 'DIES', _LINE => __LINE__ },
						);
				}
			} elsif ($type eq 'boolean') {
				$case_input{$field} = rand_bool();
			} elsif ($type eq 'number') {
				$case_input{$field} = _random_number_for_spec($spec, 0);
			} elsif ($type eq 'arrayref') {

				if(my $element_type = $input{element_type}) {
					if($element_type eq 'integer') {
						push @cases,
							{ %mandatory_args, ($field => '0.3', _STATUS => 'DIES', _LINE => __LINE__, _DESCRIPTION => 'float in list of integers') },
							{ %mandatory_args, ($field => 'string in array of ints', _STATUS => 'DIES', _LINE => __LINE__, _DESCRIPTION => 'string in list of integers') };
					} elsif($element_type eq 'boolean') {
						push @cases,
							{ %mandatory_args, ($field => 2, _STATUS => 'DIES', _LINE => __LINE__, _DESCRIPTION => '2 list of booleans') },
							{ %mandatory_args, ($field => '0.3', _STATUS => 'DIES', _LINE => __LINE__, _DESCRIPTION => 'float in list of booleans') },
							{ %mandatory_args, ($field => 'string in array of bools', _STATUS => 'DIES', _LINE => __LINE__, _DESCRIPTION => 'string in list of booleans') };
					}
				}

				push @cases, { %mandatory_args, (field => [ 'fred', undef, 'wilma' ], _LINE => __LINE__, _DESCRIPTION => 'undef element in array') } if($config{test_undef});
				$case_input{$field} = _random_array_for_spec($spec);
			} elsif ($type eq 'hashref') {
				if($config{test_undef}) {
					push @cases, { %mandatory_args, (field => { 'fred' => 'wilma', 'undef' => undef, 'foo' => 'bar' }, _LINE => __LINE__, _DESCRIPTION => 'undef element in hashref') };
					push @cases, { %mandatory_args, (field => { 'fred' => 'wilma', 'nested' => { 'first' => 'one', 'undef' => undef, 'third' => 'three' }, 'foo' => 'bar' }, _LINE => __LINE__, _DESCRIPTION => 'undef element in nested hashref') };
				}
				$case_input{$field} = _random_hash_for_spec($spec);
			} elsif($config{'test_undef'}) {
				$case_input{$field} = undef;
			}

			# 4) occasionally drop optional fields
			if ($spec->{optional} && rand() < 0.25) {
				delete $case_input{$field};
			}
			push @cases, { _input => \%case_input, status => 'OK' } if(keys %case_input);

			# A member list is handled where the field's valid values are
			# generated (see fuzz_inputs()); every other type gets its
			# edge cases from the shared dispatcher.
			push @cases, @{_generate_type_cases($field, $type, $spec, \%mandatory_args)};

			# Add notmemberof tests
			if (defined $spec->{notmemberof}) {
				my @blacklist = @{$spec->{notmemberof}};
				# Each blacklisted value should die
				foreach my $val (@blacklist) {
					push @cases, { %mandatory_args, ( $field => $val, _STATUS => 'DIES' ) };
				}
				# Non-blacklisted value should pass
				push @cases, { %mandatory_args, ( $field => '_not_in_blacklist_' ) };
			}

			# semantic tests
			if(defined(my $semantic = $spec->{'semantic'})) {
				if($semantic eq 'unix_timestamp') {
					push @cases, { %mandatory_args, ( -1, _STATUS => 'DIES' ) },
						{ %mandatory_args, ( 0 ) },
						{ %mandatory_args, ( 1 ) },
						{ %mandatory_args, ( time ) },
						{ %mandatory_args, ( 2147483647 ) },
						{ %mandatory_args, ( 45.67, _STATUS => 'DIES', _DESCRIPTION => 'UNIX timestamp should not be a float' ) },
						{ %mandatory_args, ( 2147483648, _STATUS => 'DIES' ) };
				} else {
					diag("semantic type $semantic is not yet supported");
				}
			}
			if(@relationships) {
				diag('Run relationship tests') if($ENV{'TEST_VERBOSE'});

				foreach my $rel (@relationships) {
					my $type = $rel->{type};

					if($type eq 'mutually_exclusive') {
						my ($p1, $p2) = @{ $rel->{params} };
						# Both specified — should die
						run_test(
							{ _STATUS => 'DIES',
							  _DESCRIPTION => "mutually exclusive: $p1 and $p2 both given" },
							{ %mandatory_args, $p1 => 'val1', $p2 => 'val2' },
							\%output,
							$positions
						);
						# Each alone — should live
						run_test(
							{ _DESCRIPTION => "mutually exclusive: only $p1 given" },
							{ %mandatory_args, $p1 => 'val1' },
							\%output,
							$positions
						);
						run_test(
							{ _DESCRIPTION => "mutually exclusive: only $p2 given" },
							{ %mandatory_args, $p2 => 'val2' },
							\%output,
							$positions
						);

					} elsif($type eq 'required_group') {
						my @params = @{ $rel->{params} };
						# None specified — should die
						my %none = map { $_ => undef } @params;
						run_test(
							{ _STATUS => 'DIES',
							  _DESCRIPTION => 'required_group: none of (' . join(', ', @params) . ') given' },
							{ %mandatory_args, %none },
							\%output,
							$positions
						);
						# Each alone — should live
						foreach my $p (@params) {
							run_test(
								{ _DESCRIPTION => "required_group: only $p given" },
								{ %mandatory_args, $p => 'val' },
								\%output,
								$positions
							);
						}

					} elsif($type eq 'conditional_requirement') {
						my ($if_param, $then_param) = ($rel->{if}, $rel->{then_required});
						# if_param set, then_param missing — should die
						run_test(
							{ _STATUS => 'DIES',
							  _DESCRIPTION => "conditional: $if_param set but $then_param missing" },
							{ %mandatory_args, $if_param => 'val', $then_param => undef },
							\%output,
							$positions
						);
						# Both set — should live
						run_test(
							{ _DESCRIPTION => "conditional: $if_param and $then_param both set" },
							{ %mandatory_args, $if_param => 'val', $then_param => 'val' },
							\%output,
							$positions
						);
						# if_param absent — then_param absence should not matter
						run_test(
							{ _DESCRIPTION => "conditional: $if_param absent so $then_param not required" },
							{ %mandatory_args, $then_param => undef },
							\%output,
							$positions
						);

					} elsif($type eq 'dependency') {
						my ($param, $requires) = ($rel->{param}, $rel->{requires});
						# param set, requires missing — should die
						run_test(
							{ _STATUS => 'DIES',
							  _DESCRIPTION => "dependency: $param set but $requires missing" },
							{ %mandatory_args, $param => 'val', $requires => undef },
							\%output,
							$positions
						);
						# Both set — should live
						run_test(
							{ _DESCRIPTION => "dependency: $param and $requires both set" },
							{ %mandatory_args, $param => 'val', $requires => 'val' },
							\%output,
							$positions
						);

					} elsif($type eq 'value_constraint') {
						my ($if_param, $then_param, $op, $val) =
							($rel->{if}, $rel->{then}, $rel->{operator}, $rel->{value});
						# if_param set, then_param wrong value — should die
						my $wrong_val = ($op eq '==') ? $val + 1 : $val - 1;
						run_test(
							{ _STATUS => 'DIES',
							  _DESCRIPTION => "value_constraint: $if_param set, $then_param = $wrong_val (wrong)" },
							{ %mandatory_args, $if_param => 'val', $then_param => $wrong_val },
							\%output,
							$positions
						);
						# if_param set, then_param correct value — should live
						run_test(
							{ _DESCRIPTION => "value_constraint: $if_param set, $then_param = $val (correct)" },
							{ %mandatory_args, $if_param => 'val', $then_param => $val },
							\%output,
							$positions
						);

					} elsif($type eq 'value_conditional') {
						my ($if_param, $equals, $then_param) =
							($rel->{if}, $rel->{equals}, $rel->{then_required});
						# if_param equals trigger value, then_param missing — should die
						run_test(
							{ _STATUS => 'DIES',
							  _DESCRIPTION => "value_conditional: $if_param='$equals', $then_param missing" },
							{ %mandatory_args, $if_param => $equals, $then_param => undef },
							\%output,
							$positions
						);
						# if_param equals trigger value, then_param present — should live
						run_test(
							{ _DESCRIPTION => "value_conditional: $if_param='$equals', $then_param present" },
							{ %mandatory_args, $if_param => $equals, $then_param => 'val' },
							\%output,
							$positions
						);
						# if_param different value — then_param absence should not matter
						run_test(
							{ _DESCRIPTION => "value_conditional: $if_param != '$equals', $then_param not required" },
							{ %mandatory_args, $if_param => '__other__', $then_param => undef },
							\%output,
							$positions
						);
					}
				}
			}
		}
	}

	# The loop above skips member lists.  fuzz_inputs() adds their cases
	# only when every argument is optional or there are several, so a
	# routine whose one argument is mandatory got none; dedup drops the
	# copies the other paths make.
	foreach my $field (keys %input) {
		my $spec = $input{$field};
		push @cases, _memberof_cases($field, $spec, \%mandatory_args) if(_has_memberof($spec));
	}

	return \@cases;
}

sub populate_positions
{
	my $input = shift;

	my $rc;
	foreach my $arg (keys %{$input}) {
		my $spec = $input->{$arg} || {};
		if(((ref($spec)) eq 'HASH') && defined($spec->{'position'})) {
			$rc->{$arg} = $spec->{'position'};
		}
	}

	return unless $rc;	# A named API has no positions

	# A parameter after the positional arguments is a named option, and has
	# to say so (named: 1): anything else is a forgotten position, which the
	# named call would silently turn into a key whose value is a string.
	foreach my $arg (keys %{$input}) {
		my $spec = $input->{$arg} || {};
		next if((ref($spec)) eq 'HASH') && (defined($spec->{'position'}) || $spec->{'named'});
		::diag("$arg is missing a position parameter in its schema (or named: 1)");
		return;
	}

	return $rc;
}

# The harness passes named arguments as a list, which is the shape the POD's
# EXAMPLE sections document: a constructor written as `my ($class, %args) =
# @_` receives a single hashref as one odd argument and reports every
# parameter as missing.  The keys the harness uses to drive a case are not
# parameters and are removed here.
sub _fuzz_args
{
	my ($input) = @_;

	return $input unless(ref($input) eq 'HASH');

	my %args = %{$input};
	delete @args{qw(_STATUS _NAME _LINE _PROPERTIES _DESCRIPTION _DOCUMENTED_CONSTRAINTS)};

	return %args;
}

sub run_test
{
	my($case, $input, $output, $positions) = @_;

	if($ENV{'TEST_VERBOSE'}) {
		require Data::Dumper;
		diag('input: ', Data::Dumper::Dumper($input));
	}

	$_current_input = (ref($input) eq 'HASH') ? { %{$input} } : $input;

	my $name = delete local $case->{'_NAME'};
	my $properties = delete local $case->{_PROPERTIES};
	my $description = delete local $case->{_DESCRIPTION};
	$documented_constraint_probe = delete local $case->{'_DOCUMENTED_CONSTRAINTS'} ? 1 : 0;
	my $result;
	my $mess;
	my @alist = ();
	my $named_options = 0;

	# Snapshots for the documented-bound check must be taken before the
	# argument list below deletes values from $input.
	$documented_tolerated = 0;
	($_documented_inside, $_documented_outside) = _documented_constraint_findings($input, \%input);
	if(defined($input) && !ref($input)) {
		# $mess is later used as a sprintf() format string further
		# below — a literal '%' in $name/$input must be escaped to
		# '%%' first, the same as the aggregate branch does for
		# $args, or a value like '%s' / '%n' corrupts the sprintf call.
		(my $safe_input = $input) =~ s/%/%%/g;
		if($name) {
			(my $safe_name = $name) =~ s/%/%%/g;
			$mess = "[% function %]($safe_name = '$safe_input') %s";
		} else {
			$mess = "[% function %]('$safe_input') %s";
		}
		# A scalar _input case is the only argument of a single-parameter
		# routine, so it has to be passed as that argument. Without this the
		# call below dropped @alist and invoked the routine with no arguments,
		# so the case tested nothing while still being reported by name.
		$alist[0] = $input if($positions && (scalar(keys %{$positions}) == 1));
	} elsif(defined($input)) {
		if($positions) {
			# Positional args, then the named options that follow them
			# (`sub f { my ($x, %opts) = @_ }` is called f($x, key => value))
			my @named;
			foreach my $key (keys %{$input}) {
				if(($key ne '_STATUS') && ($key ne '_NAME') && ($key ne '_LINE') && ($key ne '_PROPERTIES') && ($key ne '_DESCRIPTION')) {
					if(exists($positions->{$key})) {
						$alist[$positions->{$key}] = delete $input->{$key};
					} elsif(ref($input{$key}) eq 'HASH' && $input{$key}{'named'}) {
						push @named, $key => delete $input->{$key};
					} else {
						diag("Lost position number for $key");
					}
				}
			}
			# Keep all slots up to the last defined position, preserving undef
			# holes for optional args that were intentionally omitted at lower
			# positions.  Stripping ALL undefs (the old grep approach) caused
			# a mandatory arg at position N to shift to position N-1 when an
			# optional arg at an earlier position was absent — the shifted arg
			# was then passed to the wrong parameter and the call died.
			my $last_def = -1;
			for my $i (0..$#alist) { $last_def = $i if defined $alist[$i] }
			@alist = $last_def >= 0 ? @alist[0..$last_def] : ();
			push @alist, @named if @named;
			$named_options = scalar(@named) ? 1 : 0;
			$input = join(', ', @alist);
		} else {
			# Named args
			if(ref($input) ne 'HASH') {
				if($case->{'_STATUS'} ne 'DIES') {
					die('Input is missing list of arguments (perhaps you only listed types)');
				}
				# e.g., we are passing a ref to a scalar to something that only takes a scalar, so it should cause the routine to die
				$positions = {};
				$alist[0] = $input;
			} else {
				foreach my $key (sort keys %{$input}) {
					if(($key ne '_STATUS') && ($key ne '_NAME') && ($key ne '_LINE') && ($key ne '_PROPERTIES')) {
						if(defined($input->{$key})) {
							push @alist, "'$key' => '$input->{$key}'";
						} else {
							push @alist, "'$key' => undef";
						}
					}
				}
			}
		}
		my $args = join(', ', @alist);
		$args =~ s/%/%%/g;
		$mess = "[% function %]($args) %s";
	} else {
		$mess = "[% function %] %s";
	}

	my $status = delete $case->{'_STATUS'} || $output->{'_STATUS'};
	# A routine whose contract reports invalid input by returning undef is
	# not also required to croak: a generated case that expects a death
	# accepts that documented signal instead.
	my $undef_error = (ref($output) eq 'HASH')
		&& ((($output->{'_error_return'} // '') eq 'undef')
			|| (ref($output->{'_error_handling'}) eq 'HASH'
				&& $output->{'_error_handling'}{'undef_on_error'}));
	my $line = delete $case->{'_LINE'};
	my %ENV_before = %ENV;
	my $cwd_before = Cwd::getcwd();
	my $globals_before = _volatile_globals();
	my %cwd_files_before = map { $_ => 1 } do { opendir(my $dh, '.') or die $!; readdir($dh) };
	my $fds_before = _open_fds();

	local $SIG{ALRM} = sub { die '__TIMEOUT__' };
	if((!defined($config{timeout})) || ($config{timeout} > 0)) {
		alarm($config{'timeout'} // 10);
	}
	my $old_warn = $SIG{__WARN__};
	my $old_die = $SIG{__DIE__};
	my $ok = eval {
		if(defined($status)) {
			if($status eq 'DIES') {
				my $err;
				if($positions) {
					[% IF position_code %]
						if(defined($name)) {
							$err = _dies_with_context { [% position_code %] } sprintf($mess, "dies (position test) - $name (status = DIES)"), $undef_error;
						} else {
							$err = _dies_with_context { [% position_code %] } sprintf($mess, 'dies (position test, status = DIES)'), $undef_error;
						}
					[% ELSE %]
						ok(0, 'dies: position_code not defined');
					[% END %]
				} else {
					$err = _dies_with_context { [% call_code %] } sprintf($mess, 'dies'), $undef_error;
					ok(!defined($result));
				}
				if(!defined($err) && $undef_error) {
					pass(sprintf($mess, 'reports invalid input as undef (status = DIES)'));
					return;
				}
				ok(defined($err));
				ok(length($err));
				# autodie and exception classes die with a blessed object that
				# stringifies to its message; a bare reference is the only error
				# that carries nothing to report.
				ok(!ref($err) || Scalar::Util::blessed($err));
				if(defined($name)) {
					unlike($err, qr/unitialized/, "$name doesn't involve an uninitialized variable");
				} else {
					unlike($err, qr/unitialized/, "Test doesn't involve an uninitialized variable");
				}
				return;	# There should be no output to validate
			} elsif($status eq 'WARNS') {
				warnings_exist { [% call_code %] } qr/./, sprintf($mess, 'warns');
			} else {
				carp 'unhandled properties in test case; continuing' if(scalar keys %{$properties});
				if($positions) {
					[% IF position_code %]
						if(defined($name)) {
							_documented_lives_ok { [% position_code %] } sprintf($mess, "survives (position test) - $name (status = LIVES)");
						} else {
							_documented_lives_ok { [% position_code %] } sprintf($mess, 'survives (position test, status = LIVES)');
						}
					[% ELSE %]
						ok(0, 'position_code not defined');
					[% END %]
				} elsif(defined($description)) {
					_documented_lives_ok { [% call_code %] } sprintf($mess, "survives ($description; status = LIVES)");
				} elsif(defined($line)) {
					_documented_lives_ok { [% call_code %] } sprintf($mess, "survives (line = $line; status = LIVES)");
				} else {
					_documented_lives_ok { [% call_code %] } sprintf($mess, 'survives (status = LIVES)');
				}
				if(!$documented_tolerated && $properties->{idempotent}) {
					[% determinism_code %]
				}
			}
		} elsif($positions) {
			if(defined($name)) {
				_documented_lives_ok { [% position_code %] } sprintf($mess, "survives (position test) - $name");
				if(!$documented_tolerated && $properties->{idempotent} && (scalar(@alist) == 1)) {
					[% UNLESS module %]
						ok([% function %]($alist[0]) eq [% function %]([% function %]($alist[0])), 'function is idempotent');
						ok([% function %]($alist[0]) eq [% function %]($alist[0]), 'function is idempotent');
					[% END %]
				}
			} else {
				carp 'unhandled properties in test case; continuing' if(scalar keys %{$properties});
				_documented_lives_ok { [% position_code %] } sprintf($mess, 'survives (position test)');

				# An extra argument should be ignored, except for getsetters, so only test if there's more than one arg.
				# A named option hash is not positional: a stray bare value
				# would become a hash key with an undef value instead.
				if(scalar(@alist) > 1 && !$named_options) {
					push(@alist, 'foo');
					_documented_lives_ok { [% position_code %] } sprintf($mess, 'survives (position test, with extra argument)');
				}
			}
			if(!$documented_tolerated && $properties->{idempotent}) {
				[% determinism_code %]
			}
		} else {
			# Status not given, assume set to LIVES
			carp 'unhandled properties in test case; continuing' if(scalar keys %{$properties});
			if(defined($description)) {
				_documented_lives_ok { [% call_code %] } sprintf($mess, "survives ($description)");
			} elsif(defined($line)) {
				_documented_lives_ok { [% call_code %] } sprintf($mess, "survives (line = $line)");
			} else {
				_documented_lives_ok { [% call_code %] } sprintf($mess, 'survives');
			}
			if(!$documented_tolerated && $properties->{idempotent}) {
				[% determinism_code %]
			}
		}
		1;
	};

	alarm 0;

	# Clean up any files the function created in cwd, keeping the list so the
	# test can report them.  They are removed either way, so a routine that
	# writes the file it was asked to write cannot break the cases after it.
	my @leftovers = grep { !$cwd_files_before{$_} && -f $_ } do { opendir(my $dh, '.') or die $!; readdir($dh) };
	unlink @leftovers;

	# Check the test did not timeout
	diag($@) if($@);
	ok((!defined($@)) || (length($@) == 0));

	# Destructive testing: the call must not leave the caller's globals
	# changed.  These are the ones a routine can clobber without any error
	# showing up: $_ left behind by a while() loop, $/ from slurping a file,
	# and $, and $; from an assignment that should have been local.  A
	# routine that does this silently changes every later call in the test
	# file, so the call is not safe to repeat.
	is(_globals_changed($globals_before), '', 'caller globals unmodified');

	# Global side effect detection
	is(Cwd::getcwd(), $cwd_before, 'cwd not modified');
	is_deeply(_filtered_env(\%ENV), _filtered_env(\%ENV_before), 'ENV not modified');
	is($SIG{__WARN__}, $old_warn, 'warn handler is not changed');
	is($SIG{__DIE__}, $old_die, 'die handler is not changed');

	# Destructive testing: what the routine leaves behind.  A routine whose job
	# is to write a file has to fail here, so a schema can set 'check_files: 0'
	# (or 'check_fds: 0' for one that hands a filehandle back to its caller).
	if($config{'check_files'} // 1) {
		is_deeply(\@leftovers, [], 'no files left in cwd');
	}
	my $fds_after = _open_fds();
	if(defined($fds_before) && defined($fds_after) && ($config{'check_fds'} // 1)) {
		is(join(', ', _leaked_fds($fds_before, $fds_after)), '', 'no file descriptors leaked');
	}

	delete local $output->{'_STATUS'};

	# A 'void' output type means the routine returns nothing, so there is no
	# value to validate (and no type claim to check it against).
	if(!$documented_tolerated && scalar keys %{$output} && defined($output->{type}) && $output->{type} ne 'void') {
		if($ENV{'TEST_VERBOSE'}) {
			require Data::Dumper;
			diag('result: ', Data::Dumper::Dumper($result));
		}
		if(($output->{type} // '') eq 'boolean') {
			# Perl has no boolean type: a routine documented to return a
			# boolean may return 1 or '' (defined() returns ''), and the
			# contract is truthiness.  What it must not return is a
			# reference, which is what a strict 0/1 check was rejecting.
			ok(!ref($result), 'output is a boolean');
		} else {
			returns_ok($result, $output, 'output validates');
		}
		if(((!defined($status)) || ($status eq 'OK')) && defined($result)) {
			is(
				Unicode::Normalize::NFC($result),
				Unicode::Normalize::NFC(Unicode::Normalize::NFD($result)),
				'Unicode normalization stable'
			);
		}
	}
}

# What this process's file descriptors point at, as a map of target to the
# number of descriptors open on it, or undef where the platform offers no way
# to ask.  A routine that opens files and never closes them costs every later
# call in the same test file a descriptor, which eventually fails an unrelated
# case.
sub _open_fds
{
	return unless -d '/proc/self/fd';
	opendir(my $dh, '/proc/self/fd') or return;
	my %targets;
	foreach my $fd (readdir($dh)) {
		next if($fd =~ /^\./);
		my $target = readlink("/proc/self/fd/$fd") // 'unknown';
		# socket:[12345] and pipe:[12345] differ on every open
		$target =~ s/:\[\d+\]$//;
		$targets{$target}++;
	}
	closedir($dh);

	return \%targets;
}

# The targets that gained descriptors between two _open_fds() snapshots.
# The first descriptor ever opened on a target is not a leak: an object that
# opens its log file or its connection on first use and keeps it is holding a
# resource, not losing one.  A leak opens the same thing again, so a target
# that gains a descriptor a second time is reported, as is anything beyond a
# handful of distinct targets (a new temporary file leaked on every call).
sub _leaked_fds
{
	my ($before, $after) = @_;

	my @leaked;
	foreach my $target (sort keys %{$after}) {
		my $was = $before->{$target} // 0;
		next if($after->{$target} <= $was);
		if(($was == 0) && ($after->{$target} == 1) && !$fds_held{$target} && (scalar(keys %fds_held) < 8)) {
			$fds_held{$target} = 1;
			diag("descriptor on $target opened and kept; taken as held, not leaked") if($ENV{'TEST_VERBOSE'});
			next;
		}
		push @leaked, $target;
	}

	return @leaked;
}

# Snapshot of the globals a routine can clobber without returning anything
# obviously wrong.  Values are stringified so a change is visible even when
# the replacement looks interchangeable; undef is kept distinct from ''.
sub _volatile_globals
{
	my %state;
	$state{'$_'} = defined($_) ? "$_" : undef;
	$state{'$/'} = defined($/) ? "$/" : undef;
	$state{'$,'} = defined($,) ? "$," : undef;
	$state{'$;'} = defined($;) ? "$;" : undef;
	$state{'@ARGV'} = join("\x1f", @ARGV);

	return \%state;
}

# Returns a comma-separated list of the globals whose value changed.
sub _globals_changed
{
	my ($before) = @_;

	my $after = _volatile_globals();
	my @changed = sort grep {
		my ($was, $is) = ($before->{$_}, $after->{$_});
		defined($was) != defined($is) || (defined($was) && $was ne $is)
	} keys %{$before};

	return join(', ', @changed);
}

# On Windows $PWD etc are not stable
sub _filtered_env
{
	my %env = %{ shift() };

	# An environment variable set to undef is unset: perl removes it from
	# %ENV, so it must not look like a change from a variable that was
	# never there.
	delete @env{ grep { !defined($env{$_}) } keys %env };

	if($^O eq 'MSWin32') {
		delete @env{
			qw(
				PWD
				OLDPWD
				_
				SHLVL
			)
		};
	}

	return \%env;
}

