# Generator for the R expectations frozen in t/frame_reshape.R.pandas.t
# (rbind/concat and t()/transpose).  Re-run with
#     Rscript --vanilla t/frame_reshape.R.pandas.R > /tmp/R.cases
# and paste the output over the block between "BEGIN R cases" and
# "END R cases" in the .t.  R 4.6.2 produced the committed block (R 4.6.1 source
