options(digits = 17)
pl <- function(x) {
  if (is.null(x)) return("undef")
  if (is.list(x)) {
    if (is.null(names(x))) return(paste0("[", paste(vapply(x, pl, ""), collapse = ", "), "]"))
    return(paste0("{", paste(sprintf("'%s' => %s", names(x), vapply(x, pl, "")), collapse = ", "), "}"))
  }
  if (length(x) != 1L) return(paste0("[", paste(vapply(as.list(x), pl, ""), collapse = ", "), "]"))
  if (is.na(x)) return("undef")
  if (is.character(x) || is.factor(x)) return(paste0("'", gsub("'", "\\\\'", as.character(x)), "'"))
  if (is.numeric(x) && x == round(x) && abs(x) < 1e15) return(format(x, scientific = FALSE))
  format(x, digits = 17)
}
hoa <- function(d) lapply(as.list(d), function(c) as.list(if (is.factor(c)) as.character(c) else c))
hoh <- function(d) { r <- lapply(seq_len(nrow(d)), function(i) lapply(as.list(d[i, , drop = FALSE]), function(v) if (is.factor(v)) as.character(v) else v)); names(r) <- rownames(d); r }
aoa <- function(m) lapply(seq_len(nrow(m)), function(i) as.list(unname(m[i, ])))
emit <- function(name, src, shape, inp, exp, extra = "")
  cat(sprintf("\t{ name => %s, src => %s, shape => '%s',\n\t  in => %s,\n\t  exp => %s%s },\n",
              pl(name), pl(src), shape, pl(inp), pl(exp), extra))

