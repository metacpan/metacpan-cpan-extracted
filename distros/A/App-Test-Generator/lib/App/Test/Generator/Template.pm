sub _random_bytes_for_spec
{
	my ($spec) = @_;

	my $len = $spec->{min} // $spec->{max};
	return rand_bytes($len) if defined($len);
	return rand_bytes();
}

# Choose a random number inside the declared bounds.  A max-only spec is
# reached from the fixed max boundary, never from an unbounded random value,
# so a routine that enforces the maximum is not sent a value above it.
sub _random_number_for_spec
{
	my ($spec, $integer) = @_;

	my $min = $spec->{min};
	# Generated data stops at sample_max: the documented maximum is the bound
	# a value is checked against, not necessarily a value this run can afford
	# to compute (a count of hashing rounds, say).
	my $max = $spec->{sample_max} // $spec->{max};

	if(defined($min) && defined($max)) {
		return $integer
			? $min + int(rand($max - $min + 1))
			: $min + rand($max - $min);
	}
	if(defined($max)) {
		return $integer ? $max - int(abs(rand_int())) : $max - abs(rand_num());
	}
	if(defined($min)) {
		return $integer ? $min + int(abs(rand_int())) : $min + abs(rand_num());
	}
	return $integer ? rand_int() : rand_num();
}

# Generate one random value that satisfies a (possibly nested) schema.
# `schema` describes the elements of an arrayref, the values of a hashref,
# or (when it maps names to schemas instead of declaring a type) the fixed
# keys of a hashref.  Element schemas may be any type, including another
# arrayref or hashref, and objects built from `isa` or `can`.
sub _random_value_for_spec
{
	my ($spec) = @_;

	$spec = { type => $spec } if(defined($spec) && !ref($spec));
	$spec = {} unless ref($spec) eq 'HASH';
	my $type = $spec->{type} // 'string';

	if($type eq 'string') {
		if(defined(my $re = $spec->{matches})) {
			$re = qr/$re/ if(ref($re) ne 'Regexp');
			my $str = _random_string_matching($re, _length_bounds($spec));
			return $str if defined($str);
		}
		# A documented list of values is the domain: any member is valid, and
		# a generated string outside it is not.
		if(_has_memberof($spec)) {
			return _pick_from($spec->{memberof});
		}
		return _random_string_for_spec($spec, 'test_value');
	}
	return _random_number_for_spec($spec, 1) if($type eq 'integer');
	return _random_number_for_spec($spec, 0) if(($type eq 'number') || ($type eq 'float'));
	return int(rand(2)) if($type eq 'boolean');
	return sub { } if($type eq 'coderef');
	return rand_ascii_str(8) if($type eq 'any');
	return _random_object_for_spec($spec) if($type eq 'object');
	return _random_array_for_spec($spec) if(($type eq 'arrayref') || ($type eq 'array'));
	return _random_hash_for_spec($spec) if($type eq 'hashref');

	carp("unhandled element type '$type'; using undef");
	return undef;
}

sub _random_array_for_spec
{
	my ($spec, $len) = @_;

	$spec = {} unless ref($spec) eq 'HASH';
	$len = $spec->{min} unless defined($len);
	$len = 1 unless defined($len);
	$len = int($len);
	$len = 0 if($len < 0);

	# A constructor that refuses an empty list of live objects documents a
	# minimum of one, and the stand-in is the only element it accepts.
	my $stub = $spec->{_stub_elements};
	if(ref($stub) eq 'HASH') {
		# An empty list is a real value here: it is the below-minimum case a
		# routine that demands a non-empty list must reject.  Only the
		# elements are fixed, not the count.
		return [] if($len == 0);
		return [ map { _build_stub_object($stub) } 1 .. $len ];
	}

	my $element = $spec->{schema};
	# A schema that maps key names to element schemas describes a hash whose
	# keys are fixed; _random_hash_for_spec() is the builder for that shape.
	if((ref($element) eq 'HASH') && !exists($element->{type})) {
		return [ map { _random_hash_for_spec({ schema => $element }) } 1 .. $len ];
	}
	return [ map { _random_value_for_spec($element) } 1 .. $len ];
}

sub _random_hash_for_spec
{
	my ($spec, $len) = @_;

	$spec = {} unless ref($spec) eq 'HASH';
	my $schema = $spec->{schema};

	# A schema without a type maps key names to element schemas, so the hash
	# has exactly those keys.  A scalar type is shorthand for { type => ... }.
	if((ref($schema) eq 'HASH') && !exists($schema->{type})) {
		my %fixed;
		foreach my $key (sort keys %{$schema}) {
			my $value = $schema->{$key};
			$value = { type => $value } if(defined($value) && !ref($value));
			next unless ref($value) eq 'HASH';
			$fixed{$key} = _random_value_for_spec($value);
		}
		return \%fixed;
	}

	$len = $spec->{min} unless defined($len);
	$len = 1 unless defined($len);
	$len = int($len);
	$len = 0 if($len < 0);

	my %hash;
	$hash{"key$_"} = _random_value_for_spec($schema) for 1 .. $len;
	return \%hash;
}

# Build a value for an object element schema.  `isa` uses a no-argument
# constructor; `can` falls back to a Class::Simple mock with that method, the
# same way a top-level object parameter is mocked.
sub _random_object_for_spec
{
	my ($spec) = @_;

	my $class = $spec->{isa};
	if(defined($class) && !ref($class)) {
		# The class may already be loaded by the module under test.
		eval { require $class; 1 } unless $class->can('new');
		my $object = eval { $class->new };
		return $object if(defined($object) && ref($object) && eval { $object->isa($class) });
	}

	my $method = $spec->{can};
	if(defined($method)) {
		eval { require Class::Simple; 1 }
			or carp("cannot build object element: Class::Simple is not available");
		my $object = eval { Class::Simple->new };
		return $object if(defined($object) && $object->can($method));
	}

	carp('cannot build object element: give a class with a no-argument constructor as isa, or a method name as can');
	return undef;
}

# A stable text key for a stub description, so one package serves every
# identical description.  No serialisation module is needed: a harness for a
# plain function should not carry a dependency it never uses.
sub _stub_key
{
	my ($value) = @_;

	return 'undef' unless defined($value);
	return 'a[' . join(',', map { _stub_key($_) } @{$value}) . ']' if ref($value) eq 'ARRAY';
	return 'h{' . join(',', map { $_ . '=' . _stub_key($value->{$_}) } sort keys %{$value}) . '}' if ref($value) eq 'HASH';
	return "$value";
}

# Build a stand-in for an object a constructor calls methods on.  The schema
# names the base class (from the constructor's POD) and the canned result of
# each method, so the stand-in passes the constructor's isa/blessed checks
# and answers the calls it makes.  One package is defined per distinct
# description; every call returns a fresh instance.
my %_stub_packages;
sub _build_stub_object
{
	my ($spec) = @_;

	my $isa     = $spec->{isa};
	my $methods = $spec->{methods} // {};

	eval "require $isa; 1" or die "cannot stub $isa: $@";

	my $key = _stub_key([ $isa, [ map { [ $_, $methods->{$_} ] } sort keys %{$methods} ] ]);

	my $pkg = $_stub_packages{$key};
	if(!defined($pkg)) {
		$pkg = 'App::Test::Generator::Stub::' . scalar(keys %_stub_packages);
		no strict 'refs';
		@{"${pkg}::ISA"} = ($isa);
		for my $name (keys %{$methods}) {
			my $canned = $methods->{$name};
			*{"${pkg}::$name"} = sub {
				my $value = $canned;
				return ref($value) eq 'ARRAY' ? [ @{$value} ]
					: ref($value) eq 'HASH' ? { %{$value} } : $value;
			};
		}
		$_stub_packages{$key} = $pkg;
	}

	return bless({}, $pkg);
}

