=head1 NAME

App::UpdateConfig - Deploy configuration fragments (dotfiles, etc.) locally or
on remote hosts.

=head1 DESCRIPTION

This module is empty. It only exists so that the distribution can be installed
by name from CPAN. All the functionality is provided by the L<update_config>
program, whose documentation describes its usage.

