package DBIx::QuickORM::Manual::BulkInsert;
use strict;
use warnings;

our $VERSION = '0.000031';

=pod

=encoding UTF-8

=head1 NAME

DBIx::QuickORM::Manual::BulkInsert - Insert many rows at once with insert_many, by example.

=head1 DESCRIPTION

C<insert_many> inserts an arrayref of rows in as few statements as the
database allows, all or nothing. C<insert_many_fk> does the same for rows
linked to one row (L<DBIx::QuickORM::Manual::ForeignKeys/INSERTING LINKED ROWS>).

=head1 SCHEMA

The examples use PostgreSQL and this schema:

=for highlighter language=sql

    CREATE TABLE users (
        id          SERIAL PRIMARY KEY,
        name        TEXT NOT NULL,
        email       TEXT UNIQUE,
        prefs       JSON,
        referred_by INTEGER REFERENCES users (id),
        created     TIMESTAMP NOT NULL DEFAULT now()
    );

    CREATE TABLE posts (
        id      SERIAL PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users (id),
        title   TEXT NOT NULL,
        views   INTEGER NOT NULL DEFAULT 0
    );

=head1 INSERTING MANY ROWS

=for highlighter language=perl

    my $users = $orm->insert_many(users => [{name => 'Ann'}, {name => 'Bob'}]);    # an arrayref of rows
    my $id    = $users->[0]->field('id');                                          # whole rows, canonical

    # the same, on a table handle
    my $more = $orm->handle('users')->insert_many([{name => 'Cy'}, {name => 'Di'}]);

    my $data = $orm->insert_many(
        users => [{name => 'Gus'}],
        data  => 1,    # hashrefs instead of row objects
    );

Called in void context it only inserts. It builds no rows, returns nothing,
and sends no C<RETURNING>, so it works on every database, even for rows
without their whole primary key:

    $orm->insert_many(users => [{name => 'Hal'}, {name => 'Ida'}]);    # void: inserts only

Otherwise C<insert_many> returns an arrayref of the new rows, never a list.
Through C<RETURNING> they hold the table's default fields (every field,
unless C<omit> or C<default_fields> narrows them), keys and defaults
included.

Every row must have the same field names. Values are deflated as C<insert>
deflates them (L<DBIx::QuickORM::Manual::Values>), and a typed primary key a
row leaves out is generated as C<insert> generates it
(L<DBIx::QuickORM::Manual::Keys>).

=head1 JUST THE COUNT

    my $count = $orm->insert_many(
        users => [{name => 'Eve'}, {name => 'Fay'}],
        count => 1,
    );    # 2

C<< count => 1 >> returns how many rows went in. It works on every database.

With C<count>, and in void context, the new rows are not read back, so the
ORM holds no copy of them (L<DBIx::QuickORM::Manual::Caching>).

=head1 ALL OR NOTHING

    # more binds than one statement may hold: two statements
    my @many = map {
        {
            name  => "User $_",
            email => "user$_\@example.com",
        }
    } 1 .. 40_000;

    $many[-1]->{email} = 'user1@example.com';    # a duplicate, in the last row

    # fails, and no row went in, not even the first statement's
    my $ok = eval { $orm->insert_many(users => \@many); 1 };

Each statement holds as many rows as the dialect's C<bind_limit> allows (65535
binds on PostgreSQL, and L<DBIx::QuickORM::Manual::Dialects/BULK INSERTS>
lists the others). More than one statement runs in a transaction of its own
(L<DBIx::QuickORM::Manual::Transactions>).

Inside an open transaction C<insert_many> always takes a savepoint, so a
failure undoes only its own rows and leaves your transaction usable. DuckDB
has no savepoints: there a failure inside your transaction is not undone by
itself, so roll the transaction back.

=head1 WITHOUT RETURNING (MySQL)

    # on MySQL every row must carry its whole primary key
    my $rows = $orm->insert_many(
        users => [
            {
                id   => 1,
                name => 'A',
            },
            {
                id   => 2,
                name => 'B',
            },
        ],
    );

    # on MySQL the row holds only its key, and fetches the rest when read
    my $name = $rows->[0]->field('name');

MySQL cannot return the rows it inserted, so there C<insert_many> gives rows
holding only their primary keys (L<DBIx::QuickORM::Manual::Dialects/RETURNING>).
Reading another field of such a row fetches it from the database.

Every key must be given, or generated by its type before the insert (a UUID
key is, see L<DBIx::QuickORM::Manual::Keys>). A row without its whole key, or
a table without a primary key, croaks before anything is sent. Pass
C<< count => 1 >>, or call it in void context, to insert such rows.

MariaDB, PostgreSQL, SQLite, and DuckDB return whole rows, with the keys they
generated.

=cut

